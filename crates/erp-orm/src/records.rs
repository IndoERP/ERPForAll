/// An untyped recordset.
#[derive(Clone)]
pub struct Records {
    env: Env,
    model: ModelId,
    ids: Ids,
    prefetch: Ids,
}

fn dedup_first(ids: impl IntoIterator<Item = RecId>) -> Vec<RecId> {
    let mut seen = FxHashSet::default();
    ids.into_iter().filter(|id| seen.insert(*id)).collect()
}

fn union_prefetch(sets: &[&Ids]) -> Ids {
    dedup_first(sets.iter().flat_map(|s| s.iter().copied())).into()
}

impl Records {
    pub(crate) fn empty(env: Env, model: ModelId) -> Self {
        let ids: Ids = Arc::from(Vec::new());
        Self {
            env,
            model,
            prefetch: Arc::clone(&ids),
            ids,
        }
    }

    pub(crate) fn from_parts(env: Env, model: ModelId, ids: Ids, prefetch: Ids) -> Self {
        Self {
            env,
            model,
            ids,
            prefetch,
        }
    }

    /// The environment.
    pub fn env(&self) -> &Env {
        &self.env
    }

    /// The model id.
    pub fn model_id(&self) -> ModelId {
        self.model
    }

    /// The model's metadata.
    pub fn spec(&self) -> &ModelSpec {
        self.env.registry().model_by_id(self.model)
    }

    /// `_name`.
    pub fn model_name(&self) -> &'static str {
        self.spec().name
    }

    /// `browse(ids)`: a recordset of these database ids, order and duplicates kept, no SQL.
    pub fn browse(&self, ids: impl IntoIterator<Item = i64>) -> Result<Self> {
        let ids: Vec<RecId> = ids
            .into_iter()
            .map(|i| match i {
                0 => Err(Error::programming("Invalid falsy real id")),
                i => RecId::from_real(i).ok_or_else(|| {
                    Error::programming(format!("Invalid real id {i}: database ids are positive"))
                }),
            })
            .collect::<Result<_>>()?;
        Ok(self.browse_ids(ids))
    }

    /// `browse` with record ids.
    pub fn browse_ids(&self, ids: impl IntoIterator<Item = RecId>) -> Self {
        let ids: Ids = ids.into_iter().collect::<Vec<_>>().into();
        Self {
            env: self.env.clone(),
            model: self.model,
            prefetch: Arc::clone(&ids),
            ids,
        }
    }

    /// The raw id tuple (`_ids`).
    pub fn rec_ids(&self) -> &[RecId] {
        &self.ids
    }

    /// The shared id list itself (an identity for caches keyed on this recordset's ids, such as
    /// a read level's slots: holding a clone keeps the list alive and unchanged).
    pub(crate) fn shared_ids(&self) -> &Ids {
        &self.ids
    }

    /// The prefetch set.
    pub fn prefetch_ids(&self) -> &[RecId] {
        &self.prefetch
    }

    /// `ids`: database ids in order, duplicates kept; new records give their origin's id, new
    /// records without origin are skipped.
    pub fn ids(&self) -> Vec<i64> {
        self.ids
            .iter()
            .filter_map(|id| id.as_real().or(id.origin()))
            .map(|id| id.get())
            .collect()
    }

    /// `_origin`: database records as themselves, new records as their origin; new records
    /// without origin are dropped (ENV §4.9).
    pub fn origin(&self) -> Self {
        let ids: Vec<RecId> = self
            .ids
            .iter()
            .filter_map(|id| id.as_real().or(id.origin()))
            .map(RecId::real)
            .collect();
        let prefetch: Vec<RecId> = self
            .prefetch
            .iter()
            .filter_map(|id| id.as_real().or(id.origin()))
            .map(RecId::real)
            .collect();
        self.with_ids(ids, prefetch.into())
    }

    /// Number of ids, duplicates included.
    pub fn len(&self) -> usize {
        self.ids.len()
    }

    /// No ids.
    pub fn is_empty(&self) -> bool {
        self.ids.is_empty()
    }

    fn singleton_error(&self) -> Error {
        Error::programming(format!("Expected singleton: {self}"))
    }

    /// `ensure_one()`.
    pub fn ensure_one(&self) -> Result<&Self> {
        if self.ids.len() == 1 {
            Ok(self)
        } else {
            Err(self.singleton_error())
        }
    }

    /// `record.id`: `None` on an empty set, the id of a singleton, the singleton error otherwise.
    pub fn id(&self) -> Result<Option<RecId>> {
        match self.ids.len() {
            0 => Ok(None),
            1 => Ok(Some(self.ids[0])),
            _ => Err(self.singleton_error()),
        }
    }

    /// `int(record)`: 0 for an empty set.
    pub fn int(&self) -> Result<i64> {
        Ok(self.id()?.map_or(0, RecId::get))
    }

    fn with_ids(&self, ids: Vec<RecId>, prefetch: Ids) -> Self {
        Self {
            env: self.env.clone(),
            model: self.model,
            ids: ids.into(),
            prefetch,
        }
    }

    /// Other ids of the same model and environment sharing this set's prefetch set (results of
    /// `filtered`, `sorted`, `grouped`, RSET §4.1).
    pub(crate) fn derive(&self, ids: Vec<RecId>) -> Self {
        self.with_ids(ids, Arc::clone(&self.prefetch))
    }

    fn single(&self, id: RecId) -> Self {
        Self {
            env: self.env.clone(),
            model: self.model,
            ids: Arc::from([id]),
            prefetch: Arc::clone(&self.prefetch),
        }
    }

    /// Singleton recordsets in order, sharing this set's environment and prefetch set.
    pub fn iter(&self) -> impl DoubleEndedIterator<Item = Self> + ExactSizeIterator + '_ {
        self.ids.iter().map(move |id| self.single(*id))
    }

    /// `records[i]`; negative indexes count from the end.
    pub fn at(&self, index: isize) -> Result<Self> {
        let len = self.ids.len() as isize;
        let i = if index < 0 { len + index } else { index };
        if i < 0 || i >= len {
            return Err(Error::programming("tuple index out of range"));
        }
        Ok(self.single(self.ids[i as usize]))
    }

    /// `records[start:stop:step]` with Python slice semantics.
    pub fn slice(&self, start: Option<isize>, stop: Option<isize>, step: isize) -> Result<Self> {
        if step == 0 {
            return Err(Error::programming("slice step cannot be zero"));
        }
        let len = self.ids.len() as isize;
        let clamp = |v: isize, lo: isize, hi: isize| v.max(lo).min(hi);
        let norm = |v: isize| if v < 0 { v + len } else { v };
        let mut out = Vec::new();
        if step > 0 {
            let start = clamp(start.map_or(0, norm), 0, len);
            let stop = clamp(stop.map_or(len, norm), 0, len);
            let mut i = start;
            while i < stop {
                out.push(self.ids[i as usize]);
                i += step;
            }
        } else {
            let start = clamp(start.map_or(len - 1, norm), -1, len - 1);
            let stop = clamp(stop.map_or(-1, norm), -1, len - 1);
            let mut i = start;
            while i > stop {
                out.push(self.ids[i as usize]);
                i += step;
            }
        }
        let prefetch = union_prefetch(&[&Ids::from(out.clone()), &self.prefetch]);
        Ok(self.with_ids(out, prefetch))
    }

    /// The same model of the same registry (models compare by registry identity and id, so two
    /// registries' models of one name are different models).
    fn same_model(&self, other: &Self) -> bool {
        self.model == other.model && Arc::ptr_eq(self.env.registry(), other.env.registry())
    }

    fn check_same_model(&self, other: &Self, op: &str) -> Result<()> {
        if self.same_model(other) {
            Ok(())
        } else {
            Err(Error::programming(format!(
                "inconsistent models in: {self} {op} {other}"
            )))
        }
    }

    /// `a + b`: concatenation, duplicates kept.
    pub fn concat(&self, other: &Self) -> Result<Self> {
        self.check_same_model(other, "+")?;
        if other.is_empty() {
            return Ok(self.clone());
        }
        let ids: Vec<RecId> = self.ids.iter().chain(other.ids.iter()).copied().collect();
        let prefetch = union_prefetch(&[&Ids::from(ids.clone()), &self.prefetch, &other.prefetch]);
        Ok(self.with_ids(ids, prefetch))
    }

    /// `a | b`: union in first-occurrence order; `a` unchanged when `b` is empty.
    pub fn union(&self, other: &Self) -> Result<Self> {
        self.check_same_model(other, "|")?;
        if other.is_empty() {
            return Ok(self.clone());
        }
        let ids = dedup_first(self.ids.iter().chain(other.ids.iter()).copied());
        let prefetch = union_prefetch(&[&Ids::from(ids.clone()), &self.prefetch, &other.prefetch]);
        Ok(self.with_ids(ids, prefetch))
    }

    /// `a & b`: ids of `a` in `b`, de-duplicated, in `a`'s order.
    pub fn intersection(&self, other: &Self) -> Result<Self> {
        self.check_same_model(other, "&")?;
        let theirs: FxHashSet<RecId> = other.ids.iter().copied().collect();
        let ids = dedup_first(self.ids.iter().copied().filter(|id| theirs.contains(id)));
        let prefetch = union_prefetch(&[&Ids::from(ids.clone()), &self.prefetch]);
        Ok(self.with_ids(ids, prefetch))
    }

    /// `a - b`: ids of `a` not in `b`, `a`'s duplicates kept.
    pub fn difference(&self, other: &Self) -> Result<Self> {
        self.check_same_model(other, "-")?;
        let theirs: FxHashSet<RecId> = other.ids.iter().copied().collect();
        let ids: Vec<RecId> = self
            .ids
            .iter()
            .copied()
            .filter(|id| !theirs.contains(id))
            .collect();
        let prefetch = union_prefetch(&[&Ids::from(ids.clone()), &self.prefetch]);
        Ok(self.with_ids(ids, prefetch))
    }

    /// `Model.concat(iterable)` on an empty recordset; empty members are skipped.
    pub fn concat_all<'a>(&self, sets: impl IntoIterator<Item = &'a Self>) -> Result<Self> {
        let mut ids: Vec<RecId> = self.ids.to_vec();
        let mut prefetch: Vec<&Ids> = vec![&self.prefetch];
        for s in sets {
            self.check_same_model(s, "+")?;
            ids.extend(s.ids.iter().copied());
            prefetch.push(&s.prefetch);
        }
        let ids_arc = Ids::from(ids.clone());
        prefetch.insert(0, &ids_arc);
        let prefetch = union_prefetch(&prefetch);
        Ok(self.with_ids(ids, prefetch))
    }

    /// `Model.union(iterable)`: de-duplicated even with one member.
    pub fn union_all<'a>(&self, sets: impl IntoIterator<Item = &'a Self>) -> Result<Self> {
        let all = self.concat_all(sets)?;
        let ids = dedup_first(all.ids.iter().copied());
        Ok(self.with_ids(ids, Arc::clone(&all.prefetch)))
    }

    /// `item in records` for a recordset item: true iff `item` is a singleton whose id is here; a
    /// recordset of another model is an error.
    pub fn contains(&self, item: &Self) -> Result<bool> {
        if !self.same_model(item) {
            return Err(Error::programming(format!(
                "inconsistent models in: {item} in {self}"
            )));
        }
        Ok(item.ids.len() == 1 && self.ids.contains(&item.ids[0]))
    }

    /// `'field' in records`: the model has a field of that name.
    pub fn has_field(&self, name: &str) -> bool {
        self.spec().field(name).is_some()
    }

    /// `a <= b`: subset.
    pub fn is_subset(&self, other: &Self) -> Result<bool> {
        self.check_same_model(other, "<=")?;
        let theirs: FxHashSet<RecId> = other.ids.iter().copied().collect();
        Ok(self.ids.iter().all(|id| theirs.contains(id)))
    }

    /// `a < b`: strict subset.
    pub fn is_strict_subset(&self, other: &Self) -> Result<bool> {
        Ok(self.is_subset(other)? && !other.is_subset(self)?)
    }

    fn id_set(&self) -> FxHashSet<RecId> {
        self.ids.iter().copied().collect()
    }

    /// Same ids on another environment.
    #[must_use]
    pub fn with_env(&self, env: Env) -> Self {
        Self {
            env,
            model: self.model,
            ids: Arc::clone(&self.ids),
            prefetch: Arc::clone(&self.prefetch),
        }
    }

    /// `sudo(flag)`. On records of an elevation block, turning superuser mode on
    /// gives records whose every use is refused ([`Env::sudo`]).
    #[must_use]
    pub fn sudo(&self, flag: bool) -> Self {
        self.with_env(self.env.sudo(flag))
    }

    /// The engine's own superuser mode ([`Env::engine_sudo`]): keeps an elevation block's
    /// lifetime instead of being refused.
    #[must_use]
    pub(crate) fn engine_sudo(&self) -> Self {
        self.with_env(self.env.engine_sudo())
    }

    /// `with_user(uid)`.
    #[must_use]
    pub fn with_user(&self, uid: impl Into<i64>) -> Self {
        self.with_env(self.env.with_user(uid))
    }

    /// `with_context(**kw)`.
    #[must_use]
    pub fn with_context<K: Into<String>>(
        &self,
        updates: impl IntoIterator<Item = (K, erp_fields::Value)>,
    ) -> Self {
        self.with_env(self.env.with_context(updates))
    }

    /// `with_prefetch(ids)`: another prefetch set (`None`: its own ids).
    #[must_use]
    pub fn with_prefetch(&self, prefetch: Option<Ids>) -> Self {
        Self {
            env: self.env.clone(),
            model: self.model,
            ids: Arc::clone(&self.ids),
            prefetch: prefetch.unwrap_or_else(|| Arc::clone(&self.ids)),
        }
    }
}

impl PartialEq for Records {
    /// Same model and same *set* of ids; order, duplicates and environment are ignored.
    fn eq(&self, other: &Self) -> bool {
        self.same_model(other) && self.id_set() == other.id_set()
    }
}

impl Eq for Records {}

impl Hash for Records {
    fn hash<H: Hasher>(&self, state: &mut H) {
        self.model_name().hash(state);
        let mut ids: Vec<RecId> = self.id_set().into_iter().collect();
        ids.sort_unstable();
        ids.hash(state);
    }
}

impl fmt::Display for Records {
    /// `model(1, 2)`, `model(1,)`, `model()`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{}(", self.model_name())?;
        for (i, id) in self.ids.iter().enumerate() {
            if i > 0 {
                f.write_str(", ")?;
            }
            write!(f, "{id}")?;
        }
        if self.ids.len() == 1 {
            f.write_str(",")?;
        }
        f.write_str(")")
    }
}

impl fmt::Debug for Records {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        fmt::Display::fmt(self, f)
    }
}

/// A recordset of model `M` (or of a model inheriting `M`).
pub struct RecordSet<M> {
    records: Records,
    _m: PhantomData<fn() -> M>,
}

impl<M> Clone for RecordSet<M> {
    fn clone(&self) -> Self {
        Self {
            records: self.records.clone(),
            _m: PhantomData,
        }
    }
}

impl<M: Model> TryFrom<Records> for RecordSet<M> {
    type Error = Error;

    /// Checked: the records' model must be `M` or inherit it.
    fn try_from(records: Records) -> Result<Self> {
        if records.spec().inherits(M::MODEL_NAME) {
            Ok(Self::unchecked(records))
        } else {
            Err(Error::programming(format!(
                "{records} is not a recordset of '{}' or of a model inheriting it",
                M::MODEL_NAME
            )))
        }
    }
}

impl<M: Model> RecordSet<M> {
    /// Only for paths that already proved the model (registry lookup by `M::MODEL_NAME`).
    pub(crate) fn unchecked(records: Records) -> Self {
        Self {
            records,
            _m: PhantomData,
        }
    }

    /// The untyped recordset.
    pub fn as_records(&self) -> &Records {
        &self.records
    }

    /// Into the untyped recordset.
    pub fn into_records(self) -> Records {
        self.records
    }

    /// `fields.Date.context_today(record)`: today's date in the time zone of this recordset's
    /// environment (its context `tz`, else UTC). Takes the transaction only so that the same call
    /// compiles in a WebAssembly component, where the zone comes from the call context.
    ///
    /// # Errors
    ///
    /// `Internal` when the environment's zone is not a known one (it resolved to a name the clock
    /// database does not have, which `Env::tz` rules out).
    pub fn context_today(&self, _tx: &crate::Transaction) -> Result<erp_fields::Date> {
        self.env().context_today()
    }

    /// Typed values for `create`/`write` on this model: only field handles of `M` and of the
    /// models it inherits are accepted.
    pub fn vals(&self) -> crate::Vals<M> {
        crate::Vals::new()
    }

    fn wrap(&self, records: Records) -> Self {
        Self::unchecked(records)
    }

    /// `browse(ids)` (/002).
    pub fn browse(&self, ids: impl IntoIterator<Item = i64>) -> Result<Self> {
        Ok(self.wrap(self.records.browse(ids)?))
    }

    /// Singleton recordsets in order.
    pub fn iter(&self) -> impl DoubleEndedIterator<Item = Self> + ExactSizeIterator + '_ {
        self.records.iter().map(Self::unchecked)
    }

    /// `records[i]`.
    pub fn at(&self, index: isize) -> Result<Self> {
        Ok(self.wrap(self.records.at(index)?))
    }

    /// `records[start:stop:step]`.
    pub fn slice(&self, start: Option<isize>, stop: Option<isize>, step: isize) -> Result<Self> {
        Ok(self.wrap(self.records.slice(start, stop, step)?))
    }

    /// `ensure_one()`: this recordset when it is a singleton.
    pub fn ensure_one(&self) -> Result<&Self> {
        self.records.ensure_one()?;
        Ok(self)
    }

    // Set operations return errors instead of guessing: a `RecordSet<M>` may hold a child model's
    // records, so two typed sets are not necessarily of the same model.

    /// `a + b`.
    pub fn concat(&self, other: &Self) -> Result<Self> {
        Ok(self.wrap(self.records.concat(&other.records)?))
    }

    /// `a | b`.
    pub fn union(&self, other: &Self) -> Result<Self> {
        Ok(self.wrap(self.records.union(&other.records)?))
    }

    /// `a & b`.
    pub fn intersection(&self, other: &Self) -> Result<Self> {
        Ok(self.wrap(self.records.intersection(&other.records)?))
    }

    /// `a - b`.
    pub fn difference(&self, other: &Self) -> Result<Self> {
        Ok(self.wrap(self.records.difference(&other.records)?))
    }

    /// `Model.concat(iterable)`.
    pub fn concat_all<'a>(&self, sets: impl IntoIterator<Item = &'a Self>) -> Result<Self> {
        let sets: Vec<&Records> = sets.into_iter().map(|s| &s.records).collect();
        Ok(self.wrap(self.records.concat_all(sets)?))
    }

    /// `Model.union(iterable)`.
    pub fn union_all<'a>(&self, sets: impl IntoIterator<Item = &'a Self>) -> Result<Self> {
        let sets: Vec<&Records> = sets.into_iter().map(|s| &s.records).collect();
        Ok(self.wrap(self.records.union_all(sets)?))
    }

    /// `item in records` (a singleton of the same model).
    pub fn contains(&self, item: &Self) -> Result<bool> {
        self.records.contains(&item.records)
    }

    /// `a <= b`.
    pub fn is_subset(&self, other: &Self) -> Result<bool> {
        self.records.is_subset(&other.records)
    }

    /// `a < b`.
    pub fn is_strict_subset(&self, other: &Self) -> Result<bool> {
        self.records.is_strict_subset(&other.records)
    }

    /// `sudo(flag)`.
    #[must_use]
    pub fn sudo(&self, flag: bool) -> Self {
        self.wrap(self.records.sudo(flag))
    }

    /// `with_user(uid)`.
    #[must_use]
    pub fn with_user(&self, uid: impl Into<i64>) -> Self {
        self.wrap(self.records.with_user(uid))
    }

    /// `with_context(**kw)`.
    #[must_use]
    pub fn with_context<K: Into<String>>(
        &self,
        updates: impl IntoIterator<Item = (K, erp_fields::Value)>,
    ) -> Self {
        self.wrap(self.records.with_context(updates))
    }

    /// Same ids on another environment.
    #[must_use]
    pub fn with_env(&self, env: Env) -> Self {
        self.wrap(self.records.with_env(env))
    }

    /// `with_prefetch(ids)`.
    #[must_use]
    pub fn with_prefetch(&self, prefetch: Option<Ids>) -> Self {
        self.wrap(self.records.with_prefetch(prefetch))
    }

    /// A field value of a singleton; the type's null value on an empty set; the singleton error on
    /// several records (/010).
    pub async fn get<P: Model, T: FieldValue>(
        &self,
        tx: &mut crate::Transaction,
        field: Field<P, T>,
    ) -> Result<T>
    where
        M: Inherits<P>,
    {
        let cell = self.records.cell(tx, field.name()).await?;
        T::from_cell(&cell)
    }

    /// `mapped(field)` for a scalar field: one value per record, in order (one query at most per
    /// prefetch chunk).
    pub async fn mapped<P: Model, T: FieldValue>(
        &self,
        tx: &mut crate::Transaction,
        field: Field<P, T>,
    ) -> Result<Vec<T>>
    where
        M: Inherits<P>,
    {
        self.records
            .cells(tx, field.name())
            .await?
            .iter()
            .map(T::from_cell)
            .collect()
    }

    /// `create(vals_list)` through the method chain.
    pub async fn create(
        &self,
        tx: &mut crate::Transaction,
        vals_list: Vec<crate::Vals<M>>,
    ) -> Result<Self> {
        let raw: Vec<RawVals> = vals_list.into_iter().map(crate::Vals::into_raw).collect();
        let created = self.records.create(tx, raw).await?;
        Self::try_from(created)
    }

    /// `new(vals)`: an in-memory record (ENV §4.9).
    pub async fn new_record(
        &self,
        tx: &mut crate::Transaction,
        vals: crate::Vals<M>,
    ) -> Result<Self> {
        self.new_with(tx, vals, None, None).await
    }

    /// `new(vals, origin=..., ref=...)`: new records of the same origin, or of the same
    /// reference, are the same record.
    pub async fn new_with(
        &self,
        tx: &mut crate::Transaction,
        vals: crate::Vals<M>,
        origin: Option<&Self>,
        reference: Option<&str>,
    ) -> Result<Self> {
        let origin = match origin {
            Some(o) => Some(o.ensure_one()?.rec_ids()[0]),
            None => None,
        };
        let records = tx
            .new_record(&self.records, vals.into_raw(), origin, reference)
            .await?;
        Ok(self.wrap(records))
    }

    /// `_origin`.
    pub fn origin(&self) -> Self {
        self.wrap(self.records.origin())
    }

    /// `write(vals)` through the method chain.
    pub async fn write(&self, tx: &mut crate::Transaction, vals: crate::Vals<M>) -> Result<()> {
        self.records.write(tx, vals.into_raw()).await
    }

    /// Assign one field on every record (`records.field = value`), which is one `write` call on the
    /// whole set for real records. `id` cannot be assigned.
    pub async fn set<P: Model, T: FieldValue, V: IntoFieldValue<T>>(
        &self,
        tx: &mut crate::Transaction,
        field: Field<P, T>,
        value: V,
    ) -> Result<()>
    where
        M: Inherits<P>,
    {
        if field.name() == "id" {
            return Err(Error::programming("field 'id' cannot be assigned"));
        }
        self.write(tx, self.vals().set(field, value)).await
    }
}

