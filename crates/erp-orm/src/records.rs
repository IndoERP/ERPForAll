//! Recordsets (RSET §4.1–4.6): an environment, a model, an immutable id tuple and a prefetch set.
//!
//! [`Records`] is the untyped form used by the dynamic surface and by method dispatch;
//! [`RecordSet<M>`] holds records of model `M` or of a model inheriting `M` (a child model's records
//! seen through a parent's method, like `self` in an inherited Python method). Typed recordsets are
//! only built through checked paths ([`TryFrom<Records>`], [`crate::Env::model`]), so field handles
//! of `M` always resolve on them. The container and set operations never touch the database and
//! are final.

