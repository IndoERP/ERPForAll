use std::hash::{Hash, Hasher};
use std::marker::PhantomData;
use std::ops::Deref;
use std::sync::Arc;

use erp_fields::{Error, FieldValue, IntoFieldValue, RecId, Result};
use erp_registry::{ModelId, ModelKind, ModelSpec};
use rustc_hash::FxHashSet;

use crate::env::Env;
use crate::vals::RawVals;

/// Ids of a recordset; cheap to clone.
pub type Ids = Arc<[RecId]>;

/// Proof that an item was generated by the ERPForAll macros (field handles, `Inherits` impls).
/// Not part of the public API: addon code never names it.
#[doc(hidden)]
#[derive(Debug, Clone, Copy)]
pub struct Token {
    _private: (),
}

impl Token {
    /// For macro output only.
    #[doc(hidden)]
    pub const fn __macro() -> Self {
        Self { _private: () }
    }
}

/// A model known at compile time (generated by `#[model]`).
pub trait Model: 'static + Send + Sync {
    /// `_name`.
    const MODEL_NAME: &'static str;
    /// The model class kind (extensions must match it, MODEL-009).
    const KIND: ModelKind;
}

/// `M: Inherits<P>` lets recordsets of `M` use fields and methods of `P` (`_inherit`). Implemented
/// by `#[model]` output only (it must supply the macro token).
pub trait Inherits<P: Model>: Model {
    /// Macro token; see [`Token`].
    #[doc(hidden)]
    const __TOKEN: Token;
}

