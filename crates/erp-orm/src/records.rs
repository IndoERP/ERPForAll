/// Use the `Result`-returning methods to handle it.
macro_rules! set_op {
    ($trait:ident, $method:ident, $impl:ident) => {
        impl<M: Model> std::ops::$trait<&RecordSet<M>> for &RecordSet<M> {
            type Output = RecordSet<M>;
            #[allow(
                clippy::panic,
                reason = "operator form of a TypeError; methods return Result"
            )]
            fn $method(self, rhs: &RecordSet<M>) -> RecordSet<M> {
                match self.$impl(rhs) {
                    Ok(records) => records,
                    Err(e) => panic!("{e}"),
                }
            }
        }
    };
}

