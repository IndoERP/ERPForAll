/// A typed handle to a field of model `M` holding values of type `T`.
pub struct Field<M, T> {
    name: &'static str,
    _p: PhantomData<fn() -> (M, T)>,
}

impl<M, T> Field<M, T> {
    /// A handle for the field named `name`; generated by `#[model]`/`#[extend]` (needs the macro
    /// token).
    #[doc(hidden)]
    pub const fn new(name: &'static str, _token: Token) -> Self {
        Self {
            name,
            _p: PhantomData,
        }
    }

    /// The field name.
    pub const fn name(&self) -> &'static str {
        self.name
    }
}

impl<M, T> Clone for Field<M, T> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<M, T> Copy for Field<M, T> {}

impl<M, T> fmt::Debug for Field<M, T> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "Field({})", self.name)
    }
}

