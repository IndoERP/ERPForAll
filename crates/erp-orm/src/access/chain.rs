//! The bottom of every chain is the
//! combined domain the policy computed (permissions, grants, restrictions, `_inherits` parents),
//! so an override narrows or widens it through [`AccessSuper::call`].
//!
//! Overrides are synchronous and see an [`AccessCtx`] only (no principal values, no I/O): the
//! policy snapshot runs the chain while it compiles, and the result is memoized by the memo key.

use std::sync::Arc;

use erp_domain::Domain;
use erp_fields::{Error, Result};
use erp_registry::{ModelId, Registry};
use rustc_hash::{FxHashMap, FxHashSet};

use super::Operation;
use super::ctx::AccessCtx;

/// The signature of an `#[access_domain]` method.
pub type AccessDomainFn = fn(&AccessCtx<'_>, Operation, AccessSuper<'_>) -> Result<Domain>;

/// One `#[access_domain]` override contributed by an addon (generated by the macro; tests build
/// them at runtime).
#[derive(Debug)]
pub struct AccessDomainImpl {
    /// Contributing addon.
    pub addon: &'static str,
    /// Model of the declaration it belongs to.
    pub model: &'static str,
    /// The override.
    pub func: AccessDomainFn,
    /// Source file.
    pub file: &'static str,
    /// Source line.
    pub line: u32,
}

impl AccessDomainImpl {
    fn location(&self) -> String {
        format!("{}:{} (addon '{}')", self.file, self.line, self.addon)
    }
}

/// `#[access_domain]` overrides linked into the binary.
#[linkme::distributed_slice]
pub static ACCESS_DOMAIN_IMPLS: [AccessDomainImpl];

/// `super` of an `#[access_domain]` override: the rest of the chain, ending at the combined
/// domain.
#[derive(Clone, Copy)]
pub struct AccessSuper<'a> {
    rest: &'a [&'static AccessDomainImpl],
    base: &'a Domain,
}

impl AccessSuper<'_> {
    /// The domain of the rest of the chain.
    ///
    /// # Errors
    ///
    /// The error of an override further down.
    pub fn call(self, ctx: &AccessCtx<'_>, op: Operation) -> Result<Domain> {
        match self.rest.split_first() {
            Some((first, rest)) => (first.func)(
                ctx,
                op,
                AccessSuper {
                    rest,
                    base: self.base,
                },
            ),
            None => Ok(self.base.clone()),
        }
    }
}

impl std::fmt::Debug for AccessSuper<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("AccessSuper")
            .field("remaining", &self.rest.len())
            .finish_non_exhaustive()
    }
}

/// The `#[access_domain]` chains of one registry.
#[derive(Debug, Default)]
pub struct AccessDomainChains {
    chains: FxHashMap<ModelId, Arc<[&'static AccessDomainImpl]>>,
}

impl AccessDomainChains {
    /// Build the chains from the linked overrides plus `extra` (runtime-built, tests). Only
    /// overrides of installed addons take part.
    ///
    /// # Errors
    ///
    /// `Programming` (naming the source location) when an addon overrides one model twice, or
    /// when an override's addon has no declaration of its model (add an `#[extend]` for it).
    pub fn build(registry: &Registry, extra: &[&'static AccessDomainImpl]) -> Result<Self> {
        let installed: FxHashSet<&str> = registry.addons().iter().map(|a| a.name).collect();
        let mut by_owner: FxHashMap<(&str, &str), &'static AccessDomainImpl> = FxHashMap::default();
        let mut all: Vec<&'static AccessDomainImpl> = ACCESS_DOMAIN_IMPLS
            .iter()
            .chain(extra.iter().copied())
            .filter(|i| installed.contains(i.addon))
            .collect();
        // deterministic: the first error reported is always the same one
        all.sort_by_key(|i| (i.model, i.addon, i.file, i.line));
        for imp in all {
            if let Some(previous) = by_owner.insert((imp.model, imp.addon), imp) {
                return Err(Error::programming(format!(
                    "#[access_domain] of model '{}' is implemented twice by addon '{}': {} and {}",
                    imp.model,
                    imp.addon,
                    previous.location(),
                    imp.location()
                )));
            }
        }
        let declared: FxHashSet<(&str, &str)> = registry
            .models()
            .iter()
            .flat_map(|m| m.mro.iter().map(|d| (d.name, d.addon)))
            .collect();
        let mut owners: Vec<(&str, &str)> = by_owner.keys().copied().collect();
        owners.sort_unstable();
        if let Some(imp) = owners
            .iter()
            .find(|owner| !declared.contains(owner))
            .and_then(|owner| by_owner.get(owner))
        {
            return Err(Error::programming(format!(
                "#[access_domain] at {} has no declaration of model '{}' in addon '{}': add an \
                 #[extend] (or #[model]) for it in that addon",
                imp.location(),
                imp.model,
                imp.addon
            )));
        }
        let mut chains = FxHashMap::default();
        for model in registry.models() {
            let mut chain: Vec<&'static AccessDomainImpl> = Vec::new();
            for decl in &model.mro {
                if let Some(imp) = by_owner.get(&(decl.name, decl.addon))
                    && !chain.iter().any(|c| std::ptr::eq(*c, *imp))
                {
                    chain.push(imp);
                }
            }
            if !chain.is_empty() {
                chains.insert(model.id, Arc::from(chain));
            }
        }
        Ok(Self { chains })
    }

    /// Whether `model` has overrides.
    pub fn has_overrides(&self, model: ModelId) -> bool {
        self.chains.contains_key(&model)
    }

    /// Run `ctx.model()`'s chain on the combined domain `base` (`base` itself without
    /// overrides).
    ///
    /// # Errors
    ///
    /// An override's error, which denies the operation with it.
    pub fn apply(&self, ctx: &AccessCtx<'_>, op: Operation, base: &Domain) -> Result<Domain> {
        match self.chains.get(&ctx.model().id) {
            Some(chain) => AccessSuper { rest: chain, base }.call(ctx, op),
            None => Ok(base.clone()),
        }
    }
}
