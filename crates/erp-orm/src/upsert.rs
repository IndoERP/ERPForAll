/// What one merged row became.
#[derive(Debug, Clone)]
struct RowOutcome {
    id: RecId,
    outcome: UpsertOutcome,
    previous_version: Option<i64>,
    version: Option<i64>,
    /// New values of the accumulated fields, in plan order.
    accumulated: Vec<Cell>,
    /// Stored new values of [`Shape::new_fields`], beyond the accumulated ones.
    stored: Vec<Cell>,
    /// Old values of [`Shape::old_fields`] (NULL unless updated).
    old: Vec<Cell>,
    /// Actual physical business changes from the database projection.
    changed: Vec<FieldId>,
}

/// The statement of a call and what its result columns mean.
struct Shape {
    sql: String,
    /// The key columns as the pre-check matches them.
    key: Vec<(&'static str, bool)>,
    /// `create_uid`/`write_uid` are inserted from a bound uid.
    uid: bool,
    /// Floors, bound after the uid, in plan order of the floored fields.
    floors: Vec<Cell>,
    /// Fields whose old values the statement returns (write hooks, inverses of many2one updates).
    old_fields: Vec<FieldId>,
    /// Fields whose stored new values the statement returns: the accumulated fields (plan
    /// order), then the tracked overwritten columns.
    new_fields: Vec<FieldId>,
    changed_fields: Vec<FieldId>,
    create_fields: Vec<FieldId>,
}

fn column_type(spec: &ModelSpec, field: FieldId) -> Result<ColumnType> {
    let fs = spec.field_by_id(field);
    fs.column()
        .ok_or_else(|| upsert_error(spec, format!("field '{}' has no column", fs.name)))
}

fn shape(tx: &Transaction, spec: &ModelSpec, plan: &Plan<'_>, batch: &Batch) -> Result<Shape> {
    let mut columns: Vec<(&str, ColumnType)> = Vec::with_capacity(batch.columns.len());
    for f in &batch.columns {
        columns.push((spec.field_by_id(*f).name, column_type(spec, *f)?));
    }
    let key: Vec<(&'static str, bool)> = plan
        .key
        .fields
        .iter()
        .map(|f| {
            let fs = spec.field_by_id(*f);
            (fs.name, !fs.required)
        })
        .collect();
    let key_columns: Vec<KeyColumn<'_>> = key
        .iter()
        .map(|(name, nullable)| KeyColumn {
            name,
            nullable: *nullable,
        })
        .collect();
    let mut next = columns.len() + 1;
    let audit_uid: Vec<&str> = ["create_uid", "write_uid"]
        .into_iter()
        .filter(|n| spec.log_access && spec.field(n).is_some())
        .collect();
    let uid_param = format!("${next}::int8");
    let uid = !audit_uid.is_empty();
    if uid {
        next += 1;
    }
    let mut insert_exprs: Vec<(&str, &str)> =
        audit_uid.iter().map(|n| (*n, uid_param.as_str())).collect();
    for n in ["create_date", "write_date"] {
        if spec.log_access && spec.field(n).is_some() {
            insert_exprs.push((n, erp_sql::NOW_UTC));
        }
    }
    if spec.row_version.is_some() {
        insert_exprs.push((erp_registry::ROW_VERSION, "1"));
    }
    let mut sets: Vec<(&str, SetAction)> = Vec::new();
    for f in &plan.update {
        sets.push((spec.field_by_id(*f).name, SetAction::Overwrite));
    }
    let mut floors = Vec::new();
    for (f, floor) in &plan.accumulate {
        let action = match floor {
            None => SetAction::Accumulate,
            Some(cell) => {
                let action = SetAction::AccumulateFloor {
                    param: next,
                    ty: column_type(spec, *f)?,
                };
                next += 1;
                floors.push(cell.clone());
                action
            }
        };
        sets.push((spec.field_by_id(*f).name, action));
    }
    let audit: Vec<&str> = ["write_uid", "write_date"]
        .into_iter()
        .filter(|n| spec.log_access && spec.field(n).is_some())
        .collect();
    let action = if plan.is_update() {
        ConflictAction::Update {
            sets: &sets,
            audit: &audit,
        }
    } else {
        ConflictAction::Nothing
    };
    let mut returning: Vec<(&str, ColumnType)> = Vec::new();
    let mut new_fields: Vec<FieldId> = Vec::new();
    for (f, _) in &plan.accumulate {
        returning.push((spec.field_by_id(*f).name, column_type(spec, *f)?));
        new_fields.push(*f);
    }
    // old values: fields write hooks name, many2one updates whose inverses may be cached
    let mut old_fields: Vec<FieldId> = Vec::new();
    if plan.is_update() {
        let written: Vec<FieldId> = plan
            .update
            .iter()
            .copied()
            .chain(plan.accumulate.iter().map(|(f, _)| *f))
            .collect();
        for hook in tx.shared.write_hooks.of(spec.id) {
            for f in &hook.fields {
                if written.contains(f) && !old_fields.contains(f) {
                    old_fields.push(*f);
                }
            }
        }
        // tracked columns the upsert writes: an update is a tracked write
        for f in &written {
            if spec.tracked.contains(f)
                && spec.field_by_id(*f).has_column()
                && !old_fields.contains(f)
            {
                old_fields.push(*f);
            }
        }
        for f in &plan.update {
            let is_m2o = matches!(spec.field_by_id(*f).ty, FieldType::Many2one { .. });
            if is_m2o
                && !tx.shared.relations.inverses(spec.id, *f).is_empty()
                && !old_fields.contains(f)
            {
                old_fields.push(*f);
            }
        }
    }
    // stored (normalised) new values of the tracked columns this upsert overwrites
    // (r1 M2): taken from RETURNING, as the write path does
    for f in &plan.update {
        if spec.tracked.contains(f) && spec.field_by_id(*f).has_column() && !new_fields.contains(f)
        {
            returning.push((spec.field_by_id(*f).name, column_type(spec, *f)?));
            new_fields.push(*f);
        }
    }
    let mut returning_old: Vec<(&str, ColumnType)> = Vec::with_capacity(old_fields.len());
    for f in &old_fields {
        returning_old.push((spec.field_by_id(*f).name, column_type(spec, *f)?));
    }
    let mut changed_fields: Vec<FieldId> = if spec.eventful && plan.is_update() {
        plan.update
            .iter()
            .copied()
            .chain(plan.accumulate.iter().map(|(field, _)| *field))
            .chain(
                spec.fields
                    .iter()
                    .filter(|field| field.generated().is_some() && field.inherited.is_none())
                    .map(|field| field.id),
            )
            .filter(|field| {
                let field = spec.field_by_id(*field);
                field.has_column() && !field.magic && spec.row_version != Some(field.id)
            })
            .collect()
    } else {
        Vec::new()
    };
    changed_fields.sort_by_key(|field| spec.field_by_id(*field).name);
    changed_fields.dedup();
    if changed_fields.len() > erp_registry::MAX_EVENT_FIELD_NAMES {
        return Err(Error::new(
            ErrorKind::ResourceExhausted,
            format!(
                "outbox CaptureLimit: event exceeds {} changed field names",
                erp_registry::MAX_EVENT_FIELD_NAMES
            ),
        ));
    }
    let changed_names: Vec<&str> = changed_fields
        .iter()
        .map(|field| spec.field_by_id(*field).name)
        .collect();
    let mut create_fields = batch.columns.clone();
    for (name, _) in &insert_exprs {
        create_fields.push(spec.field_id(name).ok_or_else(|| {
            upsert_error(spec, format!("server-set column '{name}' has no field"))
        })?);
    }
    create_fields.sort_by_key(|field| spec.field_by_id(*field).name);
    create_fields.dedup();
    let constraint = plan.key.full_name.as_str();
    let sql = erp_sql::upsert::upsert(
        &erp_sql::upsert::Upsert::new(&spec.table, constraint, &columns, &key_columns, action)
            .insert_exprs(&insert_exprs)
            .row_version(spec.row_version.is_some())
            .returning(&returning)
            .returning_old(&returning_old)
            .returning_changed(&changed_names),
    );
    Ok(Shape {
        sql,
        key,
        uid,
        floors,
        old_fields,
        new_fields,
        changed_fields,
        create_fields,
    })
}

fn scalar_param(spec: &ModelSpec, cell: &Cell) -> Result<Box<dyn ToSql + Sync + Send>> {
    Ok(match cell {
        Cell::Int(i) => Box::new(*i),
        Cell::Float(f) => Box::new(*f),
        Cell::Decimal(d) => Box::new(*d),
        other => {
            return Err(upsert_error(
                spec,
                format!("a floor must be a number, not {other:?}"),
            ));
        }
    })
}

fn decode_error(e: tokio_postgres::Error) -> Error {
    Error::new(ErrorKind::Database, "could not decode an upsert result").with_source(e)
}

/// One chunk of a batch: the merged rows `members` of `batch`, and the statement shape.
#[derive(Clone, Copy)]
struct Chunk<'a> {
    batch: &'a Batch,
    shape: &'a Shape,
    members: &'a [usize],
}

/// Which existing rows the caller may read, as the write pre-check tells them apart.
enum Readable {
    /// Every row (superuser, or no read rule restricts the model).
    All,
    /// None: the model check refuses reads, or the read rule is constant `FALSE`.
    Nothing,
    /// The rows the read rule lets through, compiled with placeholders after the write rule's.
    Rule(Arc<crate::search::Compiled>),
}

/// The read side of the write pre-check: the model check, then the read rule with placeholders
/// numbered after the write rule's `offset` parameters.
async fn readable(tx: &mut Transaction, records: &Records, offset: usize) -> Result<Readable> {
    let env = records.env().clone();
    // a refused company context is an error, never "reads none" (review F1/S5)
    env.companies()?;
    match tx.check_model(&env, records.model_id(), Operation::Read) {
        Ok(()) => {}
        // a caller who may not read the model reads none of its rows
        Err(error) if error.kind() == ErrorKind::Access => return Ok(Readable::Nothing),
        Err(error) => return Err(error),
    }
    Ok(
        match crate::search::record_restriction_at(tx, records, Operation::Read, offset).await? {
            None => Readable::All,
            Some(rule) => match rule.constant {
                Some(true) => Readable::All,
                Some(false) => Readable::Nothing,
                None => Readable::Rule(rule),
            },
        },
    )
}

/// The `Validation` error of a key whose existing row the caller may not read: the key's
/// declared message, exactly as a `create` of that key raises it from the unique violation
/// (`dberror`), with no id, so the upsert discloses no more than `create` does (final
/// review, must 1).
fn hidden_conflict(key: &BusinessKey) -> Error {
    crate::dberror::declared_violation(key.message)
}

/// The pre-check of one chunk (design note §3.5 step 3) over the existing rows of its keys: a row
/// the write rule denies or the caller may not read is selected. Selected rows the caller may not
/// read raise the key's declared message without ids ([`hidden_conflict`]), whether or not the
/// write rule lets them through (the upsert reports the id, the version and the accumulated
/// values of every row it matches: review SEC-M1); the others raise the record-level `Access`
/// error of the write, naming them. `rule` is the restricting write rule, `None` when it
/// restricts nothing.
async fn precheck(
    tx: &mut Transaction,
    records: &Records,
    key: &BusinessKey,
    chunk: Chunk<'_>,
    rule: Option<&crate::search::Compiled>,
    read: &Readable,
) -> Result<()> {
    let Chunk {
        batch,
        shape,
        members,
    } = chunk;
    let spec = records.spec();
    if let Some(rule) = rule {
        crate::search::flush_read_inputs(tx, &rule.fields).await?;
    }
    let (write_sql, write_params, write_joins): (Option<&str>, &[erp_sql::param::Param], &[_]) =
        match rule {
            Some(rule) => (Some(&*rule.sql), &rule.params, &rule.join_list),
            None => (None, &[], &[]),
        };
    let (read_sql, read_params, read_joins): (Option<&str>, &[erp_sql::param::Param], &[_]) =
        match read {
            Readable::All => (None, &[], &[]),
            Readable::Nothing => (Some("FALSE"), &[], &[]),
            Readable::Rule(read) => {
                crate::search::flush_read_inputs(tx, &read.fields).await?;
                (Some(&*read.sql), &read.params, &read.join_list)
            }
        };
    let key_columns: Vec<KeyColumn<'_>> = shape
        .key
        .iter()
        .map(|(name, nullable)| KeyColumn {
            name,
            nullable: *nullable,
        })
        .collect();
    let mut types = Vec::with_capacity(key_columns.len());
    let mut bound = crate::search::bind(write_params)?;
    bound.extend(crate::search::bind(read_params)?);
    for (c, f) in batch.columns.iter().take(key_columns.len()).enumerate() {
        types.push(column_type(spec, *f)?);
        let cells: Vec<Cell> = members.iter().map(|&m| batch.rows[m][c].clone()).collect();
        bound.push(crate::write::array_param(
            spec.field_by_id(*f).storage(),
            cells,
        )?);
    }
    let joins = crate::search::merge_joins(&[write_joins, read_joins]);
    let sql = erp_sql::upsert::existing_denied(
        &spec.table,
        &key_columns,
        &types,
        &joins,
        erp_sql::upsert::PreCheckRules::new(write_sql, read_sql),
        write_params.len() + read_params.len(),
    );
    let refs: Vec<&(dyn ToSql + Sync)> = bound
        .iter()
        .map(|b| b.as_ref() as &(dyn ToSql + Sync))
        .collect();
    let rows = tx.query(&sql, &refs).await?;
    if rows.is_empty() {
        return Ok(());
    }
    let mut ids = Vec::with_capacity(rows.len());
    for row in &rows {
        if !row.try_get::<_, bool>(1).map_err(decode_error)? {
            return Err(hidden_conflict(key));
        }
        ids.push(row.try_get::<_, i64>(0).map_err(decode_error)?);
    }
    ids.sort_unstable();
    // the engine's SEC-009 record-level text; `None` when none of the rows exists any more (a
    // concurrent delete): the statement then inserts instead of updating, nothing was denied
    let denied: Vec<RealId> = ids.iter().filter_map(|id| RealId::new(*id)).collect();
    if denied.len() != ids.len() {
        return Err(upsert_error(
            spec,
            "the pre-check returned an id that is not a database id".to_owned(),
        ));
    }
    let env = records.env().clone();
    match tx
        .record_access_error(&env, records.model_id(), Operation::Write, &denied)
        .await?
    {
        Some(error) => Err(error),
        None => Ok(()),
    }
}

/// The error for a `22003` of the statement. The server does not say which number overflowed:
/// with accumulated fields and no row version the accumulated fields are the only candidates, and
/// the error is the `Validation` naming them; with a row version too (`row_version + 1`), the
/// error is a `Database` error naming every candidate; with no accumulated field, the row version
/// is the only one (review SEC-S4).
fn overflow(spec: &ModelSpec, plan: &Plan<'_>, error: Error) -> Error {
    let fields: Vec<&FieldSpec> = plan
        .accumulate
        .iter()
        .map(|(f, _)| spec.field_by_id(*f))
        .filter(|f| {
            matches!(
                f.storage(),
                Storage::Int | Storage::Float | Storage::Decimal
            )
        })
        .collect();
    let sqlstate = error.sqlstate().map(str::to_owned);
    match (fields.is_empty(), spec.row_version.is_some()) {
        (true, _) => crate::version::version_overflow(spec, error),
        (false, false) => out_of_range(spec, &fields)
            .with_sqlstate(sqlstate)
            .with_source(error),
        (false, true) => {
            let names: Vec<String> = fields
                .iter()
                .map(|f| format!("'{}' ({})", f.string, f.name))
                .collect();
            Error::new(
                ErrorKind::Database,
                format!(
                    "a number of the upsert on '{}' is out of range in the database: the \
                     accumulated {} or the row version ({}); the statement does not say which",
                    spec.description,
                    names.join(" or "),
                    erp_registry::ROW_VERSION
                ),
            )
            .with_sqlstate(sqlstate)
            .with_source(error)
        }
    }
}

/// The server routine that raises "constraint ... for table ... does not exist" for an `ON
/// CONFLICT ON CONSTRAINT` arbiter (`get_relation_constraint_attnos` in PostgreSQL 18, observed with `VERBOSITY=verbose`; it is the server's source name; the
/// error's `routine` field, not its language-dependent text).
const MISSING_CONSTRAINT_ROUTINE: &str = "get_relation_constraint_attnos";

/// Whether `error` is the missing-arbiter error of the upsert statement: SQLSTATE `42704` raised
/// by the routine that looks a constraint up by name. The constraint does not exist because the
/// post-commit steps that add it to a large table have not completed. Any other
/// `42704` (a type, a function, ...) is not it. The server error stays the source.
fn is_missing_arbiter(error: &Error) -> bool {
    let routine = std::error::Error::source(error)
        .and_then(|s| s.downcast_ref::<tokio_postgres::Error>())
        .and_then(tokio_postgres::Error::as_db_error)
        .and_then(|db| db.routine());
    arbiter_missing(error.sqlstate(), routine)
}

fn arbiter_missing(sqlstate: Option<&str>, routine: Option<&str>) -> bool {
    sqlstate == Some("42704") && routine == Some(MISSING_CONSTRAINT_ROUTINE)
}

/// Send the statement for the merged rows `members`; their outcomes in `members` order.
async fn run_statement(
    tx: &mut Transaction,
    records: &Records,
    plan: &Plan<'_>,
    batch: &Batch,
    shape: &Shape,
    members: &[usize],
    ran: &mut bool,
) -> Result<Vec<RowOutcome>> {
    let spec = records.spec();
    let mut params: Vec<Box<dyn ToSql + Sync + Send>> = Vec::new();
    for (c, f) in batch.columns.iter().enumerate() {
        let cells: Vec<Cell> = members.iter().map(|&m| batch.rows[m][c].clone()).collect();
        params.push(crate::write::array_param(
            spec.field_by_id(*f).storage(),
            cells,
        )?);
    }
    if shape.uid {
        params.push(Box::new(records.env().uid()));
    }
    for floor in &shape.floors {
        params.push(scalar_param(spec, floor)?);
    }
    let refs: Vec<&(dyn ToSql + Sync)> = params
        .iter()
        .map(|p| p.as_ref() as &(dyn ToSql + Sync))
        .collect();
    let rows = match tx.query(&shape.sql, &refs).await {
        Ok(rows) => rows,
        Err(error) if error.sqlstate() == Some("22003") => {
            return Err(overflow(spec, plan, error));
        }
        Err(error) if is_missing_arbiter(&error) => {
            return Err(Error::new(
                ErrorKind::Database,
                format!(
                    "business key '{}' of '{}' is not usable yet: its post-commit steps have \
                     not completed (pending or failed; see the schema step report and the \
                     module health check)",
                    plan.key.name, spec.name
                ),
            )
            .with_sqlstate(error.sqlstate().map(str::to_owned))
            .with_source(error));
        }
        Err(error) => return Err(error),
    };
    // Once SQL succeeds, every later decode/capture failure is after mutation.
    *ran = true;
    let mut out: Vec<Option<RowOutcome>> = vec![None; members.len()];
    let first_new = 6;
    let first_old = first_new + shape.new_fields.len();
    let now_index = first_old + shape.old_fields.len();
    for row in &rows {
        let ord: i64 = row.try_get(0).map_err(decode_error)?;
        let raw: i64 = row.try_get(1).map_err(decode_error)?;
        let inserted: bool = row.try_get(2).map_err(decode_error)?;
        let written: bool = row.try_get(3).map_err(decode_error)?;
        let old_version: Option<i64> = row.try_get(4).map_err(decode_error)?;
        let version: Option<i64> = row.try_get(5).map_err(decode_error)?;
        let now: DateTime = row.try_get(now_index).map_err(decode_error)?;
        tx.now = Some(now);
        let slot = usize::try_from(ord)
            .ok()
            .and_then(|o| o.checked_sub(1))
            .and_then(|i| out.get_mut(i))
            .ok_or_else(|| upsert_error(spec, format!("the statement returned ordinal {ord}")))?;
        if slot.is_some() {
            return Err(upsert_error(
                spec,
                format!("the statement returned ordinal {ord} twice"),
            ));
        }
        let id = RecId::from_real(raw)
            .ok_or_else(|| upsert_error(spec, format!("the statement returned id {raw}")))?;
        let mut accumulated = Vec::with_capacity(plan.accumulate.len());
        for (i, (f, _)) in plan.accumulate.iter().enumerate() {
            let cell = crate::read::decode(row, first_new + i, column_type(spec, *f)?)?;
            crate::precision::validate(tx, records.env(), spec, spec.field_by_id(*f), &cell)
                .await?;
            accumulated.push(cell);
        }
        let mut stored = Vec::new();
        for (i, f) in shape
            .new_fields
            .iter()
            .enumerate()
            .skip(plan.accumulate.len())
        {
            stored.push(crate::read::decode(
                row,
                first_new + i,
                column_type(spec, *f)?,
            )?);
        }
        let mut old = Vec::with_capacity(shape.old_fields.len());
        for (i, f) in shape.old_fields.iter().enumerate() {
            old.push(crate::read::decode(
                row,
                first_old + i,
                column_type(spec, *f)?,
            )?);
        }
        let mut changed = Vec::new();
        for (index, field) in shape.changed_fields.iter().enumerate() {
            let flag: bool = row.try_get(now_index + 1 + index).map_err(decode_error)?;
            if flag {
                changed.push(*field);
            }
        }
        let (outcome, previous_version) = if inserted {
            (UpsertOutcome::Inserted, None)
        } else if written {
            (UpsertOutcome::Updated, old_version)
        } else {
            (UpsertOutcome::Unchanged, version)
        };
        *slot = Some(RowOutcome {
            id,
            outcome,
            previous_version,
            version,
            accumulated,
            stored,
            old,
            changed,
        });
    }
    out.into_iter()
        .zip(members)
        .map(|(o, m)| {
            o.ok_or_else(|| {
                upsert_error(
                    spec,
                    format!(
                        "the statement returned nothing for merged row {m} (neither inserted, \
                         updated nor found)"
                    ),
                )
            })
        })
        .collect()
}

/// After the statement of one chunk: cache, stored computes, inverses, constraints, company
/// checks and write hooks (design note §3.6).
async fn apply(
    tx: &mut Transaction,
    records: &Records,
    plan: &Plan<'_>,
    batch: &Batch,
    shape: &Shape,
    members: &[usize],
    out: &[RowOutcome],
) -> Result<()> {
    let env = records.env().clone();
    let model = records.model_id();
    let registry = Arc::clone(env.registry());
    let spec = registry.model_by_id(model);
    let shared = Arc::clone(&tx.shared);
    let graph = shared.graph.model(model);
    let uid = Cell::Id(env.uid());
    // every row of the statement returned the transaction timestamp (run_statement stored it)
    let now = tx
        .now
        .map(Cell::DateTime)
        .ok_or_else(|| upsert_error(spec, "the statement returned no transaction timestamp"))?;
    let mut inserted: Vec<(usize, RecId)> = Vec::new();
    let mut updated: Vec<(usize, &RowOutcome)> = Vec::new();
    for (&m, o) in members.iter().zip(out) {
        match o.outcome {
            UpsertOutcome::Inserted => inserted.push((m, o.id)),
            UpsertOutcome::Updated => updated.push((m, o)),
            UpsertOutcome::Unchanged => {}
        }
    }
    let written: Vec<FieldId> = plan
        .update
        .iter()
        .copied()
        .chain(plan.accumulate.iter().map(|(f, _)| *f))
        .collect();

    // the cache equals what a fetch would return
    {
        let cache = tx.cache.model_mut(model);
        for (&m, o) in members.iter().zip(out) {
            if let (Some(rv), Some(version)) = (spec.row_version, o.version) {
                cache.set(rv, erp_fields::Storage::Id, o.id, Cell::Id(version), false)?;
            }
            match o.outcome {
                UpsertOutcome::Inserted => {
                    for field in &spec.fields {
                        if field.is_generated()
                            || field.inherited.is_some()
                            || matches!(field.ty, FieldType::RowVersion)
                        {
                            continue;
                        }
                        let storage = field.storage();
                        let cell = if field.magic {
                            match field.name {
                                "create_uid" | "write_uid" => uid.clone(),
                                "create_date" | "write_date" => now.clone(),
                                other => {
                                    return Err(upsert_error(
                                        spec,
                                        format!(
                                            "no inserted value is known for the server-set \
                                             field '{other}'"
                                        ),
                                    ));
                                }
                            }
                        } else if let Some(c) = batch.column_of[field.id.index()] {
                            batch.rows[m][c].clone()
                        } else if field.ty.is_x2many() && field.store {
                            Cell::Ids(Arc::from([]))
                        } else if field.has_column() {
                            // the INSERT stores NULL here: ORM columns have no database default
                            // (the row version, set by the statement, is skipped above), and a
                            // required one was refused when the batch was prepared
                            Cell::Null
                        } else {
                            continue;
                        };
                        cache.set(field.id, storage, o.id, cell, false)?;
                    }
                    for ((f, _), cell) in plan.accumulate.iter().zip(&o.accumulated) {
                        let storage = spec.field_by_id(*f).storage();
                        cache.set(*f, storage, o.id, cell.clone(), false)?;
                    }
                }
                UpsertOutcome::Updated => {
                    for f in &plan.update {
                        let Some(c) = batch.column_of[f.index()] else {
                            return Err(upsert_error(
                                spec,
                                format!(
                                    "updated field '{}' is missing from the statement",
                                    spec.field_by_id(*f).name
                                ),
                            ));
                        };
                        let storage = spec.field_by_id(*f).storage();
                        cache.set(*f, storage, o.id, batch.rows[m][c].clone(), false)?;
                    }
                    for ((f, _), cell) in plan.accumulate.iter().zip(&o.accumulated) {
                        let storage = spec.field_by_id(*f).storage();
                        cache.set(*f, storage, o.id, cell.clone(), false)?;
                    }
                    if spec.log_access {
                        if let Some(wu) = spec.field("write_uid") {
                            cache.set(wu.id, erp_fields::Storage::Id, o.id, uid.clone(), false)?;
                        }
                        if let Some(wd) = spec.field("write_date") {
                            cache.set(
                                wd.id,
                                erp_fields::Storage::DateTime,
                                o.id,
                                now.clone(),
                                false,
                            )?;
                        }
                    }
                }
                UpsertOutcome::Unchanged => {}
            }
        }
    }

    // stored computes of inserted rows that were not given are computed at the next flush
    // (`create`'s rule, COMP §4.4), dependents of updated fields are notified
    for &f in &graph.order {
        let Some(fc) = graph.compute(f) else { continue };
        if !fc.stored {
            continue;
        }
        let todo: Vec<RecId> = inserted
            .iter()
            .filter(|(m, _)| !batch.given[*m][f.index()])
            .map(|(_, id)| *id)
            .collect();
        if !todo.is_empty() {
            let storage = spec.field_by_id(f).storage();
            tx.bind_capture(model, f, &todo)?;
            tx.cache.model_mut(model).mark_pending(f, storage, &todo);
        }
    }
    let updated_ids: Vec<RecId> = updated.iter().map(|(_, o)| o.id).collect();
    if !updated_ids.is_empty() {
        let mut changes: Vec<(FieldId, Vec<RecId>)> =
            written.iter().map(|f| (*f, updated_ids.clone())).collect();
        if spec.log_access {
            for name in ["write_uid", "write_date"] {
                if let Some(f) = spec.field(name) {
                    changes.push((f.id, updated_ids.clone()));
                }
            }
        }
        tx.modified(model, changes).await?;
    }

    // cached one2many values of the many2one targets (REL §4.4.4)
    for field in spec.fields.iter().filter(|f| {
        matches!(f.ty, FieldType::Many2one { .. })
            && f.inherited.is_none()
            && f.has_column()
            && !shared.relations.inverses(model, f.id).is_empty()
    }) {
        let column = batch.column_of[field.id.index()];
        let mut groups: Vec<(Cell, Vec<RecId>, Vec<Option<Cell>>)> = Vec::new();
        let mut add = |target: Cell, id: RecId, old: Option<Cell>| match groups
            .iter_mut()
            .find(|(t, _, _)| *t == target)
        {
            Some((_, ids, olds)) => {
                ids.push(id);
                olds.push(old);
            }
            None => groups.push((target, vec![id], vec![old])),
        };
        if let Some(c) = column {
            for (m, id) in &inserted {
                let target = batch.rows[*m][c].clone();
                if !target.is_null() {
                    add(target, *id, Some(Cell::Null));
                }
            }
        }
        if let (Some(c), Some(o)) = (
            column.filter(|_| plan.update.contains(&field.id)),
            shape.old_fields.iter().position(|f| *f == field.id),
        ) {
            for (m, row) in &updated {
                add(batch.rows[*m][c].clone(), row.id, Some(row.old[o].clone()));
            }
        }
        for (target, ids, olds) in groups {
            let recs = records.browse_ids(ids);
            tx.update_inverses(model, field.id, &recs, &olds, &target)
                .await?;
        }
    }
    let mut touched: Vec<FieldId> = batch.columns.clone();
    touched.sort_unstable();
    tx.forget_reference_inverses(model, &touched);

    // constraints of the inserted columns (given or defaulted, as `create` checks the values
    // `default_get` added) on inserted rows, of the written fields on updated rows
    if !inserted.is_empty() {
        let names: FxHashSet<FieldId> = batch.columns.iter().copied().collect();
        let recs = records.browse_ids(inserted.iter().map(|(_, id)| *id));
        tx.run_constraints(&recs, &names, &FxHashSet::default())
            .await?;
        tx.check_company(&recs, None).await?;
    }
    if !updated_ids.is_empty() {
        let names: FxHashSet<FieldId> = written.iter().copied().collect();
        let recs = records.browse_ids(updated_ids.iter().copied());
        tx.run_constraints(&recs, &names, &FxHashSet::default())
            .await?;
        tx.check_company(&recs, Some(&written)).await?;
        // Like ordinary write, changing a compute input can move the record out of its
        // generated restriction (including a computed escape), even without writing an
        // anchor explicitly. Only this model's fields and these updated records are checked.
        let mut moved: FxHashSet<FieldId> = written.iter().copied().collect();
        let mut pending = written.clone();
        while let Some(fid) = pending.pop() {
            for dep in graph.dependents(fid) {
                if moved.insert(*dep) {
                    pending.push(*dep);
                }
            }
        }
        let moved: Vec<FieldId> = moved.into_iter().collect();
        tx.check_generated_restriction(&recs, &moved).await?;
    }

    // tracked fields: rows inserted never report changes; rows updated are
    // written records, with old values from the statement and new values as written
    if !spec.tracked.is_empty() {
        let depth = tx.savepoint_depth();
        let new_ids: Vec<RecId> = inserted.iter().map(|(_, id)| *id).collect();
        tx.tracking.created(depth, model, &new_ids);
        let tracked: Vec<FieldId> = shape
            .old_fields
            .iter()
            .copied()
            .filter(|f| spec.tracked.contains(f) && written.contains(f))
            .collect();
        if !updated.is_empty() && !tracked.is_empty() {
            let mut rows: Vec<(RecId, Vec<(Cell, Cell)>)> = Vec::with_capacity(updated.len());
            for (_, o) in &updated {
                let mut values = Vec::with_capacity(tracked.len());
                for f in &tracked {
                    let old = shape
                        .old_fields
                        .iter()
                        .position(|x| x == f)
                        .map(|i| o.old[i].clone())
                        .ok_or_else(|| {
                            upsert_error(
                                spec,
                                format!(
                                    "tracked field '{}' has no old value",
                                    spec.field_by_id(*f).name
                                ),
                            )
                        })?;
                    // the stored value of RETURNING, never the raw batch cell
                    let new = match shape.new_fields.iter().position(|x| x == f) {
                        Some(i) if i < plan.accumulate.len() => o.accumulated[i].clone(),
                        Some(i) => o.stored[i - plan.accumulate.len()].clone(),
                        None => {
                            return Err(upsert_error(
                                spec,
                                format!(
                                    "tracked field '{}' has no new value",
                                    spec.field_by_id(*f).name
                                ),
                            ));
                        }
                    };
                    values.push((old, new));
                }
                rows.push((o.id, values));
            }
            let ids: Vec<RecId> = rows.iter().map(|(id, _)| *id).collect();
            tx.track_prepare_direct(records, &ids);
            tx.track_capture(spec, &tracked, &rows);
        }
    }

    // write hooks: old values from the statement, new values as written
    if !updated.is_empty() {
        for hook in shared.write_hooks.of(model) {
            let fields: Vec<FieldId> = hook
                .fields
                .iter()
                .copied()
                .filter(|f| written.contains(f))
                .collect();
            if fields.is_empty() {
                continue;
            }
            let mut rows = Vec::with_capacity(updated.len());
            for (m, o) in &updated {
                let mut values = Vec::with_capacity(fields.len());
                for f in &fields {
                    let old_at = shape.old_fields.iter().position(|x| x == f);
                    let old = match old_at {
                        Some(i) => o.old[i].clone(),
                        None => {
                            return Err(upsert_error(
                                spec,
                                format!(
                                    "hooked field '{}' has no old value",
                                    spec.field_by_id(*f).name
                                ),
                            ));
                        }
                    };
                    let new = match plan.accumulate.iter().position(|(x, _)| x == f) {
                        Some(i) => o.accumulated[i].clone(),
                        None => match batch.column_of[f.index()] {
                            Some(c) => batch.rows[*m][c].clone(),
                            None => {
                                return Err(upsert_error(
                                    spec,
                                    format!(
                                        "hooked field '{}' has no new value",
                                        spec.field_by_id(*f).name
                                    ),
                                ));
                            }
                        },
                    };
                    values.push((old, new));
                }
                rows.push(crate::version::WrittenRow::new(o.id, values));
            }
            let names = fields.iter().map(|f| spec.field_by_id(*f).name).collect();
            let batch = crate::version::WriteBatch::new(spec.name, names, rows);
            (hook.call)(tx, &batch).await?;
        }
    }
    Ok(())
}

/// `value < floor` for two cells of one numeric field.
fn below(spec: &ModelSpec, field: &FieldSpec, value: &Cell, floor: &Cell) -> Result<bool> {
    Ok(match (value, floor) {
        (Cell::Int(v), Cell::Int(f)) => v < f,
        (Cell::Float(v), Cell::Float(f)) => v < f,
        (Cell::Decimal(v), Cell::Decimal(f)) => v < f,
        (v, f) => {
            return Err(upsert_error(
                spec,
                format!(
                    "cannot compare {v:?} with the floor {f:?} of '{}'",
                    field.name
                ),
            ));
        }
    })
}

/// An inserted row starts with its own value, so an accumulated value below its floor would be
/// stored as is: the call fails instead (the floor applies to updates by `GREATEST`).
fn check_floors(spec: &ModelSpec, plan: &Plan<'_>, out: &[RowOutcome]) -> Result<()> {
    for row in out.iter().filter(|o| o.outcome == UpsertOutcome::Inserted) {
        for ((f, floor), value) in plan.accumulate.iter().zip(&row.accumulated) {
            let Some(floor) = floor else { continue };
            let field = spec.field_by_id(*f);
            if below(spec, field, value, floor)? {
                return Err(Error::validation(format!(
                    "The operation cannot be completed: a new '{}' record would start with '{}' \
                     ({}) = {} below its floor {}",
                    spec.description,
                    field.string,
                    field.name,
                    Value::from_cell(value),
                    Value::from_cell(floor)
                )));
            }
        }
    }
    Ok(())
}

/// Buffer only physical rows returned by SQL, never repeated public input positions.
fn capture_upsert(
    tx: &mut Transaction,
    records: &Records,
    shape: &Shape,
    rows: &[RowOutcome],
) -> Result<()> {
    let spec = records.spec();
    if !spec.eventful {
        return Ok(());
    }
    let context = tx
        .pending_capture
        .active
        .as_ref()
        .ok_or_else(|| Error::programming("outbox: eventful upsert is missing writer provenance"))?
        .clone();
    let mut created = Vec::new();
    let mut written: BTreeMap<Vec<FieldId>, Vec<crate::outbox::IdEntry>> = BTreeMap::new();
    for row in rows {
        let id = row
            .id
            .as_real()
            .ok_or_else(|| upsert_error(spec, "the statement returned a non-real id"))?;
        let entry = crate::outbox::IdEntry::Single(id.get());
        match row.outcome {
            UpsertOutcome::Inserted => created.push(entry),
            UpsertOutcome::Updated if !row.changed.is_empty() => {
                written.entry(row.changed.clone()).or_default().push(entry)
            }
            // Unchanged rows and bookkeeping-only updates carry no business change.
            UpsertOutcome::Updated | UpsertOutcome::Unchanged => {}
        }
    }
    let depth = tx.savepoint_depth();
    if !created.is_empty() {
        let names: Vec<String> = shape
            .create_fields
            .iter()
            .map(|field| spec.field_by_id(*field).name.to_owned())
            .collect();
        for ids in created.chunks(crate::outbox::MAX_ID_ENTRIES) {
            tx.outbox.push(
                context.envelope(
                    crate::outbox::Kind::Create,
                    spec.name,
                    ids.to_vec(),
                    names.clone(),
                    Vec::new(),
                )?,
                depth,
            )?;
        }
    }
    for (fields, ids) in written {
        let names: Vec<String> = fields
            .iter()
            .map(|field| spec.field_by_id(*field).name.to_owned())
            .collect();
        for ids in ids.chunks(crate::outbox::MAX_ID_ENTRIES) {
            tx.outbox.push(
                context.envelope(
                    crate::outbox::Kind::Write,
                    spec.name,
                    ids.to_vec(),
                    names.clone(),
                    Vec::new(),
                )?,
                depth,
            )?;
        }
    }
    Ok(())
}

/// Everything after one chunk's statement: floors, cache, computes, constraints, hooks and the
/// create check of the inserted rows.
async fn after_statement(
    tx: &mut Transaction,
    records: &Records,
    plan: &Plan<'_>,
    batch: &Batch,
    shape: &Shape,
    members: &[usize],
    out: &[RowOutcome],
) -> Result<()> {
    check_floors(records.spec(), plan, out)?;
    apply(tx, records, plan, batch, shape, members, out).await?;
    let inserted: Vec<RecId> = out
        .iter()
        .filter(|o| o.outcome == UpsertOutcome::Inserted)
        .map(|o| o.id)
        .collect();
    if !inserted.is_empty() {
        // after the statement, as a `create` whose check is not fused: the predicate may read
        // the stored values; a refusal leaves the transaction poisoned
        tx.check_record_access(&records.browse_ids(inserted), Operation::Create)
            .await?;
    }
    Ok(())
}

/// `base.upsert`: see the module documentation.
pub(crate) async fn upsert_records(
    tx: &mut Transaction,
    records: &Records,
    call: UpsertCall,
) -> Result<UpsertResult> {
    tx.admit_records(records).await?;
    tx.check_capture_create(records, &call.rows)?;
    let before = tx.mutations();
    let guard = tx.guard();
    let previous_origin = tx.pending_capture.active.clone();
    let result = upsert_records_inner(tx, records, call).await;
    tx.pending_capture.active = previous_origin;
    if let Err(error) = &result {
        tx.poison_after(before, error);
    }
    guard.disarm();
    result
}

async fn upsert_records_inner(
    tx: &mut Transaction,
    records: &Records,
    call: UpsertCall,
) -> Result<UpsertResult> {
    let env = records.env().clone();
    let model = records.model_id();
    let registry = Arc::clone(env.registry());
    let spec = registry.model_by_id(model);
    if let Some(field) = spec.fields.iter().find(|field| field.company_dependent) {
        return Err(crate::company_dependent_runtime::unsupported(
            spec.name, field.name, "upsert",
        ));
    }
    if spec
        .fields
        .iter()
        .any(|field| matches!(field.ty, FieldType::Monetary { .. }))
    {
        return Err(upsert_error(
            spec,
            "monetary fields are not supported until a later release",
        ));
    }
    let plan = plan(spec, &call)?;
    if call.rows.is_empty() {
        return Ok(UpsertResult::default());
    }
    tx.require_writable(crate::WriteOp::Upsert, spec.name)?;
    // the statement does not check pending expectations and bumps the version itself: the
    // expectation would later fail against the upsert's own bump (review DB-M1)
    if tx.versions.has_model(model) {
        return Err(upsert_error(
            spec,
            "expect_versions expectations are pending for this model; write and flush the \
             expected records before upserting (an upsert does not check them, and its own \
             version bump would make them fail later)",
        ));
    }
    // the policy and the principal current before any decision
    tx.prepare_access(&env).await?;
    // a policy source or a membership: what is pending runs under the policy it started with, and
    // the transaction rebuilds its policy at the next engine call (a create or a write of such a
    // model, whichever the row turns out to be: no field narrows it)
    let source = tx.before_policy_source_write(model, None).await?;
    let result = upsert_checked(tx, records, &plan, call.rows).await;
    // also after a failure: the statement may have run (over-invalidation is safe)
    tx.policy_source_written(source);
    result
}

/// The checks and the statements of an upsert once the engine is prepared. Once a chunk's
/// statement has run, any later error (a failing second chunk included) poisons the transaction:
/// the first chunk is written (review SF-N2).
async fn upsert_checked(
    tx: &mut Transaction,
    records: &Records,
    plan: &Plan<'_>,
    rows: Vec<RawVals>,
) -> Result<UpsertResult> {
    let mut ran = false;
    let result = upsert_chunks(tx, records, plan, rows, &mut ran).await;
    if let Err(error) = &result
        && ran
    {
        tx.poison_with(error);
    }
    result
}

async fn upsert_chunks(
    tx: &mut Transaction,
    records: &Records,
    plan: &Plan<'_>,
    rows: Vec<RawVals>,
    ran: &mut bool,
) -> Result<UpsertResult> {
    let env = records.env().clone();
    let model = records.model_id();
    let spec = records.spec();
    tx.check_model(&env, model, Operation::Create)?;
    tx.check_model(&env, model, Operation::Write)?;
    let batch = prepare(tx, records, plan, &rows)?;
    // Upsert is both create and write: input keys/values and conflict targets obey the
    // same field mask as ordinary assignments (/023).
    tx.check_field_names(
        &env,
        model,
        rows.iter()
            .flat_map(|row| row.names())
            .chain(
                plan.update
                    .iter()
                    .map(|field| spec.field_by_id(*field).name),
            )
            .chain(
                plan.accumulate
                    .iter()
                    .map(|(field, _)| spec.field_by_id(*field).name),
            )
            .chain(env.context().default_field_names()),
        crate::field_access::FieldOp::Write,
    )?;
    // Validate caller/default cells and folded rows after field authorization, before SQL.
    for vals in &rows {
        for (name, cell) in vals.iter() {
            let field = writable_column(spec, name)?;
            crate::precision::validate(tx, &env, spec, field, cell).await?;
        }
    }
    for row in &batch.rows {
        for (fid, cell) in batch.columns.iter().zip(row) {
            crate::precision::validate(tx, &env, spec, spec.field_by_id(*fid), cell).await?;
        }
    }
    for (fid, floor) in &plan.accumulate {
        if let Some(cell) = floor {
            crate::precision::validate(tx, &env, spec, spec.field_by_id(*fid), cell).await?;
        }
    }
    let mut rows = rows;
    tx.check_references(records, &mut rows).await?;
    // Access/input/reference admission precedes settling an earlier capture operation:
    // an ordinary denial must not turn permitted pending work rollback-only.
    let relevant = tx.capture_model_relevant(model);
    tx.begin_capture_operation(records, relevant).await?;
    // pending writes and recomputations reach the database before the statement reads the rows
    tx.flush().await?;
    let write_rule = crate::search::record_restriction(tx, records, Operation::Write)
        .await?
        .filter(|rule| rule.constant != Some(true));
    // the read predicate is evaluated in the pre-check statement too, its placeholders after the
    // write predicate's: every matched row must be readable (review SEC-M1)
    let read = readable(
        tx,
        records,
        write_rule.as_ref().map_or(0, |rule| rule.params.len()),
    )
    .await?;
    let prechecked = write_rule.is_some() || !matches!(read, Readable::All);
    let shape = shape(tx, spec, plan, &batch)?;
    let mut outcomes: Vec<Option<UpsertedRow>> = vec![None; batch.rows.len()];
    for members in batch.order.chunks(tx.config().insert_batch.max(1)) {
        if prechecked {
            let chunk = Chunk {
                batch: &batch,
                shape: &shape,
                members,
            };
            precheck(tx, records, plan.key, chunk, write_rule.as_deref(), &read).await?;
        }
        let out = run_statement(tx, records, plan, &batch, &shape, members, ran).await?;
        capture_upsert(tx, records, &shape, &out)?;
        // rows were inserted or written: the memoized record checks whose predicates read this
        // model are stale
        tx.access_written(model, None);
        // the statement ran: whatever fails from here on poisons the transaction, whichever way
        // the caller reaches us (review SF-S5)
        after_statement(tx, records, plan, &batch, &shape, members, &out).await?;
        for (&m, o) in members.iter().zip(&out) {
            outcomes[m] = Some(UpsertedRow {
                id: o.id,
                outcome: o.outcome,
                previous_version: o.previous_version,
                version: o.version,
            });
        }
    }
    let mut result = Vec::with_capacity(batch.position.len());
    for (n, m) in batch.position.iter().enumerate() {
        let Some(row) = outcomes.get(*m).copied().flatten() else {
            return Err(upsert_error(spec, format!("input row {n} has no outcome")));
        };
        result.push(row);
    }
    Ok(UpsertResult { rows: result })
}

// ---- base implementation --------------------------------------------------------------------

type UpsertFn = MethodFn<(UpsertCall,), UpsertResult>;

fn base_upsert<'a>(
    tx: &'a mut Transaction,
    records: &'a Records,
    args: (UpsertCall,),
    _sup: Super<(UpsertCall,), UpsertResult>,
) -> BoxFuture<'a, Result<UpsertResult>> {
    Box::pin(upsert_records(tx, records, args.0))
}

fn upsert_entry() -> &'static (dyn Any + Send + Sync) {
    static F: UpsertFn = base_upsert;
    &F
}

/// `base.upsert`, registered by [`crate::Dispatch::build`].
pub(crate) static BUILTIN_IMPLS: [&MethodImpl; 1] = [&BASE_UPSERT];

static BASE_UPSERT: MethodImpl = MethodImpl {
    addon: "base",
    model: "base",
    method: "upsert",
    kind: ImplKind::Define,
    sig_name: std::any::type_name::<UpsertFn>,
    entry: upsert_entry,
    file: file!(),
    line: line!(),
};

