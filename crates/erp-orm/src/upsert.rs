/// A key value as the arbiter compares it: NULL equals NULL (`NULLS NOT DISTINCT`), numerics by
/// value.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
enum KeyPart {
    Null,
    Bool(bool),
    Int(i32),
    Id(i64),
    Decimal(Decimal),
    Str(Arc<str>),
    Date(Date),
    DateTime(DateTime),
    Uuid(erp_fields::Uuid),
    Xid8(erp_fields::Xid8),
    TimestampTz(erp_fields::TimestampTz),
}

fn key_part(spec: &ModelSpec, field: &FieldSpec, cell: &Cell) -> Result<KeyPart> {
    Ok(match cell {
        Cell::Null => KeyPart::Null,
        Cell::Bool(b) => KeyPart::Bool(*b),
        Cell::Int(i) => KeyPart::Int(*i),
        Cell::Id(i) => KeyPart::Id(*i),
        Cell::Decimal(d) => KeyPart::Decimal(d.normalize()),
        Cell::Str(s) => KeyPart::Str(Arc::clone(s)),
        Cell::Date(d) => KeyPart::Date(*d),
        Cell::DateTime(d) => KeyPart::DateTime(*d),
        Cell::Uuid(v) => KeyPart::Uuid(*v),
        Cell::Xid8(v) => KeyPart::Xid8(*v),
        Cell::TimestampTz(v) => KeyPart::TimestampTz(*v),

        // the registry refuses these kinds as key fields
        Cell::Float(_)
        | Cell::Json(_)
        | Cell::Ids(_)
        | Cell::DateRange(_)
        | Cell::DatetimeRange(_) => {
            return Err(upsert_error(
                spec,
                format!(
                    "key field '{}' holds a value that cannot be compared exactly",
                    field.name
                ),
            ));
        }
    })
}

/// The `Validation` error of an accumulated value out of range (in the batch or in the database).
fn out_of_range(spec: &ModelSpec, fields: &[&FieldSpec]) -> Error {
    let names: Vec<String> = fields
        .iter()
        .map(|f| format!("'{}' ({})", f.string, f.name))
        .collect();
    Error::validation(format!(
        "The operation cannot be completed: the new value of {} on '{}' is out of range",
        names.join(" or "),
        spec.description
    ))
}

/// `a + b` for an accumulated field, checked.
fn add_checked(spec: &ModelSpec, field: &FieldSpec, a: &Cell, b: &Cell) -> Result<Cell> {
    let sum = match (a, b) {
        (Cell::Int(x), Cell::Int(y)) => x.checked_add(*y).map(Cell::Int),
        (Cell::Float(x), Cell::Float(y)) => Some(x + y).filter(|s| s.is_finite()).map(Cell::Float),
        (Cell::Decimal(x), Cell::Decimal(y)) => x.checked_add(*y).map(Cell::Decimal),
        _ => {
            return Err(upsert_error(
                spec,
                format!(
                    "accumulated field '{}' holds a non-numeric value",
                    field.name
                ),
            ));
        }
    };
    sum.ok_or_else(|| out_of_range(spec, &[field]))
}

/// The rows of a call, merged on the key, with the statement's column set.
struct Batch {
    /// Statement columns: the key fields in key order, then the others by name.
    columns: Vec<FieldId>,
    /// The column of each field (by field index), when the statement has one.
    column_of: Vec<Option<usize>>,
    /// One cell per column per merged row.
    rows: Vec<Vec<Cell>>,
    /// Fields each merged row gave (not defaulted), by field index.
    given: Vec<Vec<bool>>,
    /// Input position → merged row.
    position: Vec<usize>,
    /// The merged rows in the order the statements take them: sorted by key, so two concurrent
    /// calls with the same keys lock the rows in the same order whatever their input order
    /// (review DB-S2); results are mapped back by ordinal.
    order: Vec<usize>,
}

fn prepare(
    tx: &mut Transaction,
    records: &Records,
    plan: &Plan<'_>,
    rows: &[RawVals],
) -> Result<Batch> {
    let spec = records.spec();
    let n_fields = spec.fields.len();
    let mut merged: Vec<Vec<Option<Cell>>> = Vec::new();
    let mut first_input: Vec<usize> = Vec::new();
    let mut key_text: Vec<String> = Vec::new();
    let mut index: FxHashMap<Vec<KeyPart>, usize> = FxHashMap::default();
    let mut position = Vec::with_capacity(rows.len());
    for (n, vals) in rows.iter().enumerate() {
        if let Some((name, _)) = vals.iter_commands().next() {
            return Err(upsert_error(
                spec,
                format!("row {n}: x2many values ('{name}') are not supported by upsert"),
            ));
        }
        let mut cells: Vec<Option<Cell>> = vec![None; n_fields];
        for (name, cell) in vals.iter() {
            let field = writable_column(spec, name)?;
            cells[field.id.index()] = Some(if matches!(field.ty, FieldType::Html) {
                tx.admit_html_cell(spec, field, cell.clone())?
            } else {
                validate_cell(fref(spec, field), &field.ty, cell.clone())?
            });
        }
        let mut parts = Vec::with_capacity(plan.key.fields.len());
        for f in &plan.key.fields {
            let field = spec.field_by_id(*f);
            let Some(cell) = cells[f.index()].as_ref() else {
                return Err(upsert_error(
                    spec,
                    format!("row {n} does not set key field '{}'", field.name),
                ));
            };
            // a required key field never holds NULL; on a large table its NOT NULL may still be
            // unvalidated, where a NULL part could match a row the `=` pre-check cannot see
            // (review DB-S1)
            if field.required && matches!(cell, Cell::Null) {
                return Err(Error::validation(format!(
                    "The operation cannot be completed: the key field '{}' ({}) of '{}' is required \
                     and row {n} gives no value for it",
                    field.string, field.name, spec.description
                )));
            }
            parts.push(key_part(spec, field, cell)?);
        }
        for f in &plan.update {
            if cells[f.index()].is_none() {
                return Err(upsert_error(
                    spec,
                    format!(
                        "row {n} does not set updated field '{}'",
                        spec.field_by_id(*f).name
                    ),
                ));
            }
        }
        for (f, _) in &plan.accumulate {
            if matches!(cells[f.index()], None | Some(Cell::Null)) {
                return Err(upsert_error(
                    spec,
                    format!(
                        "row {n} does not set accumulated field '{}'",
                        spec.field_by_id(*f).name
                    ),
                ));
            }
        }
        let text = format!("{parts:?}");
        match index.entry(parts) {
            Entry::Occupied(entry) => {
                let m = *entry.get();
                if plan.has_floor() {
                    return Err(upsert_error(
                        spec,
                        format!(
                            "rows {} and {n} have the same key; accumulate_floor applies its floor \
                             per call, so they cannot be merged into one statement (merge them \
                             first, or upsert them in separate calls)",
                            first_input[m]
                        ),
                    ));
                }
                let target = &mut merged[m];
                for f in &plan.update {
                    target[f.index()] = cells[f.index()].take();
                }
                for (f, _) in &plan.accumulate {
                    let field = spec.field_by_id(*f);
                    let (Some(Some(a)), Some(b)) = (target.get(f.index()), &cells[f.index()])
                    else {
                        return Err(upsert_error(
                            spec,
                            format!("accumulated field '{}' lost its value", field.name),
                        ));
                    };
                    let sum = add_checked(spec, field, a, b)?;
                    target[f.index()] = Some(sum);
                }
                position.push(m);
            }
            Entry::Vacant(entry) => {
                entry.insert(merged.len());
                position.push(merged.len());
                first_input.push(n);
                key_text.push(text);
                merged.push(cells);
            }
        }
    }
    let given: Vec<Vec<bool>> = merged
        .iter()
        .map(|row| row.iter().map(Option::is_some).collect())
        .collect();

    // defaults of the fields some row leaves out (design note §3.4)
    let context = records.env().context();
    let context_defaults = context.has_default_keys();
    let mut computed_defaults: Vec<&str> = Vec::new();
    let mut required_computed: Vec<&str> = Vec::new();
    for field in spec.column_fields() {
        if field.is_generated() {
            if context.get(&format!("default_{}", field.name)).is_some() {
                crate::database_generated::check_assignment(spec, field)?;
            }
            continue;
        }
        if field.magic
            || field.inherited.is_some()
            || matches!(field.ty, FieldType::RowVersion)
            || !merged.iter().any(|row| row[field.id.index()].is_none())
        {
            continue;
        }
        if context_defaults && context.get(&format!("default_{}", field.name)).is_some() {
            computed_defaults.push(field.name);
            continue;
        }
        match &field.default {
            Some(FieldDefault::Fn(_)) => computed_defaults.push(field.name),
            Some(FieldDefault::Value(value)) => {
                let cell = to_cell(fref(spec, field), &field.ty, &value.to_value())?;
                for row in &mut merged {
                    let slot = &mut row[field.id.index()];
                    if slot.is_none() {
                        *slot = Some(cell.clone());
                    }
                }
            }
            None if field.required && field.is_computed() => required_computed.push(field.name),
            None => {}
        }
    }
    if !computed_defaults.is_empty() {
        computed_defaults.sort_unstable();
        return Err(upsert_error(
            spec,
            format!(
                "fields with computed defaults must be given explicitly (an upsert evaluates \
                 defaults before it knows which rows are new): {}",
                computed_defaults.join(", ")
            ),
        ));
    }
    if !required_computed.is_empty() {
        required_computed.sort_unstable();
        return Err(upsert_error(
            spec,
            format!(
                "required computed fields must be given explicitly (an upsert computes stored \
                 fields after the statement): {}",
                required_computed.join(", ")
            ),
        ));
    }

    // a required column that no default fills must be given by every row: the INSERT would fail
    // with a bare NOT NULL violation (review SF-S3)
    for field in spec.column_fields() {
        if field.magic
            || field.inherited.is_some()
            || !field.required
            || field.is_computed()
            || matches!(field.ty, FieldType::RowVersion | FieldType::Id)
        {
            continue;
        }
        if let Some(m) = merged
            .iter()
            .position(|row| row[field.id.index()].is_none())
        {
            return Err(upsert_error(
                spec,
                format!(
                    "row {} does not set required field '{}', which has no default (the INSERT \
                     would fail with a NOT NULL violation)",
                    first_input[m], field.name
                ),
            ));
        }
    }

    // the statements take the rows sorted by key
    let mut order: Vec<usize> = (0..merged.len()).collect();
    order.sort_by(|a, b| key_text[*a].cmp(&key_text[*b]));

    // one column set: the key fields first, then every other field some row has
    let mut columns: Vec<FieldId> = plan.key.fields.clone();
    let mut others: Vec<FieldId> = spec
        .column_fields()
        .filter(|f| !plan.key.fields.contains(&f.id))
        .filter(|f| merged.iter().any(|row| row[f.id.index()].is_some()))
        .map(|f| f.id)
        .collect();
    others.sort_by_key(|f| spec.field_by_id(*f).name);
    columns.extend(others);
    // a row without one of the columns inserts NULL there, which is what leaving the column out
    // stores (ORM columns have no database default), exactly as `create` pads its rows
    let rows = merged
        .into_iter()
        .map(|row| {
            columns
                .iter()
                .map(|f| row[f.index()].clone().unwrap_or(Cell::Null))
                .collect()
        })
        .collect();
    let mut column_of: Vec<Option<usize>> = vec![None; n_fields];
    for (c, f) in columns.iter().enumerate() {
        column_of[f.index()] = Some(c);
    }
    Ok(Batch {
        columns,
        column_of,
        rows,
        given,
        position,
        order,
    })
}

