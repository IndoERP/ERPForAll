//! `upsert` on a declared business key (–D2;
//! ).
//!
//! `records.upsert(tx, Upsert::on(Model::KEY).rows(rows).update([..]).accumulate(..))` inserts the
//! rows whose key is new and updates the others in **one statement per batch** of
//! [`crate::OrmConfig::insert_batch`] distinct keys (`INSERT … ON CONFLICT ON CONSTRAINT <key> DO
//! UPDATE … WHERE <something changes>`), and reports for every input row, in input order, the id,
//! whether it was [`UpsertOutcome::Inserted`], [`UpsertOutcome::Updated`] or left
//! [`UpsertOutcome::Unchanged`], and the previous row version.
//!
//! Before the statement (no statement sent): the call is checked (the key can arbitrate; `update`
//! and `accumulate` name columns of the model's own table, never a key field), every row is
//! validated like `create` validates values, sets every key, update and accumulate field, and the
//! rows are merged on their key: `update` fields take the last row's value, `accumulate` fields
//! are summed with checked arithmetic, every other field keeps the first row's value — what
//! sequential calls would end with. Static field defaults fill the fields a row leaves out;
//! a field whose default is computed (a default function, a `default_<field>` context key) must
//! be given explicitly, since the defaults would be evaluated before the statement knows which
//! rows are new. Pending writes are flushed first.
//!
//! Access ('s `create` and `write` shapes, design §3.5): the engine is prepared (policy and
//! principal current, a policy-source model flushes and marks the transaction like `create` does),
//! then the model checks for both operations (a `read_only` API-key scope refuses here); the write
//! predicate over the existing rows of the batch's keys by one `SELECT` before the statement
//! (skipped when it restricts nothing); the create record check on the inserted rows after it, as
//! `create` does without a fused check ([`Transaction::check_record_access`]). A denied row fails
//! the whole call with the engine's SEC-009 text (`explain`). The pre-check reads the read
//! predicate in the same statement: a denied row the caller may not read raises the key's declared
//! message (what a `create` of that key raises), never its id; readable denied rows are explained
//! by the engine.
//!
//! After the statement the cache holds the written values, stored computes of inserted rows and
//! dependents of updated fields are marked to recompute, `#[constrains]` methods run, and write
//! hooks get the old values the statement returned. **The model's `create` and `write` overrides
//! do not run** (nor `default_get` overrides): that is the contract of declaring a key. `upsert`
//! itself is a dispatched method that addons override with `super`.

