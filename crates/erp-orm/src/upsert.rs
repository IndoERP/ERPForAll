/// A field handle usable on records of model `M` (a field of `M` or of a model `M` inherits).
pub trait FieldOf<M>: Copy {
    /// The field name.
    fn field_name(self) -> &'static str;
}

impl<M: Model, P: Model, T> FieldOf<M> for Field<P, T>
where
    M: Inherits<P>,
{
    fn field_name(self) -> &'static str {
        self.name()
    }
}

/// A typed upsert on model `M` (design note §3.2):
///
/// ```ignore
/// let out = quants
///     .upsert(&mut tx, Upsert::on(StockQuant::QUANT_KEY)
///         .rows(rows)                                       // Vec<Vals<StockQuant>>
///         .update([StockQuant::IN_DATE])                    // overwrite when it differs
///         .accumulate(StockQuant::QUANTITY)                 // existing + row value
///         .accumulate_floor(StockQuant::RESERVED_QUANTITY, 0.0)) // GREATEST(0, existing + value)
///     .await?;
/// ```
///
/// Without `update` and `accumulate` the call is get-or-create.
#[must_use = "an upsert does nothing until it is passed to RecordSet::upsert"]
pub struct Upsert<M> {
    call: UpsertCall,
    _m: PhantomData<fn() -> M>,
}

impl<M> Clone for Upsert<M> {
    fn clone(&self) -> Self {
        Self {
            call: self.call.clone(),
            _m: PhantomData,
        }
    }
}

impl<M> std::fmt::Debug for Upsert<M> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Upsert").field("call", &self.call).finish()
    }
}

impl<M: Model> Upsert<M> {
    /// An upsert on `key`, with no rows.
    pub fn on(key: KeyRef<M>) -> Self {
        Self {
            call: UpsertCall::new(key.name()),
            _m: PhantomData,
        }
    }

    /// Append rows.
    pub fn rows(mut self, rows: impl IntoIterator<Item = Vals<M>>) -> Self {
        self.call = self.call.with_rows(rows.into_iter().map(Vals::into_raw));
        self
    }

    /// Overwrite these fields on conflict when they differ (cumulative: call it once per field
    /// type when the fields have different value types).
    pub fn update<F: FieldOf<M>>(mut self, fields: impl IntoIterator<Item = F>) -> Self {
        self.call = self
            .call
            .with_update(fields.into_iter().map(FieldOf::field_name));
        self
    }

    /// Add the row's value to the existing value.
    pub fn accumulate<P: Model, T: Accumulable>(mut self, field: Field<P, T>) -> Self
    where
        M: Inherits<P>,
    {
        self.call = self.call.with_accumulate(field.name());
        self
    }

    /// Store `GREATEST(floor, existing + value)`; a new row below the floor fails the call.
    pub fn accumulate_floor<P: Model, T: Accumulable>(
        mut self,
        field: Field<P, T>,
        floor: T,
    ) -> Self
    where
        M: Inherits<P>,
    {
        self.call = self
            .call
            .with_accumulate_floor(field.name(), floor.into_cell());
        self
    }

    /// The untyped call.
    pub fn into_call(self) -> UpsertCall {
        self.call
    }
}

/// The result of one input row.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct UpsertedRow {
    id: RecId,
    outcome: UpsertOutcome,
    previous_version: Option<i64>,
    version: Option<i64>,
}

impl UpsertedRow {
    /// The record (rows that share a key share it).
    pub fn id(&self) -> RecId {
        self.id
    }

    /// What happened to the row.
    pub fn outcome(&self) -> UpsertOutcome {
        self.outcome
    }

    /// The row version before the call: `None` for an inserted row and for models without row
    /// versions; for an unchanged row, its current version.
    pub fn previous_version(&self) -> Option<i64> {
        self.previous_version
    }

    /// The row version after the call (`None` for models without row versions).
    pub fn version(&self) -> Option<i64> {
        self.version
    }
}

/// The result of an upsert: one [`UpsertedRow`] per input row, in input order.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct UpsertResult {
    rows: Vec<UpsertedRow>,
}

impl UpsertResult {
    /// One entry per input row, in input order.
    pub fn rows(&self) -> &[UpsertedRow] {
        &self.rows
    }

    /// Number of input rows.
    pub fn len(&self) -> usize {
        self.rows.len()
    }

    /// No input rows.
    pub fn is_empty(&self) -> bool {
        self.rows.is_empty()
    }

    /// The ids of the input rows, in input order (rows sharing a key repeat their id).
    pub fn ids(&self) -> Vec<RecId> {
        self.rows.iter().map(|r| r.id).collect()
    }

    /// The distinct ids, in first-occurrence order.
    pub fn distinct_ids(&self) -> Vec<RecId> {
        let mut seen = FxHashSet::default();
        self.rows
            .iter()
            .map(|r| r.id)
            .filter(|id| seen.insert(*id))
            .collect()
    }
}

