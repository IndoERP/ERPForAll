/// A business key of model `M`: generated by `keys = [key(name = "_quant_key", ...)]` as the
/// associated constant `QUANT_KEY` (the name without its leading `_`, upper-cased).
pub struct KeyRef<M> {
    name: &'static str,
    _m: PhantomData<fn() -> M>,
}

impl<M> KeyRef<M> {
    /// For macro output (needs the macro token).
    #[doc(hidden)]
    pub const fn new(name: &'static str, _token: Token) -> Self {
        Self {
            name,
            _m: PhantomData,
        }
    }

    /// The declared name (e.g. `_quant_key`).
    pub const fn name(&self) -> &'static str {
        self.name
    }
}

impl<M> Clone for KeyRef<M> {
    fn clone(&self) -> Self {
        *self
    }
}

impl<M> Copy for KeyRef<M> {}

impl<M> std::fmt::Debug for KeyRef<M> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "KeyRef({})", self.name)
    }
}

/// What an upsert did with an input row.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum UpsertOutcome {
    /// The key was new: the row was inserted.
    Inserted,
    /// The key existed and an `update` or `accumulate` field changed it.
    Updated,
    /// The key existed and nothing changed (every value already equal, every delta zero, or a
    /// get-or-create call without `update`/`accumulate`): the row was not written.
    Unchanged,
}

/// An upsert on the untyped surface: what overrides of `upsert` receive and pass to `super`.
/// Built by [`Upsert`] on the typed surface or directly:
///
/// ```
/// use erp_orm::{RawVals, UpsertCall};
/// use erp_fields::Cell;
///
/// let call = UpsertCall::new("_quant_key")
///     .with_rows([RawVals::new().set_cell("product_id", Cell::Id(1)).set_cell("quantity", Cell::Float(5.0))])
///     .with_accumulate("quantity");
/// assert_eq!((call.key(), call.rows().len()), ("_quant_key", 1));
/// ```
#[derive(Debug, Clone, PartialEq)]
pub struct UpsertCall {
    key: Cow<'static, str>,
    rows: Vec<RawVals>,
    update: Vec<Cow<'static, str>>,
    accumulate: Vec<(Cow<'static, str>, Option<Cell>)>,
}

impl UpsertCall {
    /// An upsert on the business key declared as `key` (e.g. `_quant_key`), with no rows.
    pub fn new(key: impl Into<Cow<'static, str>>) -> Self {
        Self {
            key: key.into(),
            rows: Vec::new(),
            update: Vec::new(),
            accumulate: Vec::new(),
        }
    }

    /// Append rows. Each row sets every key field (a NULL part is a value: "none").
    #[must_use]
    pub fn with_rows(mut self, rows: impl IntoIterator<Item = RawVals>) -> Self {
        self.rows.extend(rows);
        self
    }

    /// Overwrite these fields of existing rows from the input when they differ.
    #[must_use]
    pub fn with_update<S: Into<Cow<'static, str>>>(
        mut self,
        fields: impl IntoIterator<Item = S>,
    ) -> Self {
        self.update.extend(fields.into_iter().map(Into::into));
        self
    }

    /// Add the row's value to the existing value of this integer, float or monetary field (a NULL
    /// existing value counts as 0).
    #[must_use]
    pub fn with_accumulate(mut self, field: impl Into<Cow<'static, str>>) -> Self {
        self.accumulate.push((field.into(), None));
        self
    }

    /// Like [`UpsertCall::with_accumulate`], storing `GREATEST(floor, existing + value)`. A new
    /// row whose value is below the floor fails the call.
    #[must_use]
    pub fn with_accumulate_floor(
        mut self,
        field: impl Into<Cow<'static, str>>,
        floor: Cell,
    ) -> Self {
        self.accumulate.push((field.into(), Some(floor)));
        self
    }

    /// The key's declared name.
    pub fn key(&self) -> &str {
        &self.key
    }

    /// The rows, in input order.
    pub fn rows(&self) -> &[RawVals] {
        &self.rows
    }

    /// The rows, for overrides that adjust them before calling `super`.
    pub fn rows_mut(&mut self) -> &mut Vec<RawVals> {
        &mut self.rows
    }

    /// The fields overwritten on conflict.
    pub fn update(&self) -> impl Iterator<Item = &str> {
        self.update.iter().map(AsRef::as_ref)
    }

    /// The accumulated fields with their floors.
    pub fn accumulate(&self) -> impl Iterator<Item = (&str, Option<&Cell>)> {
        self.accumulate
            .iter()
            .map(|(f, c)| (f.as_ref(), c.as_ref()))
    }
}

