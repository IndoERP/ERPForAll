impl Records {
    /// `upsert(call)` through the method chain (`base` implements it, see the module
    /// documentation). A `Validation` error, or any error once rows were written, poisons the
    /// transaction (F1): no partial upsert can be committed.
    ///
    /// # Errors
    ///
    /// `Programming` for a call the model cannot take (unknown key, a key that cannot arbitrate,
    /// a field that is not a column of the model's table, a server-set field such as `id`,
    /// `create_date` or `row_version`, a row without a key field, computed defaults not given, …;
    /// the texts are in the design note §10); `Access` when the model or a record rule refuses the
    /// create or the write (naming only records the caller may read); `Validation` for invalid
    /// values, constraint violations, accumulated values out of range, and a key whose existing
    /// record the write rule refuses and the caller may not read (the key's declared message, no
    /// id). Explicit generated output rows, update/accumulate targets and context defaults
    /// return `Validation` with the generated read-only message before method dispatch.
    /// Event-relevant scalar upserts require an OperationIdentity and capture actual returned
    /// physical inserts/changes under the writer, including deferred compute provenance.
    /// Relation/bulk capture and nested event-relevant side effects remain unsupported.
    pub async fn upsert(&self, tx: &mut Transaction, call: UpsertCall) -> Result<UpsertResult> {
        tx.admit_records(self).await?;
        tx.check_capture_create(self, &call.rows)?;
        let before = tx.mutations();
        let guard = tx.guard();
        let result = match crate::database_generated::check_write_names(
            tx,
            self.spec(),
            call.rows
                .iter()
                .flat_map(|v| v.names())
                .chain(call.update.iter().map(|name| name.as_ref()))
                .chain(call.accumulate.iter().map(|(name, _)| name.as_ref()))
                .chain(self.env().context().default_field_names()),
        ) {
            Ok(()) => call_method::<(UpsertCall,), UpsertResult>(tx, self, "upsert", (call,)).await,
            Err(error) => Err(error),
        };
        if let Err(error) = &result {
            tx.poison_after(before, error);
        }
        guard.disarm();
        result
    }

    /// `upsert` with dynamic values (Luau, data files; JSON-2 when exposes it): rows as
    /// `{field: value}` maps, converted by the one converter; floors converted for their field.
    ///
    /// # Errors
    ///
    /// As [`Records::upsert`]; conversion errors of values and floors.
    pub async fn upsert_values(
        &self,
        tx: &mut Transaction,
        key: &str,
        rows: &[BTreeMap<String, Value>],
        update: &[&str],
        accumulate: &[(&str, Option<Value>)],
    ) -> Result<UpsertResult> {
        tx.admit_records(self).await?;
        let spec = self.spec();
        crate::database_generated::check_write_names(
            tx,
            spec,
            rows.iter()
                .flat_map(|row| row.keys().map(String::as_str))
                .chain(update.iter().copied())
                .chain(accumulate.iter().map(|(name, _)| *name)),
        )?;
        let vals = rows
            .iter()
            .map(|row| self.vals_from_values(row))
            .collect::<Result<Vec<_>>>()?;
        let mut call = UpsertCall::new(key.to_owned())
            .with_rows(vals)
            .with_update(update.iter().map(|f| (*f).to_owned()));
        for (name, floor) in accumulate {
            call = match floor {
                None => call.with_accumulate((*name).to_owned()),
                Some(value) => {
                    let field = spec
                        .field(name)
                        .ok_or_else(|| upsert_error(spec, format!("no field '{name}'")))?;
                    let cell = to_cell(fref(spec, field), &field.ty, value)?;
                    call.with_accumulate_floor((*name).to_owned(), cell)
                }
            };
        }
        self.upsert(tx, call).await
    }
}

impl<M: Model> RecordSet<M> {
    /// The typed upsert ([`Upsert`]); see [`Records::upsert`].
    ///
    /// # Errors
    ///
    /// As [`Records::upsert`].
    pub async fn upsert(&self, tx: &mut Transaction, upsert: Upsert<M>) -> Result<Upserted<M>> {
        let result = self.as_records().upsert(tx, upsert.into_call()).await?;
        let records = RecordSet::unchecked(self.as_records().browse_ids(result.distinct_ids()));
        Ok(Upserted { result, records })
    }
}

// ---- checks ---------------------------------------------------------------------------------

fn upsert_error(spec: &ModelSpec, message: impl std::fmt::Display) -> Error {
    Error::programming(format!("upsert on '{}': {message}", spec.name))
}

fn fref<'a>(spec: &'a ModelSpec, field: &'a FieldSpec) -> FieldRef<'a> {
    FieldRef {
        model: spec.name,
        field: field.name,
        label: &field.string,
    }
}

/// Whether the server sets `field` and callers never do: the id, the audit fields of a model with
/// log access (by name, as `create` treats them), the row version, the parent path.
fn is_server_set(spec: &ModelSpec, field: &FieldSpec) -> bool {
    matches!(field.ty, FieldType::Id | FieldType::RowVersion)
        || field.server_set
        || field.magic
        || (spec.log_access && MAGIC_FIELD_NAMES.contains(&field.name))
        || spec.parent_path == Some(field.id)
}

/// A field the call may write: a column of the model's own table that callers may set.
fn writable_column<'s>(spec: &'s ModelSpec, name: &str) -> Result<&'s FieldSpec> {
    let field = spec
        .field(name)
        .ok_or_else(|| upsert_error(spec, format!("no field '{name}'")))?;
    crate::database_generated::check_assignment(spec, field)?;
    if is_server_set(spec, field) {
        return Err(server_set_error(fref(spec, field)));
    }
    if field.inherited.is_some() || field.column().is_none() {
        return Err(upsert_error(
            spec,
            format!(
                "field '{name}' is not a column of the model's own table (inherited, x2many or not \
                 stored)"
            ),
        ));
    }
    // `create` drops a caller value of a readonly precomputed field (COMP §4.9), and a stored
    // computed field without `precompute` is precomputed by default; the upsert
    // refuses any readonly stored computed or related field without an inverse instead of storing
    // a value the compute would overwrite (review SEC-S2, round 2)
    if (field.compute.is_some() || field.related.is_some())
        && field.store
        && field.readonly
        && field.inverse.is_none()
    {
        return Err(upsert_error(
            spec,
            format!(
                "field '{name}' is a readonly stored computed or related field: it is always \
                 computed and a caller value is refused"
            ),
        ));
    }
    Ok(field)
}

/// The validated shape of a call.
struct Plan<'s> {
    key: &'s BusinessKey,
    update: Vec<FieldId>,
    /// `(field, floor)`.
    accumulate: Vec<(FieldId, Option<Cell>)>,
}

impl Plan<'_> {
    fn has_floor(&self) -> bool {
        self.accumulate.iter().any(|(_, f)| f.is_some())
    }

    fn is_update(&self) -> bool {
        !self.update.is_empty() || !self.accumulate.is_empty()
    }
}

fn plan<'s>(spec: &'s ModelSpec, call: &UpsertCall) -> Result<Plan<'s>> {
    if !spec.has_table() {
        return Err(upsert_error(
            spec,
            "the model has no table (abstract model)",
        ));
    }
    if spec.parent_path.is_some() {
        return Err(upsert_error(
            spec,
            "models with _parent_store are not supported (the parent path is maintained by \
             create and write)",
        ));
    }
    if let Some(partition) = spec.partition {
        return Err(upsert_error(
            spec,
            format!(
                "rows of a partitioned model are inserted with create, not upserted (a unique \
                 constraint of a partitioned table must include the partition key '{}', which the \
                 server sets on every insert)",
                partition.key_name()
            ),
        ));
    }
    let key = spec.business_key(call.key()).ok_or_else(|| {
        let declared: Vec<&str> = spec.business_keys().iter().map(|k| k.name).collect();
        upsert_error(
            spec,
            format!(
                "no business key '{}' (declared keys: {})",
                call.key(),
                if declared.is_empty() {
                    "none".to_owned()
                } else {
                    declared.join(", ")
                }
            ),
        )
    })?;
    if let Some(reason) = key.arbitration_refusal() {
        return Err(upsert_error(
            spec,
            format!("key '{}' cannot arbitrate an upsert ({reason})", key.name),
        ));
    }
    let mut named: Vec<FieldId> = Vec::new();
    let mut check = |name: &str| -> Result<&'s FieldSpec> {
        let field = spec
            .field(name)
            .ok_or_else(|| upsert_error(spec, format!("no field '{name}'")))?;
        if key.fields.contains(&field.id) {
            return Err(upsert_error(
                spec,
                format!("key field '{name}' cannot be updated on conflict"),
            ));
        }
        let field = writable_column(spec, name)?;
        if named.contains(&field.id) {
            return Err(upsert_error(
                spec,
                format!("field '{name}' is named twice in update and accumulate"),
            ));
        }
        named.push(field.id);
        Ok(field)
    };
    let mut update = Vec::new();
    for name in call.update() {
        update.push(check(name)?.id);
    }
    let mut accumulate = Vec::new();
    for (name, floor) in call.accumulate() {
        let field = check(name)?;
        if !matches!(
            field.ty,
            FieldType::Integer | FieldType::Float { .. } | FieldType::Monetary { .. }
        ) {
            return Err(upsert_error(
                spec,
                format!(
                    "accumulate needs an integer, float or monetary field; '{name}' is {}",
                    field.ty.type_name()
                ),
            ));
        }
        let floor = match floor {
            None => None,
            Some(Cell::Null) => {
                return Err(upsert_error(
                    spec,
                    format!("the floor of '{name}' is empty"),
                ));
            }
            Some(cell) => Some(validate_cell(fref(spec, field), &field.ty, cell.clone())?),
        };
        accumulate.push((field.id, floor));
    }
    Ok(Plan {
        key,
        update,
        accumulate,
    })
}

