//! B6 native integrity declaration acceptance. Fixture models ship no default data.
#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    reason = "tests"
)]
use erp_registry::*;

static ADDON: AddonDescriptor = AddonDescriptor {
    name: "test_integrity",
    depends: &["base"],
    exact_only: false,
};
fn leak<T>(v: T) -> &'static T {
    Box::leak(Box::new(v))
}
fn models() -> Vec<ModelDecl> {
    vec![
        ModelDecl::new(ADDON.name, "integrity.parent")
            .fields(const { &[FieldDecl::integer("company").required(true)] })
            .table_objects(
                const {
                    &[TableObjectDecl {
                        name: "_company_id",
                        kind: TableObjectKind::Key(KeyDecl::new(
                            &["company", "id"],
                            "Unique pair.",
                        )),
                    }]
                },
            ),
        ModelDecl::new(ADDON.name, "integrity.child").fields(
            const {
                &[
                    FieldDecl::integer("company").required(true),
                    FieldDecl::many2one("reference_id", "integrity.parent"),
                ]
            },
        ),
    ]
}
fn foreign(
    columns: &'static [&'static str],
    targets: &'static [&'static str],
) -> SqlForeignKeyDecl {
    SqlForeignKeyDecl::new(
        "Integrity$fk",
        "integrity.child",
        columns,
        "integrity.parent",
        targets,
        SqlForeignKeyTarget::Key("_company_id"),
    )
}
fn fk(f: SqlForeignKeyDecl) -> SqlObjectDecl {
    SqlObjectDecl::foreign_key(ADDON.name, "fk", f)
}
fn build(
    decls: Vec<SqlObjectDecl>,
    models: Vec<ModelDecl>,
    limits: SqlObjectLimits,
) -> erp_fields::Result<Registry> {
    let keys = Box::leak(
        decls
            .iter()
            .map(SqlObjectDecl::key)
            .collect::<Vec<_>>()
            .into_boxed_slice(),
    );
    RegistryBuilder::new([&ADDON])
        .with_decls(models.into_iter().map(leak))
        .require_sql_objects([leak(SqlObjectManifest::new(ADDON.name, keys))])
        .with_sql_objects(decls.into_iter().map(leak))
        .sql_object_limits(limits)
        .build()
}
#[test]
fn render_fk_actions_and_shape() {
    let declaration = foreign(&["company", "reference_id"], &["company", "id"])
        .on_delete(SqlForeignKeyAction::SetNull(&["reference_id"]))
        .deferral(SqlDeferral::InitiallyDeferred);
    let registry = build(vec![fk(declaration)], models(), SqlObjectLimits::default()).unwrap();
    let object = registry.sql_objects().get(ADDON.name, "fk").unwrap();
    let SqlObjectKind::ForeignKey(f) = object.kind() else {
        panic!("foreign key")
    };
    assert_eq!(
        erp_sql::sqlobj::create_foreign_key(f, true),
        r#"ALTER TABLE "integrity_child" ADD CONSTRAINT "Integrity$fk" FOREIGN KEY ("company", "reference_id") REFERENCES "integrity_parent" ("company", "id") ON DELETE SET NULL ("reference_id") DEFERRABLE INITIALLY DEFERRED NOT VALID"#
    );
    let old = erp_sql::sqlobj::shape_payload(object);
    let changed = build(
        vec![fk(declaration.on_delete(SqlForeignKeyAction::Restrict))],
        models(),
        SqlObjectLimits::default(),
    )
    .unwrap();
    assert_eq!(
        erp_sql::sqlobj::shape_change(changed.sql_objects().get(ADDON.name, "fk").unwrap(), &old)
            .unwrap(),
        Some("delete action")
    );
}
#[test]
fn render_unlogged_without_table_rewrite() {
    let sql = erp_sql::ddl::create_table_with_persistence(
        "t",
        "Table",
        &[],
        None,
        None,
        SqlTablePersistence::Unlogged,
    );
    assert!(sql[0].starts_with(r#"CREATE UNLOGGED TABLE "t" ("#));
    assert!(sql[0].contains("GENERATED BY DEFAULT AS IDENTITY"));
    assert_eq!(sql[1], r#"COMMENT ON TABLE "t" IS 'Table'"#);
    assert!(sql.iter().all(|s| !s.contains("ALTER TABLE")));
    assert_eq!(
        erp_sql::ddl::create_table("t", "Table", &[], None, None),
        erp_sql::ddl::create_table_with_persistence(
            "t",
            "Table",
            &[],
            None,
            None,
            SqlTablePersistence::Logged
        )
    );
}
