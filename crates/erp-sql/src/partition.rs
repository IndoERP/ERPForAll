//! Partitioned tables and the statements of partition upkeep (
//! –§7.7). Leaf models only: their primary key is `(id, key)` and
//! they are partitioned by range of a server-set timestamp.
//!
//! New partitions are created as standalone tables (`CREATE TABLE … (LIKE parent …)`) and attached
//! with `ATTACH PARTITION`, which takes only `SHARE UPDATE EXCLUSIVE` on the parent, so writers
//! keep inserting. Retired partitions are marked, detached with `DETACH PARTITION … CONCURRENTLY`
//! (never inside a transaction block) and dropped; there is never a default partition, which would
//! forbid the concurrent detach.

use erp_fields::DateTime;

use crate::ddl::{ColumnDef, comment_on_column};
use crate::{literal, quote};

/// The two-key advisory lock space of partition upkeep: `pg_advisory_lock(PARTITION_LOCK_SPACE,
/// hashtext(<table>))` serializes the upkeep calls of one partitioned table across processes, and
/// the schema sync takes the same lock (transaction-scoped) while it creates partitions.
pub const PARTITION_LOCK_SPACE: i32 = 1_701;

/// The advisory lock space of the stepwise partitioned-index builds: `pg_try_advisory_lock(
/// STEP_LOCK_SPACE, hashtext(<index name>))` is held by the runner of a step for the step's whole
/// duration, so two runners of one index build cannot break each other (one would see the other's
/// in-progress concurrent build as invalid and drop it). It is deliberately a different space from
/// [`PARTITION_LOCK_SPACE`]: upkeep and schema sync never take or wait on it, and the step only
/// ever try-locks it, so it takes part in no wait cycle.
pub const STEP_LOCK_SPACE: i32 = 1_702;

/// The key column must be among `columns` and `NOT NULL`.
///
/// ```
/// use erp_fields::ColumnType;
/// use erp_sql::ddl::ColumnDef;
/// let columns = [ColumnDef {
///     name: "create_date".into(),
///     ty: ColumnType::Timestamp,
///     not_null: true,
///     comment: "Created on".into(),
///     generated: None,
/// }];
/// let sql = erp_sql::partition::create_partitioned_table("t", "T", &columns, "create_date");
/// assert_eq!(
///     sql[0],
///     "CREATE TABLE \"t\" (\"id\" int8 GENERATED BY DEFAULT AS IDENTITY, \"create_date\" \
///      timestamp NOT NULL, PRIMARY KEY(\"id\", \"create_date\")) PARTITION BY RANGE \
///      (\"create_date\")"
/// );
/// ```
pub fn create_partitioned_table(
    table: &str,
    comment: &str,
    columns: &[ColumnDef],
    key: &str,
) -> Vec<String> {
    let mut cols: Vec<&ColumnDef> = columns.iter().collect();
    cols.sort_by_key(|c| c.ty.rank());
    let mut parts = vec![format!(
        "{} int8 GENERATED BY DEFAULT AS IDENTITY",
        quote("id")
    )];
    for c in &cols {
        let col_sql = if let Some(col_gen) = &c.generated {
            format!(
                "{} {} GENERATED ALWAYS AS ({}) {}{}",
                quote(&c.name),
                c.ty.sql(),
                col_gen.expression,
                col_gen.storage.as_str().to_uppercase(),
                if c.not_null { " NOT NULL" } else { "" }
            )
        } else {
            format!(
                "{} {}{}",
                quote(&c.name),
                c.ty.sql(),
                if c.not_null { " NOT NULL" } else { "" }
            )
        };
        parts.push(col_sql);
    }
    parts.push(format!("PRIMARY KEY({}, {})", quote("id"), quote(key)));
    let mut out = vec![format!(
        "CREATE TABLE {} ({}) PARTITION BY RANGE ({})",
        quote(table),
        parts.join(", "),
        quote(key)
    )];
    out.push(format!(
        "COMMENT ON TABLE {} IS {}",
        quote(table),
        literal(comment)
    ));
    for c in &cols {
        out.push(comment_on_column(table, &c.name, &c.comment));
    }
    out
}

/// The `FOR VALUES FROM (…) TO (…)` bound of the partition covering `[from, to)`. ISO literals,
/// which PostgreSQL reads whatever the session's `DateStyle`.
fn bound(from: DateTime, to: DateTime) -> String {
    format!(
        "FOR VALUES FROM ({}) TO ({})",
        literal(&from.to_string()),
        literal(&to.to_string())
    )
}

/// A new standalone table shaped like `parent` (columns, `NOT NULL`, `CHECK` constraints), to be
/// attached as partition `name`. The parent's identity, primary key, indexes and foreign keys come
/// with the attachment.
pub fn create_partition(parent: &str, name: &str) -> String {
    format!(
        "CREATE TABLE {} (LIKE {} INCLUDING DEFAULTS INCLUDING GENERATED INCLUDING CONSTRAINTS)",
        quote(name),
        quote(parent)
    )
}

/// `ALTER TABLE parent ATTACH PARTITION name FOR VALUES FROM (from) TO (to)`: `SHARE UPDATE
/// EXCLUSIVE` on the parent, so concurrent inserts and reads go on.
pub fn attach_partition(parent: &str, name: &str, from: DateTime, to: DateTime) -> String {
    format!(
        "ALTER TABLE {} ATTACH PARTITION {} {}",
        quote(parent),
        quote(name),
        bound(from, to)
    )
}

/// The partition `name` of `parent` for `[from, to)`, created and attached unless it exists
/// already, as one statement that does not trust the caller's snapshot (schema sync runs at
/// `REPEATABLE READ`, so its catalog read may predate a partition another process attached since):
/// the existence test reads the current catalog. A table of that name that is not a partition of
/// `parent` is an error (SQLSTATE `42P07`).
pub fn ensure_partition_block(parent: &str, name: &str, from: DateTime, to: DateTime) -> String {
    let (p, n) = (quote(parent), quote(name));
    let (p_lit, n_lit) = (literal(&p), literal(&n));
    format!(
        "DO $erp$ BEGIN IF to_regclass({n_lit}) IS NULL THEN {create}; {attach}; ELSIF NOT EXISTS \
         (SELECT FROM pg_partition_tree({p_lit}::regclass) WHERE relid = to_regclass({n_lit}) AND \
         level = 1) THEN RAISE EXCEPTION 'table % exists and is not a partition of %', {n_lit}, \
         {p_lit} USING ERRCODE = '42P07'; END IF; END $erp$",
        create = create_partition(parent, name),
        attach = attach_partition(parent, name, from, to),
    )
}

/// `DETACH PARTITION … CONCURRENTLY`: two transactions of its own, so it never runs inside a
/// transaction block; an interruption leaves the partition pending detach (finished by
/// [`detach_finalize`]).
pub fn detach_concurrently(parent: &str, name: &str) -> String {
    format!(
        "ALTER TABLE {} DETACH PARTITION {} CONCURRENTLY",
        quote(parent),
        quote(name)
    )
}

/// `DETACH PARTITION … FINALIZE`: completes a detach that was interrupted.
pub fn detach_finalize(parent: &str, name: &str) -> String {
    format!(
        "ALTER TABLE {} DETACH PARTITION {} FINALIZE",
        quote(parent),
        quote(name)
    )
}

/// `DETACH PARTITION … FINALIZE` of `name`, only when `name` is still a partition (attached or
/// pending detach) in the current catalog: one statement that does not trust the caller's snapshot
/// (schema sync runs at `REPEATABLE READ`, so its catalog read may predate a finalize). The test is
/// [`STILL_PARTITION_QUERY`]'s, which reads the relation cache, not the transaction's snapshot; a
/// table that is gone or standalone already is a no-op, where a plain `FINALIZE` fails with
/// `There's no pending concurrent detach`.
pub fn detach_finalize_if_pending(parent: &str, name: &str) -> String {
    format!(
        "DO $erp$ BEGIN IF pg_get_partition_constraintdef(to_regclass({n_lit})) IS NOT NULL THEN \
         {finalize}; END IF; END $erp$",
        n_lit = literal(&quote(name)),
        finalize = detach_finalize(parent, name),
    )
}

/// Whether the table in `$1` (a quoted table name) is still a partition, attached or pending
/// detach, in the current catalog: `pg_get_partition_constraintdef` is `NULL` for a table that is
/// not a partition (and for one that does not exist) and looks the relation up in the relation
/// cache, so a finalize committed after the caller's `REPEATABLE READ` snapshot is seen. One row,
/// one `bool`.
pub const STILL_PARTITION_QUERY: &str =
    "SELECT pg_get_partition_constraintdef(to_regclass($1::text)) IS NOT NULL";

/// `inhdetachpending` of the table named in `$1` (`text`, unquoted): one row when it is a
/// partition (attached, or pending detach), none otherwise.
pub const DETACH_STATE_QUERY: &str = "SELECT i.inhdetachpending FROM pg_inherits i \
     JOIN pg_class c ON c.oid = i.inhrelid JOIN pg_namespace n ON n.oid = c.relnamespace \
     WHERE n.nspname = current_schema() AND c.relname = $1::text";

/// `COMMENT ON TABLE name IS NULL`: removes the retired marker of a partition whose detach failed
/// and left it attached, so a later manual detach is never taken for an interrupted retirement.
pub fn unmark_retired(name: &str) -> String {
    format!("COMMENT ON TABLE {} IS NULL", quote(name))
}

/// The comment that marks a partition of `parent` as being retired: set before the detach, so a
/// table left behind by an interrupted retirement is recognised and dropped by a later run, and a
/// table someone detached for another reason is never dropped.
pub fn retired_marker(parent: &str) -> String {
    format!("erp:retired partition of {parent}")
}

/// `COMMENT ON TABLE name IS '<retired marker>'`.
pub fn mark_retired(parent: &str, name: &str) -> String {
    format!(
        "COMMENT ON TABLE {} IS {}",
        quote(name),
        literal(&retired_marker(parent))
    )
}

/// `DROP TABLE name` (a partitioned table takes its partitions along; dependent objects outside
/// the registry make it fail, never cascade).
pub fn drop_table(name: &str) -> String {
    format!("DROP TABLE {}", quote(name))
}

/// `LOCK TABLE … IN ACCESS EXCLUSIVE MODE` for the tables whose partitioning schema sync changes:
/// taken before their emptiness probe, so no row can arrive between the probe and the drop.
pub fn lock_tables(tables: &[&str]) -> String {
    let names: Vec<String> = tables.iter().map(|t| quote(t)).collect();
    format!("LOCK TABLE {} IN ACCESS EXCLUSIVE MODE", names.join(", "))
}

/// The session-scoped partition lock of the table in `$1` (`text`); waits within the session's
/// `lock_timeout`.
pub const SESSION_LOCK: &str = "SELECT pg_advisory_lock(1701, hashtext($1::text))";

/// Tries the session-scoped partition lock of the table in `$1` (`text`) without waiting; returns
/// whether it was taken. The stepwise index build uses this in a bounded retry loop instead of
/// [`SESSION_LOCK`]: a blocked `pg_advisory_lock` statement holds a snapshot, and an upkeep call
/// holding the lock may be waiting (in a detach finalize) for exactly that snapshot to end.
pub const SESSION_TRY_LOCK: &str = "SELECT pg_try_advisory_lock(1701, hashtext($1::text))";

/// Tries the per-step lock of the index named in `$1` (`text`, [`STEP_LOCK_SPACE`]); returns
/// whether it was taken.
pub const STEP_TRY_LOCK: &str = "SELECT pg_try_advisory_lock(1702, hashtext($1::text))";

/// Releases [`STEP_TRY_LOCK`]; returns whether it was held.
pub const STEP_UNLOCK: &str = "SELECT pg_advisory_unlock(1702, hashtext($1::text))";

/// Releases [`SESSION_LOCK`]; returns whether it was held.
pub const SESSION_UNLOCK: &str = "SELECT pg_advisory_unlock(1701, hashtext($1::text))";

/// Whether `table` holds rows, by two measures: `(heap bytes, visible rows exist)`. The heap size
/// (of the table, or summed over the partitions of a partitioned table, which has no heap of its
/// own) does not depend on the transaction's snapshot: a table that was never written has none,
/// whatever concurrent transactions committed.
pub fn rows_probe(table: &str) -> String {
    let t = quote(table);
    format!(
        "SELECT CASE WHEN c.relkind = 'p' THEN (SELECT coalesce(sum(pg_relation_size(p.relid)), \
         0) FROM pg_partition_tree(c.oid) p WHERE p.isleaf) ELSE pg_relation_size(c.oid) \
         END::int8, EXISTS (SELECT FROM {t}) FROM pg_class c WHERE c.oid = {}::regclass",
        literal(&t)
    )
}

/// The transaction-scoped partition locks of the tables in `$1` (a `text[]`), in name order: schema
/// sync takes them before it reads the partition catalog and before any DDL, so an upkeep call
/// never runs between its plan and its statements, and the two never wait for each other while
/// holding a table lock. One row (`void`) per table.
pub const XACT_LOCKS: &str = "SELECT pg_advisory_xact_lock(1701, hashtext(s.t)) FROM (SELECT t FROM \
                              unnest($1::text[]) AS t ORDER BY t OFFSET 0) AS s";

/// Partitioning facts of the tables in `$1` (a `text[]`), as `(kind, table, name, a, b, c)` text
/// rows like [`crate::ddl::CATALOG_QUERY`]:
///
/// - `partkey`: `a` = `pg_get_partkeydef` (e.g. `RANGE (create_date)`);
/// - `partition`: `name` = the partition, `a`/`b` = its lower/upper bound in microseconds since the
///   epoch when both are single timestamps (`NULL` otherwise), `c` = `<detach pending>|<relkind>|
///   <bound as written>`; the bound text is parsed back with the session's own `DateStyle`, so the
///   numbers are right whatever it is; an `infinity` bound is not a timestamp here (`NULL`: the
///   partition is listed as unreadable);
/// - `now`: `a` = the statement's `now()` in microseconds since the epoch (UTC).
pub const PARTITION_CATALOG_QUERY: &str = r#"
SELECT 'partkey'::text, c.relname::text, NULL::text, pg_get_partkeydef(c.oid), NULL::text, NULL::text
  FROM pg_partitioned_table p JOIN pg_class c ON c.oid = p.partrelid
  JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = current_schema() AND c.relname::text = ANY($1)
UNION ALL
SELECT 'partition', pc.relname::text, cc.relname::text, b.lo, b.hi,
       i.inhdetachpending::text || '|' || cc.relkind::text || '|' || r.raw
  FROM pg_inherits i
  JOIN pg_class pc ON pc.oid = i.inhparent
  JOIN pg_class cc ON cc.oid = i.inhrelid
  JOIN pg_namespace n ON n.oid = pc.relnamespace
 CROSS JOIN LATERAL (SELECT pg_get_expr(cc.relpartbound, cc.oid) AS raw) r
 CROSS JOIN LATERAL (SELECT regexp_match(r.raw,
        '^FOR VALUES FROM \(''([^'']*)''\) TO \(''([^'']*)''\)$') AS m) x
 CROSS JOIN LATERAL (SELECT
        CASE WHEN pg_input_is_valid(x.m[1], 'timestamp')
             THEN CASE WHEN isfinite(x.m[1]::timestamp)
                       THEN (extract(epoch FROM x.m[1]::timestamp) * 1000000)::int8::text END END AS lo,
        CASE WHEN pg_input_is_valid(x.m[2], 'timestamp')
             THEN CASE WHEN isfinite(x.m[2]::timestamp)
                       THEN (extract(epoch FROM x.m[2]::timestamp) * 1000000)::int8::text END END AS hi) b
 WHERE n.nspname = current_schema() AND pc.relname::text = ANY($1) AND pc.relkind = 'p'
UNION ALL
SELECT 'now', NULL, NULL, (extract(epoch FROM now()) * 1000000)::int8::text, NULL, NULL"#;

/// Standalone tables of the current schema carrying the retired marker `$1` and named with the
/// prefix `$2` (`<parent>_p`): partitions whose retirement was interrupted after the detach.
pub const RETIRED_TABLES_QUERY: &str = "\
SELECT c.relname::text FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
 WHERE n.nspname = current_schema() AND c.relkind = 'r' AND NOT c.relispartition
   AND starts_with(c.relname::text, $2::text) AND obj_description(c.oid, 'pg_class') = $1::text
 ORDER BY 1";

/// Partitions that carry the retired marker `$1` but are still attached and not pending a detach
/// (`$2` is the name prefix, `$3` the quoted name of the parent table: only its own partitions): a crash between the marker and the detach leaves them. They are
/// live partitions; their marker must go, or a later manual detach would be dropped as a
/// retirement.
pub const ATTACHED_RETIRED_QUERY: &str = "\
SELECT c.relname::text FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
  JOIN pg_inherits i ON i.inhrelid = c.oid
 WHERE n.nspname = current_schema() AND c.relkind = 'r' AND NOT i.inhdetachpending
   AND i.inhparent = $3::text::regclass
   AND starts_with(c.relname::text, $2::text) AND obj_description(c.oid, 'pg_class') = $1::text
 ORDER BY 1";

#[cfg(test)]
mod tests {
    use erp_fields::{ColumnType, Date};

    use super::*;

    fn day(d: u32) -> DateTime {
        Date::from_ymd(2026, 10, d).unwrap().at_midnight()
    }

    #[test]
    fn partitioned_table_shape() {
        let cols = [
            ColumnDef {
                name: "name".into(),
                ty: ColumnType::Varchar(None),
                not_null: false,
                comment: "Name".into(),
                generated: None,
            },
            ColumnDef {
                name: "create_date".into(),
                ty: ColumnType::Timestamp,
                not_null: true,
                comment: "Created on".into(),
                generated: None,
            },
        ];
        let sql = create_partitioned_table("scale_event", "Event", &cols, "create_date");
        assert_eq!(
            sql[0],
            "CREATE TABLE \"scale_event\" (\"id\" int8 GENERATED BY DEFAULT AS IDENTITY, \
             \"name\" varchar, \"create_date\" timestamp NOT NULL, PRIMARY KEY(\"id\", \
             \"create_date\")) PARTITION BY RANGE (\"create_date\")"
        );
        assert_eq!(sql[1], "COMMENT ON TABLE \"scale_event\" IS 'Event'");
        assert_eq!(sql.len(), 4);
    }

    #[test]
    fn partitioned_table_with_generated_column() {
        use erp_fields::{ColumnGenerated, GeneratedStorage};

        let cols = [
            ColumnDef::new("name", ColumnType::Varchar(None)).comment("Name"),
            ColumnDef::new("create_date", ColumnType::Timestamp)
                .not_null(true)
                .comment("Created on"),
            ColumnDef::new("total", ColumnType::Int4)
                .comment("Total")
                .generated(ColumnGenerated::new(
                    GeneratedStorage::Virtual,
                    "\"a\" + \"b\"",
                )),
        ];
        let sql = create_partitioned_table("scale_event", "Event", &cols, "create_date");
        assert_eq!(
            sql[0],
            "CREATE TABLE \"scale_event\" (\"id\" int8 GENERATED BY DEFAULT AS IDENTITY, \
             \"total\" int4 GENERATED ALWAYS AS (\"a\" + \"b\") VIRTUAL, \"name\" varchar, \
             \"create_date\" timestamp NOT NULL, PRIMARY KEY(\"id\", \
             \"create_date\")) PARTITION BY RANGE (\"create_date\")"
        );
    }

    #[test]
    fn upkeep_statements() {
        assert_eq!(
            create_partition("t", "t_p20261016"),
            "CREATE TABLE \"t_p20261016\" (LIKE \"t\" INCLUDING DEFAULTS INCLUDING GENERATED INCLUDING CONSTRAINTS)"
        );
        assert_eq!(
            attach_partition("t", "t_p20261016", day(16), day(17)),
            "ALTER TABLE \"t\" ATTACH PARTITION \"t_p20261016\" FOR VALUES FROM ('2026-10-16 \
             00:00:00') TO ('2026-10-17 00:00:00')"
        );
        assert_eq!(
            detach_concurrently("t", "t_p20261016"),
            "ALTER TABLE \"t\" DETACH PARTITION \"t_p20261016\" CONCURRENTLY"
        );
        assert_eq!(
            detach_finalize("t", "t_p20261016"),
            "ALTER TABLE \"t\" DETACH PARTITION \"t_p20261016\" FINALIZE"
        );
        assert_eq!(
            mark_retired("t", "t_p20261016"),
            "COMMENT ON TABLE \"t_p20261016\" IS 'erp:retired partition of t'"
        );
        assert_eq!(
            unmark_retired("t_p20261016"),
            "COMMENT ON TABLE \"t_p20261016\" IS NULL"
        );
        assert_eq!(
            detach_finalize_if_pending("t", "t_p20261016"),
            "DO $erp$ BEGIN IF pg_get_partition_constraintdef(to_regclass('\"t_p20261016\"')) IS \
             NOT NULL THEN ALTER TABLE \"t\" DETACH PARTITION \"t_p20261016\" FINALIZE; END IF; \
             END $erp$"
        );
        assert_eq!(drop_table("t_p1"), "DROP TABLE \"t_p1\"");
        assert_eq!(
            lock_tables(&["a", "b"]),
            "LOCK TABLE \"a\", \"b\" IN ACCESS EXCLUSIVE MODE"
        );
        assert!(SESSION_LOCK.contains(&PARTITION_LOCK_SPACE.to_string()));
        assert!(SESSION_UNLOCK.contains(&PARTITION_LOCK_SPACE.to_string()));
        assert!(SESSION_TRY_LOCK.contains(&PARTITION_LOCK_SPACE.to_string()));
        assert!(STEP_TRY_LOCK.contains(&STEP_LOCK_SPACE.to_string()));
        assert!(STEP_UNLOCK.contains(&STEP_LOCK_SPACE.to_string()));
        assert_ne!(STEP_LOCK_SPACE, PARTITION_LOCK_SPACE);
        assert_eq!(
            ensure_partition_block("t", "t_p20261016", day(16), day(17)),
            "DO $erp$ BEGIN IF to_regclass('\"t_p20261016\"') IS NULL THEN CREATE TABLE \
             \"t_p20261016\" (LIKE \"t\" INCLUDING DEFAULTS INCLUDING GENERATED INCLUDING CONSTRAINTS); ALTER TABLE \
             \"t\" ATTACH PARTITION \"t_p20261016\" FOR VALUES FROM ('2026-10-16 00:00:00') TO \
             ('2026-10-17 00:00:00'); ELSIF NOT EXISTS (SELECT FROM \
             pg_partition_tree('\"t\"'::regclass) WHERE relid = to_regclass('\"t_p20261016\"') \
             AND level = 1) THEN RAISE EXCEPTION 'table % exists and is not a partition of %', \
             '\"t_p20261016\"', '\"t\"' USING ERRCODE = '42P07'; END IF; END $erp$"
        );
        assert_eq!(
            rows_probe("t"),
            "SELECT CASE WHEN c.relkind = 'p' THEN (SELECT coalesce(sum(pg_relation_size(p.relid)), \
             0) FROM pg_partition_tree(c.oid) p WHERE p.isleaf) ELSE pg_relation_size(c.oid) \
             END::int8, EXISTS (SELECT FROM \"t\") FROM pg_class c WHERE c.oid = \
             '\"t\"'::regclass"
        );
        assert!(XACT_LOCKS.contains(&PARTITION_LOCK_SPACE.to_string()));
    }
}
