    #[test]
    fn typed_index_definitions() {
        use erp_registry::{IndexDecl, IndexMethod};
        let def = |index: IndexDecl, unaccent| typed_index_definition(&index, unaccent, None);
        assert_eq!(
            def(
                IndexDecl::new(&["d"]).method(IndexMethod::Brin),
                Unaccent::Off
            ),
            "USING brin (\"d\")"
        );
        // trigram keys are folded like `ilike` when folding is indexable, every one of them
        assert_eq!(
            def(
                IndexDecl::new(&["a", "b"]).method(IndexMethod::Trigram),
                Unaccent::Indexable
            ),
            "USING gin (erp_unaccent(\"a\") gin_trgm_ops, erp_unaccent(\"b\") gin_trgm_ops)"
        );
        assert_eq!(
            def(
                IndexDecl::new(&["a"]).method(IndexMethod::Trigram),
                Unaccent::Present
            ),
            "USING gin (\"a\" gin_trgm_ops)"
        );
        let trigram_idx = IndexDecl::new(&["name", "plain"]).method(IndexMethod::Trigram);
        assert_eq!(
            typed_index_definition_with_translated(&trigram_idx, Unaccent::Indexable, None, |f| f
                == "name"),
            "USING gin (erp_unaccent((jsonb_path_query_array(\"name\", '$.*')::text)) gin_trgm_ops, erp_unaccent(\"plain\") gin_trgm_ops)"
        );
        assert_eq!(
            typed_index_definition_with_translated(&trigram_idx, Unaccent::Off, None, |f| f
                == "name"),
            "USING gin ((jsonb_path_query_array(\"name\", '$.*')::text) gin_trgm_ops, \"plain\" gin_trgm_ops)"
        );
        // other methods never fold
        assert_eq!(
            def(IndexDecl::new(&["a"]), Unaccent::Indexable),
            "USING btree (\"a\")"
        );
        assert_eq!(
            def(
                IndexDecl::new(&["r", "s"])
                    .method(IndexMethod::Gist)
                    .include(&["x"]),
                Unaccent::Off
            ),
            "USING gist (\"r\", \"s\") INCLUDE (\"x\")"
        );
        // identifiers are quoted
        assert_eq!(
            def(IndexDecl::new(&["we\"ird"]), Unaccent::Off),
            "USING btree (\"we\"\"ird\")"
        );
        // the compiled filter is the last part, in parentheses
        assert_eq!(
            typed_index_definition(
                &IndexDecl::new(&["a"]).include(&["b"]),
                Unaccent::Off,
                Some("\"state\" = 'open'")
            ),
            "USING btree (\"a\") INCLUDE (\"b\") WHERE (\"state\" = 'open')"
        );
    }

