    #[test]
    fn swap_index_name_and_concurrent_statement() {
        let name = "scale_ix_big__d_index";
        let temp = swap_index_name(name);
        assert_eq!(temp, "scale_ix_big__d_index__swap");
        assert!(temp.len() <= 63);

        // long name is shortened to 63 bytes and create_swap_index_concurrently works on it
        let long_name = "x".repeat(60);
        let long_temp = swap_index_name(&long_name);
        assert!(long_temp.len() <= 63);
        let long_stmt = format!("CREATE INDEX \"{long_name}\" ON \"tbl\" (\"col\")");
        let long_swap = create_swap_index_concurrently(&long_stmt, &long_name, &long_temp).unwrap();
        assert_eq!(
            long_swap,
            format!("CREATE INDEX CONCURRENTLY \"{long_temp}\" ON \"tbl\" (\"col\")")
        );

        // statement rewriting
        let stmt = "CREATE INDEX \"scale_ix_big__d_index\" ON \"scale_ix_big\" USING brin (\"d\")";
        let swap_stmt = create_swap_index_concurrently(stmt, name, &temp).unwrap();
        assert_eq!(
            swap_stmt,
            "CREATE INDEX CONCURRENTLY \"scale_ix_big__d_index__swap\" ON \"scale_ix_big\" USING brin (\"d\")"
        );

        let uq_stmt = "CREATE UNIQUE INDEX \"uq_idx\" ON \"tbl\" (\"col\")";
        let swap_uq = create_swap_index_concurrently(uq_stmt, "uq_idx", "uq_idx__swap").unwrap();
        assert_eq!(
            swap_uq,
            "CREATE UNIQUE INDEX CONCURRENTLY \"uq_idx__swap\" ON \"tbl\" (\"col\")"
        );

        // Generators always quote names: refuse other input instead of supporting an unused form.
        let unquoted = "CREATE INDEX uq_idx ON \"tbl\" (\"col\")";
        assert!(create_swap_index_concurrently(unquoted, "uq_idx", "uq_idx__swap").is_none());

        // prefix-collision negative case (old name "uq", statement defines "uq_idx")
        assert!(create_swap_index_concurrently(uq_stmt, "uq", "uq__swap").is_none());
        assert!(create_swap_index_concurrently(unquoted, "uq", "uq__swap").is_none());

        // non-matching index name or statement returns None
        assert!(create_swap_index_concurrently(stmt, "different_name", &temp).is_none());
        assert!(
            create_swap_index_concurrently("ALTER TABLE t ADD COLUMN c text", name, &temp)
                .is_none()
        );
    }
