/// The first step of a business key on a large table: `CREATE UNIQUE INDEX CONCURRENTLY "name" ON
/// "table" ("a", "b") [NULLS NOT DISTINCT]`, which scans the table without blocking writes.
/// `ADD CONSTRAINT … UNIQUE USING INDEX` ([`add_constraint_using_index`]) then adopts it.
pub fn create_key_index_concurrently(
    table: &str,
    name: &str,
    columns: &[&str],
    nulls_distinct: bool,
) -> String {
    let cols: Vec<String> = columns.iter().map(|c| quote(c)).collect();
    format!(
        "CREATE UNIQUE INDEX CONCURRENTLY {} ON {} ({}){}",
        quote(name),
        quote(table),
        cols.join(", "),
        if nulls_distinct {
            ""
        } else {
            " NULLS NOT DISTINCT"
        }
    )
}

/// The second step of a business key on a large table, in one implicit transaction: `ADD
/// CONSTRAINT <name> UNIQUE USING INDEX <index>` (no scan; a short `ACCESS EXCLUSIVE`) and the
/// comment holding the canonical `definition`, as [`add_constraint`] writes it.
pub fn add_constraint_using_index(
    table: &str,
    name: &str,
    index: &str,
    definition: &str,
) -> Vec<String> {
    vec![
        format!(
            "ALTER TABLE {} ADD CONSTRAINT {} UNIQUE USING INDEX {}",
            quote(table),
            quote(name),
            quote(index)
        ),
        format!(
            "COMMENT ON CONSTRAINT {} ON {} IS {}",
            quote(name),
            quote(table),
            literal(definition)
        ),
    ]
}

/// Whether `indexdef` (`pg_get_indexdef`) is exactly the unique index
/// [`create_key_index_concurrently`] builds for these columns: a plain `btree` over the columns in
/// order, `NULLS NOT DISTINCT` as declared, no predicate, expression, `INCLUDE`, ordering or
/// non-default operator class (PostgreSQL prints any of those, so the text would differ). Double
/// quotes and a `schema.` qualification of the table are ignored.
pub fn key_index_matches(
    indexdef: &str,
    schema: Option<&str>,
    table: &str,
    name: &str,
    columns: &[&str],
    nulls_distinct: bool,
) -> bool {
    let actual = indexdef.replace('"', "");
    let tail = if nulls_distinct {
        ""
    } else {
        " NULLS NOT DISTINCT"
    };
    let cols = columns.join(", ");
    let head = format!("CREATE UNIQUE INDEX {name} ON ");
    let rest = format!("{table} USING btree ({cols}){tail}");
    actual == format!("{head}{rest}")
        || schema.is_some_and(|s| actual == format!("{head}{s}.{rest}"))
}

/// A statement that fails with `55P03` and `message` when the per-step lock of `step_key` (the
/// one a running schema step holds, [`crate::partition::STEP_TRY_LOCK`]) is held by another
/// session, and otherwise takes it until the end of the transaction. The install path runs it
/// before it drops an invalid key index, so it never pulls the index from under a running build.
///
/// The two texts go into a dollar-quoted body, so a `$` in either (a name may hold one) is spliced
/// in as `chr(36)`: nothing in them can close the `$erp$` quote.
pub fn guard_key_index_build(step_key: &str, message: &str) -> String {
    format!(
        "DO $erp$ BEGIN IF NOT pg_try_advisory_xact_lock({}, hashtext({})) THEN RAISE EXCEPTION \
         '%', {} USING ERRCODE = '55P03'; END IF; END $erp$",
        crate::partition::STEP_LOCK_SPACE,
        no_dollar_literal(step_key),
        no_dollar_literal(message)
    )
}

/// [`literal`] with every `$` replaced by `chr(36)`, for text inside a dollar-quoted body.
fn no_dollar_literal(text: &str) -> String {
    text.split('$')
        .map(literal)
        .collect::<Vec<_>>()
        .join(" || chr(36) || ")
}

