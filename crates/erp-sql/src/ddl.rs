/// A column to create.
#[derive(Debug, Clone)]
pub struct ColumnDef {
    /// Column name.
    pub name: String,
    /// Type.
    pub ty: ColumnType,
    /// `NOT NULL`.
    pub not_null: bool,
    /// Column comment (the field label).
    pub comment: String,
    /// Generation metadata.
    pub generated: Option<ColumnGenerated>,
}

impl ColumnDef {
    /// Create a new column definition.
    pub fn new(name: impl Into<String>, ty: ColumnType) -> Self {
        Self {
            name: name.into(),
            ty,
            not_null: false,
            comment: String::new(),
            generated: None,
        }
    }

    /// Set `NOT NULL`.
    pub fn not_null(mut self, not_null: bool) -> Self {
        self.not_null = not_null;
        self
    }

    /// Set column comment.
    pub fn comment(mut self, comment: impl Into<String>) -> Self {
        self.comment = comment.into();
        self
    }

    /// Set generation metadata.
    pub fn generated(mut self, generated: ColumnGenerated) -> Self {
        self.generated = Some(generated);
        self
    }
}

/// With `id_sequence` the `id` draws from that shared sequence instead
/// (`"id" int8 DEFAULT nextval('"seq"'::regclass)`); [`create_sequence`] creates it first.
pub fn create_table(
    table: &str,
    comment: &str,
    columns: &[ColumnDef],
    fillfactor: Option<u8>,
    id_sequence: Option<&str>,
) -> Vec<String> {
    let mut cols: Vec<&ColumnDef> = columns.iter().collect();
    cols.sort_by_key(|c| c.ty.rank());
    let id = match id_sequence {
        None => format!("{} int8 GENERATED BY DEFAULT AS IDENTITY", quote("id")),
        Some(seq) => format!(
            "{} int8 DEFAULT nextval({}::regclass)",
            quote("id"),
            literal(&quote(seq))
        ),
    };
    let mut parts = vec![id];
    for c in &cols {
        let col_sql = if let Some(col_gen) = &c.generated {
            format!(
                "{} {} GENERATED ALWAYS AS ({}) {}{}",
                quote(&c.name),
                c.ty.sql(),
                col_gen.expression,
                col_gen.storage.as_str().to_uppercase(),
                if c.not_null { " NOT NULL" } else { "" }
            )
        } else {
            format!(
                "{} {}{}",
                quote(&c.name),
                c.ty.sql(),
                if c.not_null { " NOT NULL" } else { "" }
            )
        };
        parts.push(col_sql);
    }
    parts.push(format!("PRIMARY KEY({})", quote("id")));
    let storage = fillfactor.map_or_else(String::new, |ff| format!(" WITH (fillfactor = {ff})"));
    let mut out = vec![format!(
        "CREATE TABLE {} ({}){storage}",
        quote(table),
        parts.join(", ")
    )];
    out.push(format!(
        "COMMENT ON TABLE {} IS {}",
        quote(table),
        literal(comment)
    ));
    for c in &cols {
        out.push(comment_on_column(table, &c.name, &c.comment));
    }
    out
}

/// `CREATE SEQUENCE` of a shared id sequence: `int8`, increment 1, no cycle (stated,
/// so the shape schema sync checks on an existing sequence is the one it creates), owned by no
/// column, so no table's removal drops it.
pub fn create_sequence(name: &str) -> String {
    format!(
        "CREATE SEQUENCE {} AS int8 INCREMENT BY 1 NO CYCLE",
        quote(name)
    )
}

/// `ALTER TABLE … SET (fillfactor = n)`: applies to pages written from now on; existing pages
/// keep their layout until the table is rewritten.
pub fn set_fillfactor(table: &str, fillfactor: u8) -> String {
    format!(
        "ALTER TABLE {} SET (fillfactor = {fillfactor})",
        quote(table)
    )
}

/// `COMMENT ON COLUMN`.
pub fn comment_on_column(table: &str, column: &str, comment: &str) -> String {
    format!(
        "COMMENT ON COLUMN {}.{} IS {}",
        quote(table),
        quote(column),
        literal(comment)
    )
}

/// `ALTER TABLE … ADD COLUMN` plus its comment. With `default` (an SQL literal), existing rows get
/// that value without a table rewrite (PostgreSQL's fast default) and the column default is dropped
/// again, since the ORM, not the database, applies defaults. `NOT NULL` is set in the same
/// statement when the column is required and has a default.
pub fn add_column(table: &str, column: &ColumnDef, default: Option<&str>) -> Vec<String> {
    let (t, c) = (quote(table), quote(&column.name));
    if let Some(col_gen) = &column.generated {
        return vec![
            format!(
                "ALTER TABLE {t} ADD COLUMN {c} {} GENERATED ALWAYS AS ({}) {}{}",
                column.ty.sql(),
                col_gen.expression,
                col_gen.storage.as_str().to_uppercase(),
                if column.not_null { " NOT NULL" } else { "" }
            ),
            comment_on_column(table, &column.name, &column.comment),
        ];
    }
    match default {
        None => vec![
            format!("ALTER TABLE {t} ADD COLUMN {c} {}", column.ty.sql()),
            comment_on_column(table, &column.name, &column.comment),
        ],
        Some(lit) => vec![
            format!(
                "ALTER TABLE {t} ADD COLUMN {c} {} DEFAULT {lit}{}",
                column.ty.sql(),
                if column.not_null { " NOT NULL" } else { "" }
            ),
            format!("ALTER TABLE {t} ALTER COLUMN {c} DROP DEFAULT"),
            comment_on_column(table, &column.name, &column.comment),
        ],
    }
}

/// `ALTER TABLE … ALTER COLUMN … SET EXPRESSION AS (…)`.
pub fn alter_column_set_expression(table: &str, column: &str, expression: &str) -> String {
    format!(
        "ALTER TABLE {} ALTER COLUMN {} SET EXPRESSION AS ({})",
        quote(table),
        quote(column),
        expression
    )
}

/// Convert a column's type with a cast, dropping its default first (FIELD §4.5).
pub fn alter_column_type(table: &str, column: &str, ty: ColumnType) -> String {
    format!(
        "ALTER TABLE {t} ALTER COLUMN {c} DROP DEFAULT, ALTER COLUMN {c} TYPE {ty} USING {c}::{ty}",
        t = quote(table),
        c = quote(column),
        ty = ty.sql()
    )
}

/// Convert a scalar column (`varchar`/`text`/`bpchar`) to translated `jsonb`
/// preserving NULL and empty strings.
pub fn alter_column_to_translated_jsonb(table: &str, column: &str) -> String {
    let (t, c) = (quote(table), quote(column));
    format!(
        "ALTER TABLE {t} ALTER COLUMN {c} DROP DEFAULT, ALTER COLUMN {c} TYPE jsonb USING (CASE WHEN {c} IS NULL THEN NULL WHEN {c} = '' THEN '{{\"en_US\": \"\"}}'::jsonb ELSE jsonb_build_object('en_US', {c}) END)"
    )
}

/// `SET NOT NULL`: one statement, which scans the table under its exclusive lock. Schema sync uses
/// it on new and small tables; on a large table it adds the constraint `NOT VALID`
/// ([`add_not_null_not_valid`]) and validates it after the commit ([`validate_constraint`]).
pub fn set_not_null(table: &str, column: &str) -> String {
    format!(
        "ALTER TABLE {} ALTER COLUMN {} SET NOT NULL",
        quote(table),
        quote(column)
    )
}

/// The name schema sync gives a column's not-null constraint (PostgreSQL's own convention,
/// shortened).
pub fn not_null_constraint_name(table: &str, column: &str) -> String {
    shorten_identifier(&format!("{table}_{column}_not_null"))
}

/// A not-null constraint added `NOT VALID` (PostgreSQL 18): enforced for rows inserted or updated
/// from now on, existing rows are checked by [`validate_constraint`] later, under a lock that
/// lets writes go on.
pub fn add_not_null_not_valid(table: &str, column: &str, name: &str) -> String {
    format!(
        "ALTER TABLE {} ADD CONSTRAINT {} NOT NULL {} NOT VALID",
        quote(table),
        quote(name),
        quote(column)
    )
}

/// `VALIDATE CONSTRAINT` (a scan under `SHARE UPDATE EXCLUSIVE`: writes go on).
pub fn validate_constraint(table: &str, name: &str) -> String {
    format!(
        "ALTER TABLE {} VALIDATE CONSTRAINT {}",
        quote(table),
        quote(name)
    )
}

/// The `CONCURRENTLY IF NOT EXISTS` form of an index statement built by this module or by
/// [`crate::relational::create_parent_path_index`] (`CREATE INDEX …` / `CREATE UNIQUE INDEX …`);
/// `None` for any other statement.
pub fn create_index_concurrently(statement: &str) -> Option<String> {
    for kind in ["CREATE INDEX ", "CREATE UNIQUE INDEX "] {
        if let Some(rest) = statement.strip_prefix(kind) {
            return Some(format!("{kind}CONCURRENTLY IF NOT EXISTS {rest}"));
        }
    }
    None
}

/// The temporary name of an index while it is built concurrently to replace `name`
/// on a large table: `<name>__swap`, shortened to PostgreSQL's 63 bytes.
pub fn swap_index_name(name: &str) -> String {
    shorten_identifier(&format!("{name}__swap"))
}

/// The `CONCURRENTLY` statement to create an index under a temporary swap name, without
/// `IF NOT EXISTS` (the swap index is temporary and any invalid leftover is dropped first).
///
/// Takes a statement generated by [`create_field_index`], [`create_table_object_index`] or
/// [`crate::relational::create_parent_path_index`] (`CREATE [UNIQUE] INDEX name ON ...`) and
/// replaces the index name with `temp_name`. Returns `None` if the statement does not match.
pub fn create_swap_index_concurrently(
    statement: &str,
    old_name: &str,
    temp_name: &str,
) -> Option<String> {
    for kind in ["CREATE INDEX ", "CREATE UNIQUE INDEX "] {
        if let Some(rest) = statement.strip_prefix(kind) {
            let quoted = quote(old_name);
            let rest_after_name = rest.strip_prefix(&quoted)?;
            if !rest_after_name.starts_with(' ') {
                return None;
            }
            let temp_quoted = quote(temp_name);
            return Some(format!("{kind}CONCURRENTLY {temp_quoted}{rest_after_name}"));
        }
    }
    None
}

/// Whether a constraint definition (`UNIQUE (…)`, `PRIMARY KEY (…)`) declares a unique key, in
/// any letter case: such a constraint builds an index over the whole table when it is added.
pub fn is_unique_constraint(definition: &str) -> bool {
    let head = definition.trim_start();
    let starts = |keyword: &str| {
        head.get(..keyword.len())
            .is_some_and(|h| h.eq_ignore_ascii_case(keyword))
    };
    starts("UNIQUE") || starts("PRIMARY KEY")
}

/// The head of an index statement built by this module for `name` on `table`
/// (`CREATE [UNIQUE] INDEX "name" ON "table"`), split into its kind and the rest after the table;
/// `None` for any other statement.
fn split_index_statement<'a>(
    statement: &'a str,
    name: &str,
    table: &str,
) -> Option<(&'static str, &'a str)> {
    for kind in ["CREATE INDEX ", "CREATE UNIQUE INDEX "] {
        let head = format!("{kind}{} ON {}", quote(name), quote(table));
        if let Some(rest) = statement.strip_prefix(&head) {
            return Some((kind, rest));
        }
    }
    None
}

/// The first step of building an index on a partitioned table that already holds rows: `CREATE
/// INDEX IF NOT EXISTS … ON ONLY <table>` from an index statement built by this module. The
/// parent index is only a catalog entry, invalid until an index is attached for every partition
/// ([`create_partition_index_concurrently`], [`attach_partition_index`]); `CREATE INDEX
/// CONCURRENTLY` itself is refused on a partitioned table. `None` for any other statement.
pub fn create_index_on_only(statement: &str, name: &str, table: &str) -> Option<String> {
    let (kind, rest) = split_index_statement(statement, name, table)?;
    Some(format!(
        "{kind}IF NOT EXISTS {} ON ONLY {}{rest}",
        quote(name),
        quote(table)
    ))
}

/// The index of one partition for a parent index declared by `statement` (an index statement of
/// `name` on `table` built by this module): `CREATE INDEX CONCURRENTLY IF NOT EXISTS
/// <partition_index> ON <partition> …`, the same definition as the parent's. `None` for any
/// other statement.
pub fn create_partition_index_concurrently(
    statement: &str,
    name: &str,
    table: &str,
    partition: &str,
    partition_index: &str,
) -> Option<String> {
    let (kind, rest) = split_index_statement(statement, name, table)?;
    Some(format!(
        "{kind}CONCURRENTLY IF NOT EXISTS {} ON {}{rest}",
        quote(partition_index),
        quote(partition)
    ))
}

/// `ALTER INDEX <parent_index> ATTACH PARTITION <partition_index>`: when every partition of the
/// table has one attached, the parent index becomes valid.
pub fn attach_partition_index(parent_index: &str, partition_index: &str) -> String {
    format!(
        "ALTER INDEX {} ATTACH PARTITION {}",
        quote(parent_index),
        quote(partition_index)
    )
}

/// The comment of an unfinished parent index of a stepwise build whose declaration carries no
/// comment of its own (a field index): `COMMENT ON INDEX <name> IS 'erp:building <statement>'`. It
/// is what lets a resumed build tell its own unfinished parent index from a stale one of another
