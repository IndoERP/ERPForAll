/// Error returned when a field index cannot be created because a required PostgreSQL extension
/// is not installed.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct MissingExtensionError {
    /// The extension that must be installed (e.g. `pg_trgm`).
    pub extension: &'static str,
    /// The table owning the field.
    pub table: String,
    /// The field that declares the index.
    pub column: String,
    /// The index kind that needs the extension.
    pub kind: IndexKind,
}

impl std::fmt::Display for MissingExtensionError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        // the wording; schema sync names the model and field instead of the
        // table and column (it knows them)
        write!(
            f,
            "column \"{}\".\"{}\" declares index = \"{}\", which needs the PostgreSQL extension \
             {}; it is not installed",
            self.table,
            self.column,
            self.kind.as_str(),
            self.extension,
        )
    }
}

impl std::error::Error for MissingExtensionError {}

/// A field index (CRUD §4.10 `check_indexes`), built from the kind's access method, operator
/// class and partial predicate ([`IndexKind::method`], [`IndexKind::opclass`],
/// [`IndexKind::not_null_only`]):
///
/// | kind | statement |
/// |---|---|
/// | `btree` | `CREATE INDEX n ON t USING btree (c)` |
/// | `btree_not_null` | `… USING btree (c) WHERE c IS NOT NULL` |
/// | `trigram` | `… USING gin (c gin_trgm_ops)`, `c` folded like `ilike` when indexable |
/// | `brin` | `… USING brin (c)` |
/// | `gin` | `… USING gin (c jsonb_path_ops)` |
///
/// # Errors
///
/// Returns [`MissingExtensionError`] when the kind needs an extension that is not installed
/// (`pg_trgm` for a trigram index, `has_extension("pg_trgm")` false): the caller must fail loudly, never silently
/// skip the index.
pub fn create_field_index(
    table: &str,
    column: &str,
    name: &str,
    kind: IndexKind,
    has_extension: impl Fn(&str) -> bool,
    unaccent: Unaccent,
) -> Result<String, MissingExtensionError> {
    create_field_index_translated(table, column, name, kind, false, has_extension, unaccent)
}

/// Create a field index, taking into account whether the field is translated.
/// When `translate` is true and `kind == IndexKind::Trigram`, indexes `(jsonb_path_query_array("col", '$.*')::text)`.
pub fn create_field_index_translated(
    table: &str,
    column: &str,
    name: &str,
    kind: IndexKind,
    translate: bool,
    has_extension: impl Fn(&str) -> bool,
    unaccent: Unaccent,
) -> Result<String, MissingExtensionError> {
    if let Some(extension) = kind.extension()
        && !has_extension(extension)
    {
        return Err(MissingExtensionError {
            extension,
            table: table.to_owned(),
            column: column.to_owned(),
            kind,
        });
    }
    let (t, c, n) = (quote(table), quote(column), quote(name));
    let mut expr = if kind == IndexKind::Trigram {
        let base_col = if translate {
            format!("(jsonb_path_query_array({c}, '$.*')::text)")
        } else {
            c.clone()
        };
        match unaccent {
            Unaccent::Indexable => unaccent.wrap(&base_col),
            Unaccent::Off | Unaccent::Present => base_col,
        }
    } else {
        c.clone()
    };
    if let Some(opclass) = kind.opclass() {
        expr = format!("{expr} {opclass}");
    }
    let mut sql = format!("CREATE INDEX {n} ON {t} USING {} ({expr})", kind.method());
    if kind.not_null_only() {
        sql.push_str(&format!(" WHERE {c} IS NOT NULL"));
    }
    Ok(sql)
}

/// The definition of a typed model-level index (design), the text
/// after the table name in `CREATE INDEX <name> ON <table> <definition>` and after `INDEX ` in
/// the index's comment: `USING <method> (<key columns>) [INCLUDE (<columns>)] [WHERE (<predicate>)]`.
/// `predicate` is the index's constant filter compiled by [`crate::constant_filter::compile`] (the
/// caller compiles it against the model; the declaration only holds the domain text). Key columns get
/// the method's operator class; the key columns of a trigram index are folded like `ilike`
/// conditions when folding is indexable, as field-level trigram indexes are.
///
/// ```
/// use erp_registry::{IndexDecl, IndexMethod};
/// use erp_sql::ddl::typed_index_definition;
/// use erp_sql::filter::Unaccent;
///
/// let open = IndexDecl::new(&["state", "start"]).include(&["resource_id"]);
/// assert_eq!(
///     typed_index_definition(&open, Unaccent::Off, None),
///     "USING btree (\"state\", \"start\") INCLUDE (\"resource_id\")"
/// );
/// assert_eq!(
///     typed_index_definition(&open, Unaccent::Off, Some("\"state\" = 'open'")),
///     "USING btree (\"state\", \"start\") INCLUDE (\"resource_id\") WHERE (\"state\" = 'open')"
/// );
/// let payload = IndexDecl::new(&["payload"]).method(IndexMethod::Gin);
/// assert_eq!(
///     typed_index_definition(&payload, Unaccent::Off, None),
///     "USING gin (\"payload\" jsonb_path_ops)"
/// );
/// ```
pub fn typed_index_definition(
    index: &erp_registry::IndexDecl,
    unaccent: Unaccent,
    predicate: Option<&str>,
) -> String {
    typed_index_definition_with_translated(index, unaccent, predicate, |_| false)
}

/// The definition of a typed model-level index, allowing translated fields to emit `jsonb_path_query_array`.
pub fn typed_index_definition_with_translated(
    index: &erp_registry::IndexDecl,
    unaccent: Unaccent,
    predicate: Option<&str>,
    is_translated: impl Fn(&str) -> bool,
) -> String {
    let method = index.method;
    let keys: Vec<String> = index
        .fields
        .iter()
        .map(|field| {
            let column = quote(field);
            let mut expr = if method == erp_registry::IndexMethod::Trigram {
                let base_col = if is_translated(field) {
                    format!("(jsonb_path_query_array({column}, '$.*')::text)")
                } else {
                    column
                };
                match unaccent {
                    Unaccent::Indexable => unaccent.wrap(&base_col),
                    // a folding function that is not immutable cannot appear in an index
                    Unaccent::Off | Unaccent::Present => base_col,
                }
            } else {
                column
            };
            if let Some(opclass) = method.opclass() {
                expr = format!("{expr} {opclass}");
            }
            expr
        })
        .collect();
    let mut definition = format!("USING {} ({})", method.access_method(), keys.join(", "));
    if !index.include.is_empty() {
        let include: Vec<String> = index.include.iter().map(|f| quote(f)).collect();
        definition.push_str(&format!(" INCLUDE ({})", include.join(", ")));
    }
    if let Some(predicate) = predicate {
        definition.push_str(&format!(" WHERE ({predicate})"));
    }
    definition
}

/// The immutable accent-folding wrapper over the `unaccent` extension installed in `schema`
/// (the extension's own function is only `STABLE`, so it cannot appear in an index).
pub fn create_unaccent_wrapper(schema: &str) -> String {
    let s = quote(schema);
    format!(
        "CREATE OR REPLACE FUNCTION {UNACCENT_WRAPPER}(text) RETURNS text LANGUAGE sql IMMUTABLE \
         PARALLEL SAFE STRICT AS $erp$ SELECT {s}.unaccent({}::regdictionary, $1) $erp$",
        literal(&format!("{s}.unaccent"))
    )
}

/// The name of a field's foreign key (PostgreSQL's own convention, shortened).
pub fn foreign_key_name(table: &str, column: &str) -> String {
    shorten_identifier(&format!("{table}_{column}_fkey"))
}

/// A foreign key. On a table that already has rows (`validate_later`), the key is added
/// `NOT VALID` (no scan under the exclusive lock) and validated in a second statement.
pub fn add_foreign_key(
    table: &str,
    column: &str,
    target: &str,
    ondelete: OnDelete,
    validate_later: bool,
) -> Vec<String> {
    if validate_later {
        vec![
            add_foreign_key_not_valid(table, column, target, ondelete),
            validate_constraint(table, &foreign_key_name(table, column)),
        ]
    } else {
        vec![foreign_key_statement(table, column, target, ondelete, "")]
    }
}

/// A foreign key added `NOT VALID`: enforced for rows written from now on; the existing rows are
/// checked by [`validate_constraint`] on the key ([`foreign_key_name`]).
pub fn add_foreign_key_not_valid(
    table: &str,
    column: &str,
    target: &str,
    ondelete: OnDelete,
) -> String {
    foreign_key_statement(table, column, target, ondelete, " NOT VALID")
}

fn foreign_key_statement(
    table: &str,
    column: &str,
    target: &str,
    ondelete: OnDelete,
    suffix: &str,
) -> String {
    format!(
        "ALTER TABLE {} ADD CONSTRAINT {} FOREIGN KEY ({}) REFERENCES {}({}) ON DELETE {}{suffix}",
        quote(table),
        quote(&foreign_key_name(table, column)),
        quote(column),
        quote(target),
        quote("id"),
        ondelete.sql(),
    )
}

