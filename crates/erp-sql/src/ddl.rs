pub fn partitioned_build_comment(name: &str, statement: &str) -> String {
    format!(
        "COMMENT ON INDEX {} IS {}",
        quote(name),
        literal(&format!("erp:building {statement}"))
    )
}

/// `COMMENT ON INDEX <name> IS NULL`.
pub fn clear_index_comment(name: &str) -> String {
    format!("COMMENT ON INDEX {} IS NULL", quote(name))
}

/// Every partition of table `$1` (current schema), pending detaches included, in name order.
pub const PARTITIONS_QUERY: &str = "\
SELECT p.relname::text
  FROM pg_inherits i
  JOIN pg_class parent ON parent.oid = i.inhparent
  JOIN pg_class p ON p.oid = i.inhrelid
  JOIN pg_namespace n ON n.oid = parent.relnamespace
 WHERE n.nspname = current_schema() AND parent.relname = $1::text
 ORDER BY 1";

/// The indexes of the pairs `(partition, index name)` given as the parallel arrays `$1` and `$2`
/// (`text[]`, current schema) that exist as an index of that partition itself (a same-named index
/// of another table is never listed) and are attached to no parent index: what a crash between a
/// partition index's build and its attach leaves behind. Partitions are plain tables (schema sync
/// refuses a sub-partitioned one, `partition/sync.rs`), so their indexes are `relkind 'i'`.
pub const UNATTACHED_INDEXES_QUERY: &str = "\
SELECT c.relname::text
  FROM unnest($1::text[], $2::text[]) AS w(part, idx)
  JOIN pg_namespace n ON n.nspname = current_schema()
  JOIN pg_class t ON t.relnamespace = n.oid AND t.relname::text = w.part
  JOIN pg_class c ON c.relnamespace = n.oid AND c.relname::text = w.idx AND c.relkind = 'i'
  JOIN pg_index x ON x.indexrelid = c.oid AND x.indrelid = t.oid
 WHERE NOT EXISTS (SELECT FROM pg_inherits i WHERE i.inhrelid = c.oid)
 ORDER BY 1";

/// The partitions of table `$1` (current schema) that have no index attached to the index `$2`
/// of the parent yet, in name order: the partitions a stepwise index build still has to cover.
pub const PARTITIONS_WITHOUT_INDEX_QUERY: &str = "\
SELECT p.relname::text
  FROM pg_inherits i
  JOIN pg_class parent ON parent.oid = i.inhparent
  JOIN pg_class p ON p.oid = i.inhrelid
  JOIN pg_namespace n ON n.oid = parent.relnamespace
  JOIN pg_class pidx ON pidx.relname = $2::text AND pidx.relnamespace = n.oid
 WHERE n.nspname = current_schema() AND parent.relname = $1::text AND NOT i.inhdetachpending
   AND NOT EXISTS (SELECT FROM pg_index x JOIN pg_inherits xi ON xi.inhrelid = x.indexrelid
                    WHERE x.indrelid = p.oid AND xi.inhparent = pidx.oid)
 ORDER BY 1";

/// Fill NULL cells of a column with an SQL literal, one batch per statement: the rows above id
/// `$1` (an `int8` cursor, `0` to start) holding a NULL, at most `$2` (an `int8`) of them, lowest
/// ids first. Returns one row `(rows in the batch, highest id of the batch)` (`int8`, `int8` or
/// NULL when the batch is empty); run it again with that id as the cursor until a batch has fewer
/// than `$2` rows. Each statement is short and each continues where the last stopped, so a large
/// table is filled without one long transaction holding every row lock and without scanning the
/// filled part again. A row a concurrent writer filled meanwhile keeps its value.
pub fn fill_nulls_batch(table: &str, column: &str, literal_value: &str) -> String {
    format!(
        "WITH \"_batch\" AS MATERIALIZED \
           (SELECT {id} FROM {t} WHERE {id} > $1 AND {c} IS NULL ORDER BY {id} LIMIT $2), \
         \"_filled\" AS \
           (UPDATE {t} AS \"_row\" SET {c} = {literal_value} FROM \"_batch\" \
             WHERE \"_row\".{id} = \"_batch\".{id} AND \"_row\".{c} IS NULL) \
         SELECT count(*)::int8, max({id})::int8 FROM \"_batch\"",
        t = quote(table),
        c = quote(column),
        id = quote("id"),
    )
}

/// Prefix of the comment of a column whose stored computed values are not filled yet (a compute
/// backfill pending on a large table): set by schema sync in the transaction that
/// adds the column, replaced by the column's label once all batches of the backfill have run (a
/// comment that lost the prefix meanwhile, changed outside the ORM, is kept and reported). The
/// catalog query reports the marked columns (`pending` rows), so a backfill interrupted by a
/// crash or an error is planned again by the next sync.
pub const PENDING_BACKFILL_COMMENT_PREFIX: &str = "[erpforall: compute backfill pending] ";

/// The comment marking a column with a pending compute backfill
/// ([`PENDING_BACKFILL_COMMENT_PREFIX`] then the label).
pub fn comment_pending_backfill(table: &str, column: &str, label: &str) -> String {
    comment_on_column(
        table,
        column,
        &format!("{PENDING_BACKFILL_COMMENT_PREFIX}{label}"),
    )
}

