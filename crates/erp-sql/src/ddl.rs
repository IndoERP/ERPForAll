/// An `Index`/`UniqueIndex` table object: `(CREATE …, COMMENT ON INDEX …)`; the comment records
/// the declaration (`INDEX <def>` / `UNIQUE INDEX <def>`).
pub fn create_table_object_index(
    table: &str,
    name: &str,
    definition: &str,
    unique: bool,
) -> (String, String) {
    let kind = if unique { "UNIQUE INDEX" } else { "INDEX" };
    (
        format!(
            "CREATE {kind} {} ON {} {definition}",
            quote(name),
            quote(table)
        ),
        format!(
            "COMMENT ON INDEX {} IS {}",
            quote(name),
            literal(&format!("{kind} {definition}"))
        ),
    )
}

