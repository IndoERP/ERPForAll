#[test]
fn runtime_grant_publication_requires_explicit_config() {
    Cli::try_parse_from([
        "erp",
        "db",
        "publish-grants",
        "--config",
        "/private/server.toml",
    ])
    .unwrap();
    let error = Cli::try_parse_from(["erp", "db", "publish-grants"]).unwrap_err();
    assert_eq!(
        error.kind(),
        clap::error::ErrorKind::MissingRequiredArgument
    );
    assert!(error.to_string().contains("--config"));
}

/// The publisher contract is a no-effect binary capability, independent of deployment config.
#[test]
fn runtime_grant_contract_needs_no_config_database_or_async_runtime() {
    let root = tempfile::tempdir().unwrap();
    let output = std::process::Command::new(env!("CARGO_BIN_EXE_erp"))
        .args(["db", "runtime-grant-contract"])
        .current_dir(root.path())
        .env_clear()
        .output()
        .unwrap();
    assert!(output.status.success(), "{:?}", output);
    assert!(output.stderr.is_empty(), "{:?}", output.stderr);
    let contract: serde_json::Value = serde_json::from_slice(&output.stdout).unwrap();
    assert_eq!(
        contract,
        serde_json::json!({"version": 13, "ui_assets": "read-only", "node_features": "execute-only", "event_outbox": "insert-only", "uom_references": "guarded-monotone", "job_queue": "column-grants", "audit_trail": "insert-only", "attachment_usage": "append-only", "audit_reader": "select-only", "attachment_owner": "read-only", "attachment_pending": "guarded-create", "attachment_peer": "read-only", "attachment_recovery": "owner-write, progress-read"})
    );
    assert_eq!(std::fs::read_dir(root.path()).unwrap().count(), 0);
}

#[test]
fn runtime_grant_contract_rejects_config_or_unknown_options() {
    for option in ["--config", "--unknown"] {
        let error =
            Cli::try_parse_from(["erp", "db", "runtime-grant-contract", option]).unwrap_err();
        assert_eq!(error.kind(), clap::error::ErrorKind::UnknownArgument);
        assert_eq!(
            error.to_string(),
            format!(
                "error: unexpected argument '{option}' found\n\nUsage: erp db runtime-grant-contract\n\nFor more information, try '--help'.\n"
            )
        );
    }
}

const REVOKE: [&str; 6] = [
    "erp",
    "auth",
    "emergency-revoke",
    "--config",
    "/private/server.toml",
    "--reason",
];

/// The arguments of a successful `erp auth emergency-revoke` parse.
fn revoke_args(rest: &[&str]) -> erp_cli::EmergencyRevokeArgs {
    let mut line: Vec<&str> = REVOKE.to_vec();
    line.extend_from_slice(rest);
    let cli = Cli::try_parse_from(line).unwrap();
    let erp_cli::Commands::Auth(command) = cli.command else {
        panic!("not an auth command");
    };
    let erp_cli::AuthAction::EmergencyRevoke(args) = command.action else {
        panic!("not an emergency revocation");
    };
    args
}

/// from the closed list and exactly one target group; `--user` needs `--keys`, `--sessions` or
/// both. The clap usage text is generated by clap, so the refusals are asserted by kind and by
/// the argument they name (the full text is not stable across clap versions).
#[test]
fn emergency_revoke_requires_config_reason_and_one_target() {
    let keys = revoke_args(&["lost", "--key", "5", "6"]);
    assert_eq!(keys.key, [5, 6]);
    assert_eq!(keys.reason, erp_cli::EmergencyReasonArg::Lost);
    let sessions = revoke_args(&[
        "incident",
        "--session",
        "01234567-89ab-7def-8123-456789abcdef",
    ]);
    assert_eq!(sessions.session.len(), 1);
    let user = revoke_args(&["offboarding", "--user", "7", "--keys", "--sessions"]);
    assert_eq!((user.user, user.keys, user.sessions), (Some(7), true, true));
    assert_eq!(
        revoke_args(&["compromised", "--user", "7", "--sessions"]).reason,
        erp_cli::EmergencyReasonArg::Compromised
    );

    let refused = |line: &[&str], kind: clap::error::ErrorKind, names: &str| {
        let error = Cli::try_parse_from(line).unwrap_err();
        assert_eq!(error.kind(), kind, "{line:?}: {error}");
        assert!(error.to_string().contains(names), "{line:?}: {error}");
    };
    let missing = clap::error::ErrorKind::MissingRequiredArgument;
    refused(
        &[
            "erp",
            "auth",
            "emergency-revoke",
            "--reason",
            "lost",
            "--key",
            "1",
        ],
        missing,
        "--config",
    );
    refused(
        &[
            "erp",
            "auth",
            "emergency-revoke",
            "--config",
            "/private/server.toml",
            "--key",
            "1",
        ],
        missing,
        "--reason",
    );
    refused(&[REVOKE.as_slice(), &["lost"]].concat(), missing, "--user");
    refused(
        &[REVOKE.as_slice(), &["lost", "--user", "7"]].concat(),
        missing,
        "--keys",
    );
    refused(
        &[REVOKE.as_slice(), &["lost", "--keys", "--key", "1"]].concat(),
        clap::error::ErrorKind::ArgumentConflict,
        "--keys",
    );
    refused(
        &[
            REVOKE.as_slice(),
            &["lost", "--key", "1", "--user", "7", "--keys"],
        ]
        .concat(),
        clap::error::ErrorKind::ArgumentConflict,
        "--key",
    );
    refused(
        &[
            REVOKE.as_slice(),
            &[
                "lost",
                "--sessions",
                "--session",
                "01234567-89ab-7def-8123-456789abcdef",
            ],
        ]
        .concat(),
        clap::error::ErrorKind::ArgumentConflict,
        "--sessions",
    );
    refused(
        &[REVOKE.as_slice(), &["whatever", "--key", "1"]].concat(),
        clap::error::ErrorKind::InvalidValue,
        "compromised",
    );
}
