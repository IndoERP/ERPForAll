//! What the enumeration test reads from the source: the files of a crate's module tree (from
//! `src/lib.rs`, `#[cfg(test)]` modules skipped), the public functions among them that take the
//! transaction, the `sudo(true)` call sites and the read-audit owner's call sites.
//!
//! Records live behind the transaction: its connection and its cache are the only way to read or
//! write them, so every function that can touch a record takes `&mut Transaction` (or is a
//! `&mut self` method of `Transaction`). A public function of that shape added anywhere in the
//! crate is found here without anyone listing it. Functions generated by macros are not seen
//! (`erp-orm` defines none of its public API that way; addon models' typed accessors call the
//! `Records` methods listed here).
//!
//! Limits: public items of traits are scanned (declared and defaulted methods; impls of traits are
//! not, their trait is the public item); a signature that mentions `Transaction` in any argument
//! type counts (`&Transaction`, `Option<&mut Transaction>`, a closure over it), so an unexpected
//! shape is listed rather than missed; macro-generated items are not seen.

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use syn::visit::Visit;
use syn::{Attribute, FnArg, ImplItem, Item, Signature, TraitItem, Type, Visibility};

/// One file of a module tree.
pub struct SourceFile {
    /// The physical source path relative to the scan root (possibly outside it via `..`).
    pub rel: String,
    /// The module path of the file (`""` for `lib.rs`, `web::read` …).
    pub module: String,
    /// The parsed file.
    pub file: syn::File,
}

/// Whether the attributes hold `#[cfg(test)]`.
pub fn is_cfg_test(attrs: &[Attribute]) -> bool {
    attrs.iter().any(|a| {
        a.path().is_ident("cfg")
            && a.parse_args::<syn::Meta>()
                .is_ok_and(|m| m.path().is_ident("test"))
    })
}

fn join(prefix: &str, name: &str) -> String {
    if prefix.is_empty() {
        name.to_owned()
    } else {
        format!("{prefix}::{name}")
    }
}

/// Every file of the module tree of the crate whose root is `lib` (`src/lib.rs`).
pub fn module_files(lib: &Path) -> Vec<SourceFile> {
    let src = lib.parent().unwrap().to_owned();
    let mut out = Vec::new();
    walk_file(lib, &src, &src, "", &mut out);
    out
}

/// The other crate roots outside `src/lib.rs`: `src/main.rs`, `src/bin/*.rs`, `src/bin/*/main.rs`
/// and `build.rs` of the crate at `dir`, each with its module tree. Paths are relative to `dir`.
pub fn other_roots(dir: &Path) -> Vec<SourceFile> {
    let mut roots: Vec<PathBuf> = Vec::new();
    for candidate in [dir.join("src/main.rs"), dir.join("build.rs")] {
        if candidate.exists() {
            roots.push(candidate);
        }
    }
    if let Ok(entries) = fs::read_dir(dir.join("src/bin")) {
        let mut found: Vec<PathBuf> = entries
            .map(|e| e.unwrap().path())
            .filter_map(|p| {
                if p.extension().is_some_and(|e| e == "rs") {
                    Some(p)
                } else if p.join("main.rs").exists() {
                    Some(p.join("main.rs"))
                } else {
                    None
                }
            })
            .collect();
        found.sort();
        roots.extend(found);
    }
    let mut out = Vec::new();
    for root in roots {
        let children = root.parent().unwrap().to_owned();
        walk_file(&root, &children, dir, "", &mut out);
    }
    out
}

fn walk_file(file: &Path, children: &Path, src: &Path, module: &str, out: &mut Vec<SourceFile>) {
    let text =
        fs::read_to_string(file).unwrap_or_else(|e| panic!("cannot read {}: {e}", file.display()));
    let parsed =
        syn::parse_file(&text).unwrap_or_else(|e| panic!("cannot parse {}: {e}", file.display()));
    let items = parsed.items.clone();
    out.push(SourceFile {
        rel: relative_source(file, src),
        module: module.to_owned(),
        file: parsed,
    });
    walk_mods(&items, children, file.parent().unwrap(), src, module, out);
}

/// Keep external source files visible in diagnostics instead of assuming they are below `src`.
fn relative_source(file: &Path, src: &Path) -> String {
    let file = file
        .canonicalize()
        .unwrap_or_else(|e| panic!("cannot resolve {}: {e}", file.display()));
    let src = src
        .canonicalize()
        .unwrap_or_else(|e| panic!("cannot resolve {}: {e}", src.display()));
    let file_parts: Vec<_> = file.components().collect();
    let src_parts: Vec<_> = src.components().collect();
    let common = file_parts
        .iter()
        .zip(&src_parts)
        .take_while(|(a, b)| a == b)
        .count();
    let mut relative = PathBuf::new();
    for _ in &src_parts[common..] {
        relative.push("..");
    }
    for part in &file_parts[common..] {
        relative.push(part.as_os_str());
    }
    relative.display().to_string()
}

fn module_path(attrs: &[Attribute], module: &str) -> Option<PathBuf> {
    let mut paths = attrs.iter().filter(|attr| attr.path().is_ident("path"));
    let attr = paths.next()?;
    assert!(
        paths.next().is_none(),
        "module {module}: duplicate #[path] attributes"
    );
    if let syn::Meta::NameValue(value) = &attr.meta
        && let syn::Expr::Lit(value) = &value.value
        && let syn::Lit::Str(value) = &value.lit
        && !value.value().is_empty()
    {
        return Some(PathBuf::from(value.value()));
    }
    panic!("module {module}: #[path] must be one non-empty string literal");
}

fn walk_mods(
    items: &[Item],
    dir: &Path,
    attribute_dir: &Path,
    src: &Path,
    module: &str,
    out: &mut Vec<SourceFile>,
) {
    for item in items {
        let Item::Mod(m) = item else { continue };
        if is_cfg_test(&m.attrs) {
            continue;
        }
        let name = m.ident.to_string();
        let path = join(module, &name);
        let explicit = module_path(&m.attrs, &path);
        match &m.content {
            // Literal path attributes resolve from the source directory outside inline modules;
            // inline modules carry their directory components (Rust Reference, items.mod.outlined.path).
            Some((_, inner)) => {
                let children = match explicit {
                    Some(explicit) => attribute_dir.join(explicit),
                    None => dir.join(&name),
                };
                walk_mods(inner, &children, &children, src, &path, out);
            }
            None => {
                let (file, children) = match explicit {
                    Some(explicit) => {
                        let file = attribute_dir.join(explicit);
                        // rustc_expand::module::mod_file_path treats every explicit #[path]
                        // file as mod.rs: default children start beside it, without its stem.
                        let children = file.parent().unwrap().to_owned();
                        (file, children)
                    }
                    None => {
                        let flat = dir.join(format!("{name}.rs"));
                        let nested = dir.join(&name).join("mod.rs");
                        let file = if flat.exists() {
                            flat
                        } else if nested.exists() {
                            nested
                        } else {
                            panic!(
                                "module {path}: neither {} nor {}",
                                flat.display(),
                                nested.display()
                            )
                        };
                        (file, dir.join(&name))
                    }
                };
                walk_file(&file, &children, src, &path, out);
            }
        }
    }
}

/// `Type::method` or `module::function` → the file (relative to `src`).
pub type Found = BTreeMap<String, String>;

/// Every public free function or public inherent method in `files` that takes `&mut Transaction`
/// (or is a `&mut self` method of `Transaction`).
pub fn transaction_entry_points(files: &[SourceFile]) -> Found {
    let mut out = Found::new();
    for file in files {
        scan_items(&file.file.items, &file.module, &file.rel, &mut out);
    }
    out
}

/// Records `name` found in `rel`; two items with one key would collapse into one row, so it is
/// refused.
fn add(out: &mut Found, name: String, rel: &str) {
    if let Some(first) = out.insert(name.clone(), rel.to_owned()) {
        panic!("two public items are keyed {name} ({first} and {rel}): give them distinct rows");
    }
}

fn scan_items(items: &[Item], module: &str, rel: &str, out: &mut Found) {
    for item in items {
        match item {
            Item::Mod(m) if is_cfg_test(&m.attrs) => {}
            Item::Mod(m) => {
                if let Some((_, inner)) = &m.content {
                    scan_items(inner, &join(module, &m.ident.to_string()), rel, out);
                }
            }
            Item::Impl(i) if i.trait_.is_none() && !is_cfg_test(&i.attrs) => {
                let owner = type_name(&i.self_ty);
                for member in &i.items {
                    if let ImplItem::Fn(f) = member
                        && matches!(f.vis, Visibility::Public(_))
                        && !is_cfg_test(&f.attrs)
                        && takes_transaction(&f.sig, owner == "Transaction")
                    {
                        add(out, format!("{owner}::{}", f.sig.ident), rel);
                    }
                }
            }
            // a public trait: its methods are public API whoever implements them
            Item::Trait(t) if matches!(t.vis, Visibility::Public(_)) && !is_cfg_test(&t.attrs) => {
                for member in &t.items {
                    if let TraitItem::Fn(f) = member
                        && !is_cfg_test(&f.attrs)
                        && takes_transaction(&f.sig, false)
                    {
                        add(out, format!("{}::{}", t.ident, f.sig.ident), rel);
                    }
                }
            }
            Item::Fn(f)
                if matches!(f.vis, Visibility::Public(_))
                    && !is_cfg_test(&f.attrs)
                    && takes_transaction(&f.sig, false) =>
            {
                add(out, join(module, &f.sig.ident.to_string()), rel);
            }
            _ => {}
        }
    }
}

/// The last path segment of a type (`RecordSet` for `RecordSet<M>`).
fn type_name(ty: &Type) -> String {
    match ty {
        Type::Path(p) => p
            .path
            .segments
            .last()
            .map(|s| s.ident.to_string())
            .unwrap_or_else(|| panic!("an inherent impl on an empty path")),
        other => panic!("an inherent impl on a type without a path: {other:?}"),
    }
}

/// Whether `ty` names `Transaction` anywhere (`&mut Transaction`, `&Transaction`, `Option<..>`,
/// a closure argument, a path such as `crate::Transaction`).
fn mentions_transaction(ty: &Type) -> bool {
    struct Find(bool);
    impl<'ast> Visit<'ast> for Find {
        fn visit_path_segment(&mut self, segment: &'ast syn::PathSegment) {
            if segment.ident == "Transaction" {
                self.0 = true;
            }
            syn::visit::visit_path_segment(self, segment);
        }
    }
    let mut find = Find(false);
    find.visit_type(ty);
    find.0
}

fn takes_transaction(sig: &Signature, on_transaction: bool) -> bool {
    sig.inputs.iter().any(|input| match input {
        FnArg::Receiver(r) => on_transaction && r.reference.is_some() && r.mutability.is_some(),
        FnArg::Typed(t) => mentions_transaction(&t.ty),
    })
}

/// `sudo(true)` call sites in `files`, outside `#[cfg(test)]` code: `<rel>::<enclosing fn>` →
/// how many. The engine's own superuser mode, `engine_sudo()` (`erp-orm`,: it keeps an
/// elevation block's lifetime), counts as a `sudo(true)` site.
pub fn sudo_sites(files: &[SourceFile], crate_name: &str) -> BTreeMap<String, usize> {
    calls(
        files,
        crate_name,
        &Matcher {
            method: |call| {
                let sudo_true = call.method == "sudo"
                    && call.args.len() == 1
                    && matches!(&call.args[0], syn::Expr::Lit(l)
                    if matches!(&l.lit, syn::Lit::Bool(b) if b.value));
                (sudo_true || (call.method == "engine_sudo" && call.args.is_empty())).then_some("")
            },
            path: |_| None,
            tokens: &[("", "sudo(true)"), ("", "engine_sudo()")],
        },
    )
}

/// The read-audit owner's call sites in `files` (A2, P4), outside `#[cfg(test)]` code:
/// `<rel>::<enclosing fn> <callee>` → how many, for `ReadAuditOwner::new`, `read_only_audited`
/// (of `BeginOptions` or `CredentialOptions`) and `take_audit_attempt`, called or named as a path.
pub fn read_audit_sites(files: &[SourceFile], crate_name: &str) -> BTreeMap<String, usize> {
    const READ_AUDIT: [&str; 2] = ["read_only_audited", "take_audit_attempt"];
    calls(
        files,
        crate_name,
        &Matcher {
            method: |call| READ_AUDIT.into_iter().find(|name| call.method == name),
            path: |path| {
                let names: Vec<String> = path
                    .path
                    .segments
                    .iter()
                    .map(|s| s.ident.to_string())
                    .collect();
                match names.as_slice() {
                    [.., owner, new] if owner == "ReadAuditOwner" && new == "new" => {
                        Some("ReadAuditOwner::new")
                    }
                    [.., last] => READ_AUDIT.into_iter().find(|name| *name == last.as_str()),
                    [] => None,
                }
            },
            tokens: &[
                ("ReadAuditOwner::new", "ReadAuditOwner::new"),
                ("read_only_audited", "read_only_audited("),
                ("take_audit_attempt", "take_audit_attempt("),
            ],
        },
    )
}

/// What [`calls`] counts: a method call or a path expression it names (the callee label, `""`
/// for none), and `(label, text)` pairs found in macro tokens without whitespace.
struct Matcher {
    method: fn(&syn::ExprMethodCall) -> Option<&'static str>,
    path: fn(&syn::ExprPath) -> Option<&'static str>,
    tokens: &'static [(&'static str, &'static str)],
}

fn calls(files: &[SourceFile], crate_name: &str, matcher: &Matcher) -> BTreeMap<String, usize> {
    let mut out = BTreeMap::new();
    for file in files {
        let mut visitor = Calls {
            site: format!("{crate_name}/{}", file.rel),
            within: Vec::new(),
            out: &mut out,
            matcher,
        };
        visitor.visit_file(&file.file);
    }
    out
}

struct Calls<'a> {
    site: String,
    within: Vec<String>,
    out: &'a mut BTreeMap<String, usize>,
    matcher: &'a Matcher,
}

impl Calls<'_> {
    fn count(&mut self, label: &str, n: usize) {
        let within = self
            .within
            .last()
            .cloned()
            .unwrap_or_else(|| "(outside a function)".to_owned());
        let key = if label.is_empty() {
            format!("{}::{within}", self.site)
        } else {
            format!("{}::{within} {label}", self.site)
        };
        *self.out.entry(key).or_default() += n;
    }
}

impl<'ast> Visit<'ast> for Calls<'_> {
    fn visit_item_mod(&mut self, m: &'ast syn::ItemMod) {
        // out-of-line modules are files of their own; inline test modules are skipped
        if m.content.is_some() && !is_cfg_test(&m.attrs) {
            syn::visit::visit_item_mod(self, m);
        }
    }

    fn visit_item_fn(&mut self, f: &'ast syn::ItemFn) {
        if is_cfg_test(&f.attrs) {
            return;
        }
        self.within.push(f.sig.ident.to_string());
        syn::visit::visit_item_fn(self, f);
        self.within.pop();
    }

    fn visit_impl_item_fn(&mut self, f: &'ast syn::ImplItemFn) {
        if is_cfg_test(&f.attrs) {
            return;
        }
        self.within.push(f.sig.ident.to_string());
        syn::visit::visit_impl_item_fn(self, f);
        self.within.pop();
    }

    /// Macro arguments are raw tokens to `syn`: a call in them (`assert!`, `vec!`,
    /// `tokio::join!`, a `macro_rules!` body) is found by reading the tokens without whitespace.
    fn visit_macro(&mut self, mac: &'ast syn::Macro) {
        let text: String = mac
            .tokens
            .to_string()
            .chars()
            .filter(|c| !c.is_whitespace())
            .collect();
        let mut by_label: BTreeMap<&str, usize> = BTreeMap::new();
        for (label, needle) in self.matcher.tokens {
            *by_label.entry(label).or_default() += text.matches(needle).count();
        }
        for (label, n) in by_label {
            if n > 0 {
                self.count(label, n);
            }
        }
        syn::visit::visit_macro(self, mac);
    }

    fn visit_expr_method_call(&mut self, call: &'ast syn::ExprMethodCall) {
        if let Some(label) = (self.matcher.method)(call) {
            self.count(label, 1);
        }
        syn::visit::visit_expr_method_call(self, call);
    }

    fn visit_expr_path(&mut self, path: &'ast syn::ExprPath) {
        if let Some(label) = (self.matcher.path)(path) {
            self.count(label, 1);
        }
        syn::visit::visit_expr_path(self, path);
    }
}
