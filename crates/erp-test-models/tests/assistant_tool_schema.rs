/// The `values` schema follows the field mapping and its exclusions (design note R6).
#[test]
fn values_schemas_map_fields_and_exclude_with_a_reason() {
    let orm = orm(&test_addons());
    let task = orm.registry().model("test_assistant.task").unwrap();
    let (create, excluded) = values_schema(task, ValuesMode::Create, |f| f.name != "estimate");
    let excluded: Vec<(&str, Excluded)> = excluded;
    for (field, why) in [
        ("child_ids", Excluded::X2Many),
        ("create_date", Excluded::NotWritable),
        ("estimate", Excluded::Predicate),
        ("id", Excluded::NotWritable),
        ("token", Excluded::Secret),
        ("upper", Excluded::NotWritable),
    ] {
        assert!(excluded.contains(&(field, why)), "{field}: {excluded:?}");
    }
    let ToolSchema::Object(object) = &create else {
        panic!("an object schema");
    };
    let required: Vec<&str> = object.required().collect();
    assert_eq!(required, ["code", "name"]);
    let name = object
        .properties()
        .find(|(n, _)| *n == "name")
        .map(|(_, p)| p)
        .unwrap();
    assert_eq!(name.description(), Some("Title: Short title of the task"));
    let ok = parse(
        r#"{"name": "Plan", "code": "P-1", "priority": "0", "open": null, "deadline": "2026-11-12",
            "parent_id": 3, "weight": 1.5, "note": null}"#
            .as_bytes(),
        8,
    )
    .unwrap();
    validate(&create, &ok).unwrap();
    for (body, path, expected) in [
        (r#"{"code": "c"}"#, "$.name", "a value (required)"),
        (
            r#"{"name": "n", "code": "c", "priority": "3"}"#,
            "$.priority",
            "one of \"0\", \"1\", \"2\"",
        ),
        (
            r#"{"name": "n", "code": "c", "deadline": "12/11/2026"}"#,
            "$.deadline",
            "a date (YYYY-MM-DD)",
        ),
        (
            r#"{"name": "n", "code": "c", "parent_id": 0}"#,
            "$.parent_id",
            "an integer >= 1",
        ),
        (
            r#"{"name": "n", "code": "c", "token": "s"}"#,
            "$.token",
            "no such property",
        ),
        (r#"{"name": null, "code": "c"}"#, "$.name", "a string"),
    ] {
        let violation = validate(&create, &parse(body.as_bytes(), 8).unwrap()).expect_err(body);
        assert_eq!(
            (violation.path(), violation.expected()),
            (path, expected),
            "{body}"
        );
    }
    let long = format!(r#"{{"name": "{}", "code": "c"}}"#, "é".repeat(65));
    let violation = validate(&create, &parse(long.as_bytes(), 8).unwrap()).unwrap_err();
    assert_eq!(
        (violation.path(), violation.expected(), violation.got()),
        ("$.name", "at most 64 characters", "65 characters")
    );
    let (update, _) = values_schema(task, ValuesMode::Update, |_| true);
    validate(&update, &parse(br#"{"estimate": 2147483647}"#, 8).unwrap()).unwrap();
    let violation =
        validate(&update, &parse(br#"{"estimate": 2147483648}"#, 8).unwrap()).unwrap_err();
    assert_eq!(violation.expected(), "an integer <= 2147483647");
}
