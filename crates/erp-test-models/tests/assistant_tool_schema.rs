fn build(addons: &[&'static AddonDescriptor]) -> erp_sdk::Result<Orm> {
    let registry = Arc::new(
        erp_sdk::RegistryBuilder::new(addons.iter().copied())
            .with_decls(currency_fixture::decls())
            .build()?,
    );
    // a lazy pool: nothing here connects
    let pool = erp_orm::pool::create_pool(erp_testkit::tokio_postgres::Config::new(), 1)
        .expect("a pool without connections");
    Orm::builder(registry, pool).build()
}

fn orm(addons: &[&'static AddonDescriptor]) -> Orm {
    build(addons).expect("the ORM builds")
}

fn model_id(orm: &Orm, name: &str) -> erp_registry::ModelId {
    orm.registry().model_id(name).expect("the model exists")
}

/// The export of one registry: every exposed method with a closed parameter table and its
/// schema (an open table must fail the export), the offered methods, and the `values` schemas of
/// two models (with their exclusions).
fn export(orm: &Orm) -> Json {
    let registry = orm.registry();
    let exposure = orm.exposure();
    let mut methods = Vec::new();
    for model in registry.models() {
        for (method, entry) in exposure.methods(model.id) {
            let Exposure::Exposed(exposed) = entry else {
                continue;
            };
            let key: Box<str> = format!("{}.{method}", model.name).into();
            let closed = exposed.params().iter().all(|p| p.shape().is_closed());
            match params_schema(model.name, method, exposed.params()) {
                Ok(schema) => {
                    assert!(closed, "{key}: a schema for an open table");
                    methods.push((key, schema.to_json()));
                }
                Err(error) => {
                    assert!(!closed, "{key}: a closed table without a schema: {error}");
                }
            }
        }
    }
    let offered = exposure
        .assistant_offers()
        .into_iter()
        .map(|o| Json::Str(format!("{}.{}", o.model(), o.method()).into()))
        .collect();
    let mut values = Vec::new();
    for name in ["test_assistant.task", "test_orm.mixed"] {
        let model = registry.model(name).expect("the model exists");
        for (mode, label) in [
            (ValuesMode::Create, "create"),
            (ValuesMode::Update, "update"),
        ] {
            let (schema, excluded) = values_schema(model, mode, |_| true);
            let excluded = excluded
                .into_iter()
                .map(|(field, why)| (Box::from(field), Json::Str(format!("{why:?}").into())))
                .collect();
            values.push((
                format!("{name}.{label}").into(),
                Json::Object(vec![
                    ("schema".into(), schema.to_json()),
                    ("excluded".into(), Json::Object(excluded)),
                ]),
            ));
        }
    }
    Json::Object(vec![
        ("methods".into(), Json::Object(methods)),
        ("offered".into(), Json::Array(offered)),
        ("values".into(), Json::Object(values)),
    ])
}

/// Every object schema in `json` closes its properties, and no `$ref` appears.
fn assert_portable(json: &Json, at: &str) {
    match json {
        Json::Object(members) => {
            assert!(members.iter().all(|(k, _)| &**k != "$ref"), "{at}: a $ref");
            let is_object_schema = members
                .iter()
                .any(|(k, v)| &**k == "type" && *v == Json::Str("object".into()));
            if is_object_schema {
                assert!(
                    members
                        .iter()
                        .any(|(k, v)| &**k == "additionalProperties" && *v == Json::Bool(false)),
                    "{at}: an object schema without additionalProperties false"
                );
            }
            for (key, value) in members {
                assert_portable(value, &format!("{at}/{key}"));
            }
        }
        Json::Array(items) => {
            for (i, item) in items.iter().enumerate() {
                assert_portable(item, &format!("{at}/{i}"));
            }
        }
        _ => {}
    }
}

fn exposed_schema(orm: &Orm, model: &str, method: &str) -> ToolSchema {
    match orm.exposure().get(model_id(orm, model), method) {
        Some(Exposure::Exposed(e)) => params_schema(model, method, e.params()).unwrap(),
        other => panic!("{model}.{method}: {other:?}"),
    }
}

/// A JSON-2 body with its envelope keys (`ids`, `context`) taken off, as the dispatcher does
/// before it binds keyword arguments.
fn keyword_arguments(body: &str) -> Json {
    let Json::Object(members) = parse(body.as_bytes(), 32).unwrap() else {
        panic!("a body is an object");
    };
    Json::Object(
        members
            .into_iter()
            .filter(|(k, _)| &**k != "ids" && &**k != "context")
            .collect(),
    )
}

#[test]
fn tool_schemas_are_deterministic_and_pinned() {
    let first = canonical(&export(&orm(&test_addons())));
    let again = canonical(&export(&orm(&test_addons())));
    assert_eq!(first, again, "two exports of one registry differ");
    let mut reversed = test_addons();
    reversed.reverse();
    let other_order = canonical(&export(&orm(&reversed)));
    assert_eq!(first, other_order, "the addon order changed the export");
    // the opted-in and the not opted-in closed method both have a schema
    let text = String::from_utf8(first.clone()).unwrap();
    for key in [
        "\"test_assistant.task.plan\"",
        "\"test_assistant.task.rename\"",
        "\"test_rpc.effects.bump\"",
    ] {
        assert!(text.contains(key), "{key} missing from the export");
    }

    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join(SNAPSHOT);
    let mut expected_bytes = first;
    expected_bytes.push(b'\n');
    let pinned = std::fs::read(&path).unwrap_or_default();
    if pinned != expected_bytes {
        let actual = path.with_extension("json.actual");
        std::fs::write(&actual, &expected_bytes).unwrap();
        panic!(
            "the export differs from {SNAPSHOT}; the exporter wrote {} (see \
             tests/snapshots/README.md to regenerate)",
            actual.display()
        );
    }
}

#[test]
fn schemas_are_portable_and_accept_real_payloads() {
    let orm = orm(&test_addons());
    let export = export(&orm);
    assert_portable(&export, "");

    for (model, method, body) in [
        (
            "test_assistant.task",
            "plan",
            r#"{"ids": [1, 2], "context": {"lang": "en_US"},
                "domain": ["|", ["name", "ilike", "Ré"], "!", ["deadline", "in", ["2026-01-01", null]]],
                "labels": ["a", "ü"], "limit": null, "weight": 2, "urgent": false}"#,
        ),
        (
            "test_assistant.task",
            "plan",
            r#"{"domain": [], "labels": [], "limit": 5, "weight": 0.5, "urgent": true}"#,
        ),
        (
            "test_assistant.task",
            "set_priority",
            r#"{"ids": [7], "priority": "2", "note": null}"#,
        ),
        (
            "test_assistant.task",
            "set_priority",
            r#"{"priority": "2", "note": "x", "rank": -3}"#,
        ),
        (
            "test_assistant.task",
            "rename",
            r#"{"ids": [1], "name": "x"}"#,
        ),
        ("test_assistant.task", "purge_closed", r#"{"context": {}}"#),
        // bodies the JSON-2 tests send to the closed `test_rpc.effects` methods and the binder
        // accepts (rpc_dispatch, rpc_hardening, rpc_audit, rpc_tx, rpc_idempotency)
        ("test_rpc.effects", "bump", r#"{"name": "x"}"#),
        ("test_rpc.effects", "echo", r#"{"name": "é"}"#),
        (
            "test_rpc.effects",
            "echo",
            r#"{"name": "n", "limit": 3, "flag": true}"#,
        ),
        (
            "test_rpc.effects",
            "bad_session",
            r#"{"function": "set_config"}"#,
        ),
        (
            "test_rpc.effects",
            "bump_then_fail",
            r#"{"name": "doomed"}"#,
        ),
        (
            "test_rpc.effects",
            "slow_bump",
            r#"{"name": "late", "millis": 3000}"#,
        ),
        (
            "test_rpc.effects",
            "bump_big",
            r#"{"name": "big", "size": 1048576}"#,
        ),
        ("test_rpc.effects", "conflict_once", r#"{"name": "once"}"#),
        (
            "test_rpc.effects",
            "gated_bump",
            r#"{"name": "raced", "gate": 9009, "millis": 30000}"#,
        ),
    ] {
        let schema = exposed_schema(&orm, model, method);
        if let Err(violation) = validate(&schema, &keyword_arguments(body)) {
            panic!("{model}.{method} {body}: {violation}");
        }
    }

    // the bodies `rpc_dispatch` sends to `echo` that its binder refuses with 422: the schema
    // refuses them too
    let echo = exposed_schema(&orm, "test_rpc.effects", "echo");
    for (body, path) in [
        (r#"{"name": 5}"#, "$.name"),
        (r#"{"name": "n", "limit": 1.5}"#, "$.limit"),
    ] {
        let violation = validate(&echo, &parse(body.as_bytes(), 8).unwrap()).expect_err(body);
        assert_eq!(violation.path(), path, "{body}");
    }

    let plan = exposed_schema(&orm, "test_assistant.task", "plan");
    for (body, path, expected, got) in [
        (
            r#"{"domain": [], "labels": [], "weight": 1, "urgent": true, "ids": [1]}"#,
            "$.ids",
            "no such property",
            "array",
        ),
        (
            r#"{"labels": [], "weight": 1, "urgent": true}"#,
            "$.domain",
            "a value (required)",
            "nothing",
        ),
        (
            r#"{"domain": [], "labels": [1], "weight": 1, "urgent": true}"#,
            "$.labels[0]",
            "a string",
            "integer",
        ),
        (
            r#"{"domain": [], "labels": [], "limit": -1, "weight": 1, "urgent": true}"#,
            "$.limit",
            "an integer >= 0",
            "-1",
        ),
        (
            r#"{"domain": [["a", "="]], "labels": [], "weight": 1, "urgent": true}"#,
            "$.domain[0]",
            "at least 3 items",
            "2 items",
        ),
        (
            r#"{"domain": ["or"], "labels": [], "weight": 1, "urgent": true}"#,
            "$.domain[0]",
            "one of \"!\", \"&\", \"|\"",
            "\"or\"",
        ),
        (
            r#"{"domain": [], "labels": [], "weight": 1, "urgent": 1}"#,
            "$.urgent",
            "a boolean",
            "integer",
        ),
    ] {
        let violation = validate(&plan, &parse(body.as_bytes(), 32).unwrap()).expect_err(body);
        assert_eq!(
            (violation.path(), violation.expected(), violation.got()),
            (path, expected, got),
            "{body}"
        );
    }

    // a method with an open parameter: the export names model, method and parameter
    let search = match orm
        .exposure()
        .get(model_id(&orm, "test_assistant.task"), "search")
    {
        Some(Exposure::Exposed(e)) => e.params(),
        other => panic!("search: {other:?}"),
    };
    let error = params_schema("test_assistant.task", "search", search).unwrap_err();
    assert!(matches!(
        &error,
        SchemaExportError::Unsupported { model, method, param: "domain", reason: "no shape declared" }
            if &**model == "test_assistant.task" && &**method == "search"
    ));
    assert_eq!(
        error.to_string(),
        "test_assistant.task.search: parameter 'domain' has no closed schema (no shape declared)"
    );
}

