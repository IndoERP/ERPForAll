#[test]
fn only_opted_in_methods_are_offered() {
    let orm = orm(&test_addons());
    let task = model_id(&orm, "test_assistant.task");
    let exposure = orm.exposure();
    let offers: Vec<(&str, &str, Effect, Receiver)> = exposure
        .assistant_offers()
        .into_iter()
        .map(|o| (o.model(), o.method(), o.effect(), o.receiver()))
        .collect();
    assert_eq!(
        offers,
        [
            (
                "test_assistant.task",
                "plan",
                Effect::Write,
                Receiver::Records
            ),
            (
                "test_assistant.task",
                "purge_closed",
                Effect::Destructive,
                Receiver::Model
            ),
            (
                "test_assistant.task",
                "set_priority",
                Effect::Write,
                Receiver::Records
            ),
        ]
    );
    let offered = exposure.assistant_offered(task, "set_priority").unwrap();
    let params: Vec<(&str, bool)> = offered
        .params()
        .iter()
        .map(|p| (p.name(), p.required()))
        .collect();
    assert_eq!(
        params,
        [("priority", true), ("note", false), ("rank", false)]
    );
    // both write methods have closed tables; only the opted-in one is offered
    assert_eq!(
        exposure.assistant_offered(task, "rename").unwrap_err(),
        NotOffered::NotOptedIn
    );
    assert_eq!(
        exposure.assistant_offered(task, "search").unwrap_err(),
        NotOffered::NotOptedIn
    );
    assert_eq!(
        exposure.assistant_offered(task, "no_such").unwrap_err(),
        NotOffered::Unknown
    );
    let model_a = model_id(&orm, "test_rpc.model_a");
    assert_eq!(
        exposure
            .assistant_offered(model_a, "private_method")
            .unwrap_err(),
        NotOffered::NotExposed
    );
    let effects = model_id(&orm, "test_rpc.effects");
    assert_eq!(
        exposure.assistant_offered(effects, "notify").unwrap_err(),
        NotOffered::External
    );

    // an override without the opt-in withdraws the offer; one with it keeps it
    let orm = self::orm(&[
        &base_users::ADDON,
        &test_orm::ADDON,
        &test_assistant::ADDON,
        &test_assistant::overrides::ADDON,
    ]);
    let task = model_id(&orm, "test_assistant.task");
    let why = orm
        .exposure()
        .assistant_offered(task, "set_priority")
        .unwrap_err();
    assert_eq!(
        why,
        NotOffered::ChainOverrideWithoutOptIn {
            addon: "test_assistant_override"
        }
    );
    assert_eq!(
        why.to_string(),
        "addon 'test_assistant_override' implements it without offering it to the assistant"
    );
    let kept: Vec<&str> = orm
        .exposure()
        .assistant_offers()
        .into_iter()
        .map(|o| o.method())
        .collect();
    assert_eq!(kept, ["plan", "purge_closed"]);
}

