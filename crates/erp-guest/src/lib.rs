//! Guest side of the ERPForAll WASM addon contract (`wit/addon/`).
//!
//! An addon compiled to a `wasm32-wasip2` component links this crate. It gives the addon:
//!
//! - [`bindings`]: the types and imports `wit-bindgen` generates for the `addon` world, and the
//!   `export_addon!` macro that exports an implementation of the `addon-guest` interface;
//! - [`ColumnStore`]: a record batch the host sent or returned, checked once (every column holds one
//!   value per id) and read as typed slices without another call to the host;
//! - [`WriteBuffer`]: field assignments collected in the guest and sent as one set-based write per
//!   group of records;
//! - [`EpochCache`]: columns kept across calls only while the transaction's `cache-epoch` is
//!   unchanged;
//! - [`host`]: the `orm-host` imports with the guest-side checks of their answers.
//!
//! Every failure is a [`BoundaryError`] with a kind and a message; nothing is replaced by a
//! default. The macros build on these types; addon authors normally reach them
//! through `erp-sdk`.

/// Code generated by `wit-bindgen` from `wit/addon/` for the `addon` world.
///
/// The canonical-ABI glue in here is the only unsafe code of the crate (see `Cargo.toml`).
#[allow(
    unsafe_code,
    clippy::all,
    clippy::pedantic,
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic
)]
pub mod bindings {
    wit_bindgen::generate!({
        world: "addon",
        path: "../../wit/addon",
        pub_export_macro: true,
        export_macro_name: "export_addon",
        default_bindings_module: "erp_guest::bindings",
        additional_derives: [PartialEq],
    });
}

