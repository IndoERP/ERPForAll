/// The static description of an addon (name and dependencies), named by link roots.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct AddonDescriptor {
    /// The addon's technical name.
    pub name: &'static str,
    /// The addons it depends on.
    pub depends: &'static [&'static str],
    /// Exact-only numeric admission declared by this addon.
    pub exact_only: bool,
}

/// The class of a model declaration.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ModelKind {
    /// A regular model with a table.
    Regular,
    /// An abstract model (mixin): no table, no records.
    Abstract,
    /// A transient (wizard) model.
    Transient,
}

/// Macro token: only `#[model]` and `#[extend]` output can build one.
#[derive(Debug, Clone, Copy)]
pub struct Token {
    _private: (),
}

impl Token {
    /// For macro output only.
    #[doc(hidden)]
    pub const fn __macro() -> Self {
        Self { _private: () }
    }
}

/// A model known at compile time (generated by `#[model]`).
pub trait Model: 'static + Send + Sync {
    /// `_name`.
    const MODEL_NAME: &'static str;
    /// The model class kind.
    const KIND: ModelKind;
}

/// `M: Inherits<P>`: recordsets of `M` may use the fields and methods of `P` (`_inherit`).
pub trait Inherits<P: Model>: Model {
    /// Macro token; see [`Token`].
    #[doc(hidden)]
    const __TOKEN: Token;
}

/// The core `base` model every model inherits.
pub enum Base {}

impl Model for Base {
    const MODEL_NAME: &'static str = "base";
    const KIND: ModelKind = ModelKind::Abstract;
}

impl<M: Model> Inherits<Base> for M {
    const __TOKEN: Token = Token::__macro();
}

/// A typed handle to a field of model `M` holding values of type `T`.
